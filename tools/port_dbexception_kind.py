#!/usr/bin/env python3
"""Generate H2Sharp/Message/ErrorCodeKind.cs from org.h2.message.DbException.

DbException.getJdbcSQLException picks one of ten java.sql.SQLException subclasses,
first by error-code prefix (errorCode / 1000) and then by an explicit per-code list.
.NET has no equivalent hierarchy, so H2Sharp keeps exactly the same information as
a switch over the H2 error code. Transcribing the case labels mechanically means a
rebase cannot silently lose a code.

Run from the repository root:

    python tools/port_dbexception_kind.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "reference" / "h2" / "h2" / "src" / "main" / "org" / "h2" / "message" / "DbException.java"
DST = ROOT / "src" / "H2Sharp" / "Message" / "ErrorCodeKind.cs"

# Java constructor -> H2Sharp SqlExceptionKind member.
KIND_BY_CONSTRUCTOR = {
    "JdbcSQLException": "Unspecified",
    "JdbcSQLNonTransientException": "NonTransient",
    "JdbcSQLSyntaxErrorException": "SyntaxError",
    "JdbcSQLNonTransientConnectionException": "NonTransientConnection",
    "JdbcSQLDataException": "Data",
    "JdbcSQLIntegrityConstraintViolationException": "IntegrityConstraintViolation",
    "JdbcSQLInvalidAuthorizationSpecException": "InvalidAuthorizationSpec",
    "JdbcSQLTransactionRollbackException": "TransactionRollback",
    "JdbcSQLFeatureNotSupportedException": "FeatureNotSupported",
    "JdbcSQLTimeoutException": "Timeout",
    "JdbcSQLTransientException": "Transient",
}

HEADER = '''/*
 * Copyright 2004-2026 H2 Group.
 * Copyright 2026 H2Sharp contributors.
 * Ported from the two switches in org.h2.message.DbException.getJdbcSQLException.
 * Licensed under the MPL 2.0 or the EPL 1.0 (see LICENSE-H2.txt).
 * Modified: generated by tools/port_dbexception_kind.py. Java instantiates a
 * java.sql.SQLException subclass here; System.Data.Common.DbException has no such
 * hierarchy, so the same information is kept as a switch over the H2 error code.
 * The two-level structure (prefix, then explicit codes) is preserved verbatim.
 */
using H2Sharp.Api;

namespace H2Sharp.Message;

internal static class ErrorCodeKind
{
    /// <summary>
    /// The default bucket, matching the JdbcSQLException that H2 falls back to.
    /// </summary>
    private const SqlExceptionKind Default = SqlExceptionKind.Unspecified;

    /// <summary>
    /// Maps an H2 error code to the exception bucket H2 would have used.
    /// </summary>
    /// <param name="errorCode">the H2 error code</param>
    /// <returns>the exception bucket</returns>
    internal static SqlExceptionKind GetKind(int errorCode)
    {
        // Use SQLState class value to detect type
        switch (errorCode / 1_000)
        {
'''

FOOTER = '''        }

        // Default
        return Default;
    }
}
'''

NAMED_CASE_RE = re.compile(r"^\s*case ([A-Z0-9_]+):\s*$")
NUMERIC_CASE_RE = re.compile(r"^\s*case (\d+):\s*$")
RETURN_RE = re.compile(r"^\s*return new ([A-Za-z0-9_]+)\(")


def to_pascal(name: str) -> str:
    if name.startswith("_") and name.endswith("_"):
        return name
    return "".join(p[:1].upper() + p[1:].lower() for p in name.split("_") if p)


def main() -> int:
    if not SRC.exists():
        print(f"reference not found: {SRC}", file=sys.stderr)
        return 1

    lines = SRC.read_text(encoding="utf-8").splitlines()
    start = next(i for i, l in enumerate(lines)
                 if "static SQLException getJdbcSQLException(String message, String sql," in l)
    end = next(i for i, l in enumerate(lines[start:], start)
               if "private static String filterSQL" in l)
    body = lines[start:end]

    out: list[str] = []
    pending: list[str] = []
    explicit_count = 0
    prefix_count = 0
    i = 0
    seen_second_switch = False

    while i < len(body):
        line = body[i]

        if not seen_second_switch and "switch (errorCode)" in line:
            seen_second_switch = True
            # close the prefix switch before opening the explicit one
            out.append("        }")
            out.append("")
            out.append("        // Check error code")
            out.append("        switch (errorCode)")
            out.append("        {")
            i += 1
            continue

        if seen_second_switch and "switch (errorCode)" not in line and pending == [] \
                and "return new JdbcSQLException(" in line:
            break

        if not seen_second_switch:
            m = NUMERIC_CASE_RE.match(line)
            if m:
                # A prefix group may list several values sharing one return:
                #   case 7: case 21: case 42: case 54: return new JdbcSQLSyntaxError...
                group = [int(m.group(1))]
                j = i + 1
                while True:
                    nxt = NUMERIC_CASE_RE.match(body[j]) if j < len(body) else None
                    if nxt is None:
                        break
                    group.append(int(nxt.group(1)))
                    j += 1
                while j < len(body) and "return new" not in body[j]:
                    j += 1
                if j >= len(body):
                    raise SystemExit("ERROR: prefix case without a return")
                constructor = RETURN_RE.match(body[j])
                if constructor is None:
                    raise SystemExit("ERROR: unexpected return: " + body[j])
                kind = KIND_BY_CONSTRUCTOR[constructor.group(1)]
                for prefix in group:
                    out.append(f"            case {prefix}:")
                out.append(f"                return SqlExceptionKind.{kind};")
                out.append("")
                prefix_count += len(group)
                i = j + 1
                continue
            i += 1
            continue

        m = NAMED_CASE_RE.match(line)
        if m:
            pending.append(m.group(1))
            i += 1
            continue

        r = RETURN_RE.match(line)
        if r:
            kind = KIND_BY_CONSTRUCTOR[r.group(1)]
            for name in pending:
                out.append(f"            case ErrorCode.{to_pascal(name)}:")
            out.append(f"                return SqlExceptionKind.{kind};")
            out.append("")
            explicit_count += len(pending)
            pending = []
            i += 1
            continue

        i += 1

    if pending:
        raise SystemExit("ERROR: unterminated case list")

    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text(HEADER + "\n".join(out) + FOOTER, encoding="utf-8", newline="\n")
    print(f"wrote {DST}: {prefix_count} prefixes, {explicit_count} explicitly listed codes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())