#!/usr/bin/env python3
"""Generate H2Sharp/Util/ParserUtil.cs from org.h2.util.ParserUtil.

ParserUtil is ~380 sorted token constants plus a map from token text to token type,
and four methods. The constants are referenced by the parser we have not ported yet, so
their values are part of the contract and must match the reference exactly; transcribing
them by hand is exactly the kind of task where a single off-by-one silently changes which
SQL word is a keyword.

The Java class builds its lookup with a HashMap<String, Integer>. The C# port uses a
FrozenDictionary with StringComparer.Ordinal, which is the same equality semantics
(Java compares UTF-16 code units through String.equals) without the per-lookup
allocation, and is built once at type initialisation.

Run:  python tools/port_parserutil.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "reference" / "h2" / "h2" / "src" / "main" / "org" / "h2" / "util" / "ParserUtil.java"
DST = ROOT / "src" / "H2Sharp" / "Util" / "ParserUtil.cs"

INDENT = "    "

# public static final int NAME = EXPR;   with the preceding javadoc
CONST_RE = re.compile(r"public static final int (\w+) = ([^;]+);")
TOKEN_DOC_RE = re.compile(r'The token "([^"]+)"')
PUT_RE = re.compile(r'map\.put\("([^"]+)", (\w+)\);')
IDENT_RE = re.compile(r"\b[A-Z][A-Z0-9_]*\b")


def to_pascal(name: str) -> str:
    """SNAKE_CASE -> PascalCase; _ROWID_ keeps its underscores, as elsewhere."""
    if name.startswith("_") and name.endswith("_"):
        return name
    return "".join(p[:1].upper() + p[1:].lower() for p in name.split("_") if p)


def translate_expression(expr: str) -> str:
    """Rewrite the Java identifiers inside a constant expression to their C# names.

    The values are a contract and are kept as written in the reference (ALL = IDENTIFIER
    + 1 and so on) so the ordering stays visible and reviewable, rather than being folded
    into bare integers.
    """
    return IDENT_RE.sub(lambda m: to_pascal(m.group(0)), expr)


def javadoc_summary(lines: list[str], index: int) -> tuple[str, str]:
    """The javadoc above line `index` as (token_text, summary).

    Token constants are documented as `The token "ALL".`, which is also the text the
    lookup table is keyed by. The two leading constants have prose instead, so the first
    sentence of their javadoc is used as the summary.
    """
    block: list[str] = []
    for back in range(index - 1, max(index - 8, 0) - 1, -1):
        line = lines[back].strip()
        if line.startswith("/**"):
            block.insert(0, line.lstrip("/").lstrip("*").strip())
            continue
        if line.startswith("*") or line.startswith("//"):
            block.insert(0, line.lstrip("/").lstrip("*").strip())
            continue
        if line.endswith("*/"):
            continue
        break

    for entry in block:
        token = TOKEN_DOC_RE.search(entry)
        if token:
            return token.group(1), entry

    summary = next((entry for entry in block if entry), "")
    return "", summary or "Token."


def parse(source: str) -> tuple[list[tuple[str, str, str, str]], list[tuple[str, str]]]:
    lines = source.splitlines()

    constants: list[tuple[str, str, str, str]] = []
    for index, line in enumerate(lines):
        match = CONST_RE.search(line)
        if not match:
            continue
        name, expr = match.group(1), match.group(2).strip()
        token, summary = javadoc_summary(lines, index)
        constants.append((name, expr, token, summary))

    puts = PUT_RE.findall(source)
    return constants, puts


HEADER = '''/*
 * Copyright 2004-2026 H2 Group.
 * Copyright 2026 H2Sharp contributors.
 * Ported from org.h2.util.ParserUtil.
 * Licensed under the MPL 2.0 or the EPL 1.0 (see LICENSE-H2.txt).
 * Modified: generated by tools/port_parserutil.py; do not edit by hand.
 *
 * The token values are a contract, not an implementation detail: the parser switches on
 * them and they are compared against values stored in H2 metadata, so they are
 * transcribed from the reference rather than renumbered.
 */
using System;
using System.Collections.Frozen;
using System.Collections.Generic;
using System.Text;

namespace H2Sharp.Util;

/// <summary>
/// Token constants and keyword lookup.
/// </summary>
public static partial class ParserUtil
{'''

FOOTER = '''
    /// <summary>
    /// The token text to token type, with <see cref="StringComparer.Ordinal"/> equality.
    /// A frozen dictionary because it is built once and then only read: it keeps the
    /// lookup allocation free without a lazy initialisation check on every call.
    /// </summary>
    private static readonly FrozenDictionary<string, int> Keywords = new Dictionary<string, int>(StringComparer.Ordinal)
    {
%(entries)s
    }.ToFrozenDictionary(StringComparer.Ordinal);
}
'''


def main() -> int:
    if not SRC.is_file():
        print(f"ERROR: reference source not found: {SRC}", file=sys.stderr)
        return 1

    constants, puts = parse(SRC.read_text(encoding="utf-8"))
    if not constants or not puts:
        print("ERROR: parsed nothing; the reference layout changed", file=sys.stderr)
        return 1

    values = {name: expr for name, expr, _, _ in constants}

    out: list[str] = [HEADER, ""]
    for name, expr, token, summary in constants:
        out.append(f"{INDENT}/// <summary>")
        out.append(f"{INDENT}/// {summary}")
        out.append(f"{INDENT}/// </summary>")
        out.append(f"{INDENT}public const int {to_pascal(name)} = {translate_expression(expr)};")
        out.append("")

    entries = []
    for token, target in puts:
        if target not in values:
            print(f"ERROR: map entry {token!r} references unknown constant {target}",
                  file=sys.stderr)
            return 1
        entries.append(f"{INDENT*2}[\"{token}\"] = {to_pascal(target)},")

    body = "\n".join(out) + (FOOTER % {"entries": "\n".join(entries)})
    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text(body, encoding="utf-8", newline="\n")
    print(f"wrote {DST}: {len(constants)} constants and {len(puts)} keyword entries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
