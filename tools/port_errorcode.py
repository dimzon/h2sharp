CONST_RE = re.compile(r"^\s*public static final int ([A-Z0-9_]+) = ([^;]+);$")


def to_pascal(name: str) -> str:
    """SNAKE_CASE -> PascalCase; _ROWID_ keeps its underscores."""
    if name.startswith("_") and name.endswith("_"):
        return name
    parts = name.split("_")
    return "".join(p[:1].upper() + p[1:].lower() for p in parts if p)


def unescape(text: str) -> str:
    return (text.replace("&lt;", "<")
                .replace("&gt;", ">")
                .replace("&amp;", "&"))


def strip_javadoc(body: list[str]) -> list[str]:
    """Turn Javadoc body lines into plain text lines, without decoration."""
    text: list[str] = []
    for line in body:
        s = line.strip()
        if s.endswith("*/"):
            s = s[:-2]
        if s.startswith("/**"):
            s = s[3:]
        s = s.lstrip("*")
        text.append(unescape(s.strip()))
    while text and not text[0]:
        text.pop(0)
    while text and not text[-1]:
        text.pop()
    return text


def render(lines: list[str]) -> list[str]:
    """Render text lines as /// comments, mapping <pre> to <code>."""
    out: list[str] = []
    in_code = False
    for s in lines:
        if s == "<pre>":
            in_code = True
            out.append(INDENT + "/// <code>")
            continue
        if s == "</pre>":
            in_code = False
            out.append(INDENT + "/// </code>")
            continue
        out.append((INDENT + "/// " + s) if s else (INDENT + "///"))
    if in_code:
        out.append(INDENT + "/// </code>")
    return out


from typing import Callable


def convert_doc(block: list[str], rename: Callable[[str], str]) -> list[str]:
    """Convert one Javadoc block into XML documentation lines."""
    body: list[str] = []
    tags: list[tuple[str, str]] = []
    current: list[str] | None = None

    for raw in strip_javadoc(block):
        raw = rename(raw)
        m = re.match(r"^@(\w+)\s*(.*)$", raw)
        if m:
            current = []
            tags.append((m.group(1), m.group(2)))
        elif current is None:
            body.append(raw)
        else:
            current.append(raw)

    out = [INDENT + "/// <summary>"]
    summary = render(body)
    out.extend(summary if summary else [INDENT + "///"])
    out.append(INDENT + "/// </summary>")

    for kind, rest in tags:
        if kind == "param":
            m = re.match(r"^(\S+)\s*(.*)$", rest, flags=re.S)
            name = m.group(1) if m else rest
            desc_text = strip_javadoc(m.group(2).splitlines()) if m else []
            out.append(f'{INDENT}/// <param name="{name}">')
            out.extend(render(desc_text) or [INDENT + "///"])
            out.append(INDENT + "/// </param>")
        elif kind == "return":
            out.append(INDENT + "/// <returns>")
            out.extend(render(strip_javadoc(rest.splitlines())) or [INDENT + "///"])
            out.append(INDENT + "/// </returns>")
        elif kind == "throws":
            parts = rest.split(None, 1)
            type_name = parts[0] if parts else "Exception"
            desc_text = strip_javadoc(parts[1].splitlines()) if len(parts) > 1 else []
            out.append(f'{INDENT}/// <exception cref="{type_name}">')
            out.extend(render(desc_text) or [INDENT + "///"])
            out.append(INDENT + "/// </exception>")
        else:
            out.extend(render([rest]))

    return out


def main() -> int:
    if not SRC.exists():
        print(f"reference not found: {SRC}", file=sys.stderr)
        return 1

    lines = SRC.read_text(encoding="utf-8").splitlines()
    body_start = next(i for i, l in enumerate(lines) if l.startswith("public class ErrorCode"))
    body_end = next(
        (i for i, l in enumerate(lines[body_start:], body_start)
         if "public static boolean isCommon" in l),
        len(lines),
    )

    # Some constants alias another constant; rewrite references to the new names.
    names = [
        match.group(1)
        for match in (CONST_RE.match(line) for line in lines)
        if match is not None
    ]
    name_map = {name: to_pascal(name) for name in names}
    alias_re = re.compile(r"\b(" + "|".join(sorted(map(re.escape, names), key=len, reverse=True)) + r")\b")

    def rename_refs(text: str) -> str:
        return alias_re.sub(lambda m: name_map[m.group(1)], text)

    result: list[str] = []
    emitted: list[str] = []
    doc: list[str] | None = None
    i = body_start
    while i < body_end:
        line = lines[i]
        stripped = line.strip()
        if stripped.startswith("/**"):
            doc = [stripped]
            i += 1
            while i < body_end and not lines[i].strip().startswith("*/"):
                doc.append(lines[i])
                i += 1
            if i < body_end:
                doc.append(lines[i])
                i += 1
            continue

        m = CONST_RE.match(line)
        if m:
            name, value = m.group(1), rename_refs(m.group(2).strip())
            result.extend(convert_doc(doc or [], rename_refs))
            result.append(INDENT + f"public const int {name_map[name]} = {value};")
            result.append("")
            emitted.append(name)
            doc = None
            i += 1
            continue
        i += 1

    missing = sorted(set(names) - set(emitted))
    if missing:
        print(f"ERROR: {len(missing)} constants not emitted: {missing}", file=sys.stderr)
        return 1

    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text(HEADER + "\n".join(result).rstrip("\n") + "\n" + FOOTER,
                   encoding="utf-8", newline="\n")
    print(f"wrote {DST} with {len(emitted)} constants")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())