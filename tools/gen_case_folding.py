#!/usr/bin/env python3
"""Generate H2Sharp/Util/CaseFolding.cs.

java.lang.String.toUpperCase/toLowerCase use the Unicode *full* case mapping, while
System.String.ToUpperInvariant/ToLowerInvariant use the *simple* 1:1 mapping. They
therefore disagree: Java maps ß to "SS" and İ to "i" plus a combining dot above, and
it maps ı to I where .NET leaves it alone.

Rather than reason about the Unicode SpecialCasing table, this generates the exact set
of code points where Java and .NET disagree, by reading a table produced by the
reference JVM (see tools/DumpCaseTable.java) and probing .NET for each code point.

Run:

    java -cp tools/out DumpCaseTable > case-java.tsv
    dotnet run --project tools/CaseProbe > case-dotnet.tsv
    python tools/gen_case_folding.py case.tsv case-dotnet.tsv

Only the differing entries end up in the generated file, which is therefore small.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DST = ROOT / "src" / "H2Sharp" / "Util" / "CaseFolding.cs"

HEADER = '''/*
 * Copyright 2026 H2Sharp contributors.
 * Ported from none (new file for H2Sharp).
 * Licensed under the MPL 2.0 or the EPL 1.0 (see LICENSE-H2.txt).
 *
 * Modified: generated by tools/gen_case_folding.py.
 *
 * Why this file exists: java.lang.String.toUpperCase/toLowerCase apply the Unicode
 * *full* case mapping, while System.String.ToUpperInvariant/ToLowerInvariant apply the
 * *simple* 1:1 mapping. The two disagree in ways that are visible to users, for
 * example:
 *
 *   "ß".ToUpperInvariant()   -> "ß"      (Java: "SS")
 *   "İ".ToLowerInvariant()   -> "ı"      (Java: "i" + U+0307)
 *   "ı".ToUpperInvariant()   -> "ı"      (Java: "I")
 *
 * H2Sharp.ToUpperEnglish/ToLowerEnglish must behave like Java's English-locale case
 * mapping, so the differing code points are tabulated here and applied on top of the
 * invariant mapping. The table is verified against the reference JVM by
 * StringUtilsOracleTests.ToUpperAndLowerEnglish_MatchReferenceJvm.
 *
 * The locale-conditional entries of SpecialCasing.txt (Turkish, Azeri, Lithuanian and
 * Greek) are deliberately absent: Java uses Locale.ENGLISH, so they never apply.
 */
using System;
using System.Collections.Generic;

namespace H2Sharp.Util;

/// <summary>
/// The code points where Java's English-locale case mapping differs from .NET's
/// invariant mapping. Generated; do not edit by hand.
/// </summary>
internal static class CaseFolding
{
    /// <summary>
    /// Maps a code point to its full uppercase expansion, when it differs from the
    /// invariant mapping.
    /// </summary>
    internal static readonly Dictionary<int, string> UpperTable = new()
    {
'''

LOWER_MARKER = '''    };

    /// <summary>
    /// Maps a code point to its full lowercase expansion, when it differs from the
    /// invariant mapping.
    /// </summary>
    internal static readonly Dictionary<int, string> LowerTable = new()
    {
'''

TAIL = '''

    };

    /// <summary>
    /// Returns the uppercase expansion of a code point, or null when the invariant
    /// mapping already matches Java.
    /// </summary>
    internal static string? Upper(int codePoint)
        => UpperTable.TryGetValue(codePoint, out string? value) ? value : null;

    /// <summary>
    /// Returns the lowercase expansion of a code point, or null when the invariant
    /// mapping already matches Java.
    /// </summary>
    internal static string? Lower(int codePoint)
        => LowerTable.TryGetValue(codePoint, out string? value) ? value : null;
}
'''


def parse_hex(text: str) -> int:
    return int(text, 16)


def parse_seq(text: str) -> list[int]:
    if not text:
        return []
    return [parse_hex(p) for p in text.split("+")]


def format_seq(points: list[int]) -> str:
    """Renders the expansion as a C# string literal holding the real characters."""
    out: list[str] = ['"']
    for p in points:
        if p > 0xFFFF:
            v = p - 0x10000
            out.append("\\u" + f"{0xD800 + (v >> 10):04x}")
            out.append("\\u" + f"{0xDC00 + (v & 0x3FF):04x}")
        elif p < 0x20 or p in (0x22, 0x5C) or (0xD800 <= p <= 0xDFFF):
            out.append("\\u" + f"{p:04x}")
        else:
            out.append(chr(p))
    out.append('"')
    return "".join(out)


def build(rows: list[tuple[int, list[int]]]) -> list[str]:
    return [
        f"        [0x{code_point:04x}] = {format_seq(expansion)},"
        for code_point, expansion in sorted(rows)
    ]


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2

    java_rows = pathlib.Path(sys.argv[1]).read_text(encoding="ascii").splitlines()
    dotnet_rows = pathlib.Path(sys.argv[2]).read_text(encoding="ascii").splitlines()

    # java.tsv: codePoint, fullUpper, fullLower  (only where full != simple)
    java: dict[int, tuple[list[int], list[int]]] = {}
    for line in java_rows:
        if not line.strip():
            continue
        cp, full_upper, full_lower = line.split("\t")
        java[int(cp, 16)] = (parse_seq(full_upper), parse_seq(full_lower))

    # dotnet.tsv lists only the code points whose .NET mapping is not the identity,
    # so a code point missing from it means .NET leaves it alone.
    dotnet: dict[int, tuple[list[int], list[int]]] = {}
    for line in dotnet_rows:
        if not line.strip():
            continue
        cp, inv_upper, inv_lower = line.split("\t")
        code_point = int(cp, 16)
        dotnet[code_point] = (parse_seq(inv_upper), parse_seq(inv_lower))

    upper_rows: list[tuple[int, list[int]]] = []
    lower_rows: list[tuple[int, list[int]]] = []
    for code_point, (full_upper, full_lower) in java.items():
        inv_upper, inv_lower = dotnet.get(code_point, ([code_point], [code_point]))
        if full_upper != inv_upper:
            upper_rows.append((code_point, full_upper))
        if full_lower != inv_lower:
            lower_rows.append((code_point, full_lower))

    body = [
        HEADER,
        *build(upper_rows),
        LOWER_MARKER,
        *build(lower_rows),
        TAIL,
    ]

    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text("\n".join(body), encoding="utf-8", newline="\n")
    print(f"wrote {DST}: {len(upper_rows)} upper and {len(lower_rows)} lower overrides")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())