// Modified (API): JDBC statements are ADO.NET commands; a failed query is a reader that
// never opens. DATABASE_TO_UPPER is always true in this port, so the reference's
// DATABASE_TO_UPPER=FALSE candidate scenarios are replaced by the default upper-folding
// and quoted-name cases. The reference's main() entry is the runner; xUnit runs Test().
using Xunit;

namespace H2Sharp.Native.Tests.Db;

/// <summary>
/// Tests the error message of a select from a table that is not found.
/// </summary>
public sealed class TestSelectTableNotFound : TestDb
{
    /// <summary>
    /// Run just this test.
    /// </summary>
    [H2Fact]
    public override void Test()
    {
        TestWithoutAnyCandidate();
        TestUnquotedNameFoldsToUpper();
        TestQuotedNameKeepsCase();
        TestWithSchema();
        TestWithSchemaSearchPath();
        TestWhenSchemaIsEmpty();
        TestWithSchemaWhenSchemaIsEmpty();
        TestWithSchemaSearchPathWhenSchemaIsEmpty();
    }

    private void TestWithoutAnyCandidate()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnection(GetTestName());
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE T2 ( ID INT GENERATED BY DEFAULT AS IDENTITY )");
        try
        {
            Query(stat, "SELECT 1 FROM t1");
            Fail("Table `t1` was accessible but should not have been.");
        }
        catch (DbException e)
        {
            AssertContains(e.Message ?? "", "Table \"T1\" not found");
        }

    }

    private void TestUnquotedNameFoldsToUpper()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnection(GetTestName());
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE T1 ( ID INT GENERATED BY DEFAULT AS IDENTITY )");
        Query(stat, "SELECT 1 FROM t1");
    }

    private void TestQuotedNameKeepsCase()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnection(GetTestName());
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE \"t1\" ( ID INT GENERATED BY DEFAULT AS IDENTITY )");
        try
        {
            Query(stat, "SELECT 1 FROM t1");
            Fail("Quoted lower-case table was accessible through an unquoted name.");
        }
        catch (DbException e)
        {
            AssertContains(e.Message ?? "", "Table \"T1\" not found");
        }

    }

    private void TestWithSchema()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnection(GetTestName());
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE T1 ( ID INT GENERATED BY DEFAULT AS IDENTITY )");
        Query(stat, "SELECT 1 FROM PUBLIC.t1");
    }

    private void TestWithSchemaSearchPath()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnection(GetTestName());
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "SET SCHEMA_SEARCH_PATH PUBLIC");
        Execute(stat, "CREATE TABLE T1 ( ID INT GENERATED BY DEFAULT AS IDENTITY )");
        Query(stat, "SELECT 1 FROM t1");
    }

    private void TestWhenSchemaIsEmpty()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnection(GetTestName());
        DbCommand stat = conn.CreateCommand();
        try
        {
            Query(stat, "SELECT 1 FROM t1");
            Fail("Table `t1` was accessible but should not have been.");
        }
        catch (DbException e)
        {
            AssertContains(e.Message ?? "", "Table \"T1\" not found (this database is empty)");
        }

    }

    private void TestWithSchemaWhenSchemaIsEmpty()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnection(GetTestName());
        DbCommand stat = conn.CreateCommand();
        try
        {
            Query(stat, "SELECT 1 FROM PUBLIC.t1");
            Fail("Table `t1` was accessible but should not have been.");
        }
        catch (DbException e)
        {
            AssertContains(e.Message ?? "", "Table \"T1\" not found (this database is empty)");
        }

    }

    private void TestWithSchemaSearchPathWhenSchemaIsEmpty()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnection(GetTestName());
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "SET SCHEMA_SEARCH_PATH PUBLIC");
        try
        {
            Query(stat, "SELECT 1 FROM t1");
            Fail("Table `t1` was accessible but should not have been.");
        }
        catch (DbException e)
        {
            AssertContains(e.Message ?? "", "Table \"T1\" not found (this database is empty)");
        }

    }

    /// <summary>
    /// The reference's stat.executeQuery(sql); the rows are read and dropped.
    /// </summary>
    private static void Query(DbCommand stat, string sql)
    {
        stat.CommandText = sql;
        using DbDataReader rs = stat.ExecuteReader();
        while (rs.Read())
        {
            // just loop
        }
    }
}
