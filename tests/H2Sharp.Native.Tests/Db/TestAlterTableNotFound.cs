using Xunit;

namespace H2Sharp.Native.Tests.Db;

/// <summary>
/// Tests the error message of ALTER TABLE on a table that is not found: the message
/// names the table as written and offers the candidates the identifier settings allow.
/// </summary>
public sealed class TestAlterTableNotFound : TestDb
{
    /// <summary>
    /// Run just this test.
    /// </summary>
    [H2Fact]
    public override void Test()
    {
        TestWithoutAnyCandidate();
        TestWithoutAnyCandidateWhenDatabaseToLower();
        TestWithoutAnyCandidateWhenDatabaseToUpper();
        TestWithoutAnyCandidateWhenCaseInsensitiveIdentifiers();
        TestWithOneCandidate();
        TestWithOneCandidateWhenDatabaseToLower();
        TestWithOneCandidateWhenDatabaseToUpper();
        TestWithOneCandidateWhenCaseInsensitiveIdentifiers();
        TestWithTwoCandidates();
    }

    private void TestWithoutAnyCandidate()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnectionWithSettings("DATABASE_TO_UPPER=FALSE");
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE T2 ( ID INT GENERATED BY DEFAULT AS IDENTITY )");
        try
        {
            Execute(stat, "ALTER TABLE t1 DROP COLUMN ID");
            Fail("Table `t1` was accessible but should not have been.");
        }
        catch (DbException e)
        {
            AssertContains(e.Message ?? "", "Table \"t1\" not found;");
        }

        DeleteDb(GetTestName());
    }

    private void TestWithoutAnyCandidateWhenDatabaseToLower()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnectionWithSettings("DATABASE_TO_LOWER=TRUE");
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE T2 ( ID INT GENERATED BY DEFAULT AS IDENTITY )");
        try
        {
            Execute(stat, "ALTER TABLE T1 DROP COLUMN ID");
            Fail("Table `t1` was accessible but should not have been.");
        }
        catch (DbException e)
        {
            AssertContains(e.Message ?? "", "Table \"t1\" not found;");
        }

        DeleteDb(GetTestName());
    }

    private void TestWithoutAnyCandidateWhenDatabaseToUpper()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnectionWithSettings("DATABASE_TO_LOWER=FALSE;DATABASE_TO_UPPER=TRUE");
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE T2 ( ID INT GENERATED BY DEFAULT AS IDENTITY )");
        try
        {
            Execute(stat, "ALTER TABLE t1 DROP COLUMN ID");
            Fail("Table `T1` was accessible but should not have been.");
        }
        catch (DbException e)
        {
            AssertContains(e.Message ?? "", "Table \"T1\" not found;");
        }

        DeleteDb(GetTestName());
    }

    private void TestWithoutAnyCandidateWhenCaseInsensitiveIdentifiers()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnectionWithSettings("DATABASE_TO_UPPER=FALSE;CASE_INSENSITIVE_IDENTIFIERS=TRUE");
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE T2 ( ID INT GENERATED BY DEFAULT AS IDENTITY )");
        try
        {
            Execute(stat, "ALTER TABLE t1 DROP COLUMN ID");
            Fail("Table `t1` was accessible but should not have been.");
        }
        catch (DbException e)
        {
            AssertContains(e.Message ?? "", "Table \"t1\" not found;");
        }

        DeleteDb(GetTestName());
    }

    private void TestWithOneCandidate()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnectionWithSettings("DATABASE_TO_UPPER=FALSE");
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE T1 ( ID INT GENERATED BY DEFAULT AS IDENTITY )");
        try
        {
            Execute(stat, "ALTER TABLE t1 DROP COLUMN ID");
            Fail("Table `t1` was accessible but should not have been.");
        }
        catch (DbException e)
        {
            AssertContains(e.Message ?? "", "Table \"t1\" not found (candidates are: \"T1\")");
        }

        DeleteDb(GetTestName());
    }

    private void TestWithOneCandidateWhenDatabaseToLower()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnectionWithSettings("DATABASE_TO_LOWER=TRUE");
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE t1 ( ID INT GENERATED BY DEFAULT AS IDENTITY, PAYLOAD INT )");
        Execute(stat, "ALTER TABLE T1 DROP COLUMN PAYLOAD");
        DeleteDb(GetTestName());
    }

    private void TestWithOneCandidateWhenDatabaseToUpper()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnectionWithSettings("DATABASE_TO_UPPER=TRUE");
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE T1 ( ID INT GENERATED BY DEFAULT AS IDENTITY, PAYLOAD INT )");
        Execute(stat, "ALTER TABLE t1 DROP COLUMN PAYLOAD");
        DeleteDb(GetTestName());
    }

    private void TestWithOneCandidateWhenCaseInsensitiveIdentifiers()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnectionWithSettings("DATABASE_TO_UPPER=FALSE;CASE_INSENSITIVE_IDENTIFIERS=TRUE");
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE T1 ( ID INT GENERATED BY DEFAULT AS IDENTITY, PAYLOAD INT )");
        Execute(stat, "ALTER TABLE t1 DROP COLUMN PAYLOAD");
        DeleteDb(GetTestName());
    }

    private void TestWithTwoCandidates()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnectionWithSettings("DATABASE_TO_UPPER=FALSE");
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE Toast ( ID INT GENERATED BY DEFAULT AS IDENTITY )");
        Execute(stat, "CREATE TABLE TOAST ( ID INT GENERATED BY DEFAULT AS IDENTITY )");
        try
        {
            Execute(stat, "ALTER TABLE toast DROP COLUMN ID");
            Fail("Table `toast` was accessible but should not have been.");
        }
        catch (DbException e)
        {
            AssertContains(e.Message ?? "", "Table \"toast\" not found (candidates are: \"TOAST, Toast\")");
        }

        DeleteDb(GetTestName());
    }

    private DbConnection GetConnectionWithSettings(string settings)
    {
        return GetConnection(GetTestName() + ";" + settings);
    }
}
