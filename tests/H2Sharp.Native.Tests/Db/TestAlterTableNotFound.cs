using Xunit;

namespace H2Sharp.Native.Tests.Db;

/// <summary>
/// Tests ALTER TABLE against a table that is not found.
/// </summary>
public sealed class TestAlterTableNotFound : TestDb
{
    /// <summary>
    /// Run just this test.
    /// </summary>
    [H2Fact]
    public override void Test()
    {
        TestWithoutAnyCandidate();
        TestWithoutAnyCandidateWhenCaseInsensitiveIdentifiers();
        TestUnquotedNameFoldsToUpper();
        TestCaseInsensitiveFindsQuotedName();
    }

    private void TestWithoutAnyCandidate()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnection(GetTestName());
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE T2 ( ID INT GENERATED BY DEFAULT AS IDENTITY )");
        try
        {
            Execute(stat, "ALTER TABLE t1 DROP COLUMN ID");
            Fail("Table `t1` was accessible but should not have been.");
        }
        catch (DbException e)
        {
            AssertContains(e.Message ?? "", "Table \"T1\" not found");
        }

    }

    private void TestWithoutAnyCandidateWhenCaseInsensitiveIdentifiers()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnection(GetTestName()
            + ";CASE_INSENSITIVE_IDENTIFIERS=TRUE");
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE T2 ( ID INT GENERATED BY DEFAULT AS IDENTITY )");
        try
        {
            Execute(stat, "ALTER TABLE t1 DROP COLUMN ID");
            Fail("Table `t1` was accessible but should not have been.");
        }
        catch (DbException e)
        {
            AssertContains(e.Message ?? "", "Table \"T1\" not found");
        }

    }

    private void TestUnquotedNameFoldsToUpper()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnection(GetTestName());
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE T1 ( ID INT GENERATED BY DEFAULT AS IDENTITY, PAYLOAD INT )");
        Execute(stat, "ALTER TABLE t1 DROP COLUMN PAYLOAD");
    }

    private void TestCaseInsensitiveFindsQuotedName()
    {
        DeleteDb(GetTestName());
        using DbConnection conn = GetConnection(GetTestName()
            + ";CASE_INSENSITIVE_IDENTIFIERS=TRUE");
        DbCommand stat = conn.CreateCommand();
        Execute(stat, "CREATE TABLE \"MixedCase\" ( ID INT GENERATED BY DEFAULT AS IDENTITY, PAYLOAD INT )");
        Execute(stat, "ALTER TABLE mixedcase DROP COLUMN payload");
    }
}
