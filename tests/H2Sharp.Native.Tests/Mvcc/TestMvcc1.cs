// Modified (API): JDBC statements/result sets are ADO.NET commands/readers;
// setAutoCommit(false) is an explicit transaction that each command carries, and
// commit()/rollback() are that transaction's Commit/Rollback followed by a fresh
// transaction, because the reference's autocommit-off session starts the next one
// implicitly. The reference's main() entry is the runner; xUnit runs Test() directly.
using H2Sharp.Api;
using Xunit;

namespace H2Sharp.Native.Tests.Mvcc;

/// <summary>
/// Basic MVCC (multi version concurrency) test cases.
/// </summary>
public sealed class TestMvcc1 : TestDb
{
    private DbConnection c1 = null!, c2 = null!;

    private DbCommand s1 = null!, s2 = null!;

    private DbTransaction t1 = null!, t2 = null!;

    /// <summary>
    /// Run just this test.
    /// </summary>
    [H2Fact]
    public override void Test()
    {
        TestCases();
        DeleteDb("mvcc1");
    }

    private void TestCases()
    {
        // TODO Prio 1: document: exclusive table lock still used when altering
        // tables, adding indexes, select ... for update; table level locks are
        // checked
        // TODO Prio 2: if MVCC is used, rows of transactions need to fit in
        // memory
        // TODO Prio 2: getFirst / getLast in MultiVersionIndex
        // TODO Prio 2: snapshot isolation (currently read-committed, not
        // repeatable read)

        // TODO test: one thread appends, the other
        //     selects new data (select * from test where id > ?) and deletes

        DeleteDb("mvcc1");
        c1 = GetConnection("mvcc1;LOCK_TIMEOUT=10");
        s1 = c1.CreateCommand();
        c2 = GetConnection("mvcc1;LOCK_TIMEOUT=10");
        s2 = c2.CreateCommand();
        Begin1();
        Begin2();

        try
        {
            // table rollback problem
            AssertThrows(ErrorCode.ColumnNotFound1, s1,
                "create table b(primary key(x))");
            Execute(s1, "create table a(id int as 1 unique)");
            Execute(s1, "drop table a");

            // update same key problem
            Execute(s1, "CREATE TABLE TEST(ID INT, NAME VARCHAR, PRIMARY KEY(ID))");
            Execute(s1, "INSERT INTO TEST VALUES(1, 'Hello')");
            Commit1();
            AssertResult("Hello", s2, "SELECT NAME FROM TEST WHERE ID=1");
            Execute(s1, "UPDATE TEST SET NAME = 'Hallo' WHERE ID=1");
            AssertResult("Hello", s2, "SELECT NAME FROM TEST WHERE ID=1");
            AssertResult("Hallo", s1, "SELECT NAME FROM TEST WHERE ID=1");
            Execute(s1, "DROP TABLE TEST");
            Commit1();
            Commit2();

            // referential integrity problem
            Execute(s1, "create table a (id integer generated by default as identity, "
                + "code varchar(10) not null, primary key(id))");
            Execute(s1, "create table b (name varchar(100) not null, a integer, "
                + "primary key(name), foreign key(a) references a(id))");
            Execute(s1, "insert into a(code) values('one')");
            AssertThrows(ErrorCode.ReferentialIntegrityViolatedParentMissing1, s2,
                "insert into b values('un B', 1)");
            Commit2();
            Rollback1();
            Execute(s1, "drop table a");
            Execute(s1, "drop table b");
            Commit2();

            // it should not be possible to drop a table
            // when an uncommitted transaction changed something
            Execute(s1, "create table test(id int primary key)");
            Execute(s1, "insert into test values(1)");
            AssertThrows(ErrorCode.LockTimeout1, s2, "drop table test");
            Rollback1();
            Execute(s2, "drop table test");
            Rollback2();

            // table scan problem
            Execute(s1, "create table test(id int, name varchar)");
            Execute(s1, "insert into test values(1, 'A'), (2, 'B')");
            Commit1();
            AssertResult("2", s1, "select count(*) from test where name<>'C'");
            Execute(s2, "update test set name='B2' where id=2");
            AssertResult("2", s1, "select count(*) from test where name<>'C'");
            Commit2();
            Execute(s2, "drop table test");
            Rollback2();

            // select for update should do an exclusive lock, even with mvcc
            Execute(s1, "create table test(id int primary key, name varchar(255))");
            Execute(s1, "insert into test values(1, 'y')");
            Commit1();
            Execute(s2, "select * from test where id = 1 for update");
            AssertThrows(ErrorCode.LockTimeout1, s1, "delete from test");
            Rollback2();
            Execute(s1, "drop table test");
            Commit1();
            Commit2();

            Execute(s1, "create table test(id int primary key, name varchar(255))");
            Execute(s2, "insert into test values(4, 'Hello')");
            Rollback2();
            AssertResult("0", s1, "select count(*) from test where name = 'Hello'");
            AssertResult("0", s2, "select count(*) from test where name = 'Hello'");
            Commit1();
            Commit2();
            Execute(s1, "DROP TABLE TEST");

            Execute(s1, "CREATE TABLE TEST(ID INT PRIMARY KEY, NAME VARCHAR(255))");
            Execute(s1, "INSERT INTO TEST VALUES(1, 'Test')");
            Commit1();
            AssertResult("1", s1, "select max(id) from test");
            Execute(s1, "INSERT INTO TEST VALUES(2, 'World')");
            Rollback1();
            AssertResult("1", s1, "select max(id) from test");
            Commit1();
            Commit2();
            Execute(s1, "DROP TABLE TEST");

            Execute(s1, "create table test as select * from table(id int=(1, 2))");
            Execute(s1, "update test set id=1 where id=1");
            Execute(s1, "select max(id) from test");
            AssertResult("2", s1, "select max(id) from test");
            Commit1();
            Commit2();
            Execute(s1, "DROP TABLE TEST");

            Execute(s1, "CREATE TABLE TEST(ID INT)");
            Execute(s1, "INSERT INTO TEST VALUES(1)");
            Commit1();
            AssertResult("1", s2, "SELECT COUNT(*) FROM TEST");
            _ = ExecuteUpdate(s1, "DELETE FROM TEST");
            DbCommand p2 = WithTransaction(c2, t2,
                "select count(*) from test");
            using (DbDataReader rs = p2.ExecuteReader())
            {
                rs.Read();
                AssertEquals(1, rs.GetInt32(0));
            }

            AssertResult("1", s2, "SELECT COUNT(*) FROM TEST");
            AssertResult("0", s1, "SELECT COUNT(*) FROM TEST");
            Commit1();
            AssertResult("0", s2, "SELECT COUNT(*) FROM TEST");
            p2.CommandText = "select count(*) from test";
            using (DbDataReader rs = p2.ExecuteReader())
            {
                rs.Read();
                AssertEquals(0, rs.GetInt32(0));
            }

            Commit1();
            Commit2();
            Execute(s1, "DROP TABLE TEST");

            Execute(s1, "CREATE TABLE TEST(ID INT)");
            Execute(s1, "INSERT INTO TEST VALUES(1)");
            Commit1();
            Execute(s1, "DELETE FROM TEST");
            AssertResult("0", s1, "SELECT COUNT(*) FROM TEST");
            Commit1();
            AssertResult("0", s1, "SELECT COUNT(*) FROM TEST");
            Execute(s1, "INSERT INTO TEST VALUES(1)");
            Execute(s1, "DELETE FROM TEST");
            Commit1();
            AssertResult("0", s1, "SELECT COUNT(*) FROM TEST");
            Execute(s1, "DROP TABLE TEST");

            Execute(s1, "CREATE TABLE TEST(ID INT PRIMARY KEY, NAME VARCHAR)");
            Execute(s1, "INSERT INTO TEST VALUES(1, 'Hello'), (2, 'World')");
            AssertResult("0", s2, "SELECT COUNT(*) FROM TEST");
            Commit1();
            AssertResult("2", s2, "SELECT COUNT(*) FROM TEST");
            Execute(s1, "INSERT INTO TEST VALUES(3, '!')");
            Rollback1();
            AssertResult("2", s2, "SELECT COUNT(*) FROM TEST");
            Execute(s1, "DROP TABLE TEST");
            Commit1();

            Execute(s1, "CREATE TABLE TEST(ID INT PRIMARY KEY, NAME VARCHAR)");
            Execute(s1, "INSERT INTO TEST VALUES(1, 'Hello')");
            Execute(s1, "DELETE FROM TEST");
            AssertResult("0", s2, "SELECT COUNT(*) FROM TEST");
            Commit1();
            AssertResult("0", s2, "SELECT COUNT(*) FROM TEST");
            Execute(s1, "DROP TABLE TEST");
            Commit1();

            Execute(s1, "CREATE TABLE TEST(ID INT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR)");
            Execute(s1, "INSERT INTO TEST(NAME) VALUES('Ruebezahl')");
            AssertResult("0", s2, "SELECT COUNT(*) FROM TEST");
            AssertResult("1", s1, "SELECT COUNT(*) FROM TEST");
            Execute(s1, "DROP TABLE TEST");
            Commit1();

            Execute(s1, "CREATE TABLE TEST(ID INT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR)");
            Execute(s1, "INSERT INTO TEST(NAME) VALUES('Ruebezahl')");
            Execute(s1, "INSERT INTO TEST(NAME) VALUES('Ruebezahl')");
            Execute(s1, "DROP TABLE TEST");
            Commit1();

            Execute(s1, "CREATE TABLE TEST(ID INT PRIMARY KEY, NAME VARCHAR)");
            Execute(s1, "INSERT INTO TEST VALUES(1, 'Hello')");
            Commit1();
            Execute(s1, "DELETE FROM TEST WHERE ID=1");
            Rollback1();
            Execute(s1, "DROP TABLE TEST");
            Commit1();

            Random random = new(1);
            Execute(s1, "CREATE TABLE TEST(ID INT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR)");
            for (int i = 0; i < 1000; i++)
            {
                bool useFirst = random.Next(2) == 0;
                DbCommand s = useFirst ? s1 : s2;
                switch (random.Next(5))
                {
                    case 0:
                        Execute(s, "INSERT INTO TEST(NAME) VALUES('Hello')");
                        break;
                    case 1:
                        Execute(s, "UPDATE TEST SET NAME=" + i + " WHERE ID=" + random.Next(i));
                        break;
                    case 2:
                        Execute(s, "DELETE FROM TEST WHERE ID=" + random.Next(i));
                        break;
                    case 3:
                        CommitAll(useFirst);
                        break;
                    case 4:
                        RollbackAll(useFirst);
                        break;
                }

                Query(s1, "SELECT * FROM TEST ORDER BY ID");
                Query(s2, "SELECT * FROM TEST ORDER BY ID");
            }

            Rollback2();
            Execute(s1, "DROP TABLE TEST");
            Commit1();
            Commit2();

            random = new Random(1);
            Execute(s1, "CREATE TABLE TEST(ID INT PRIMARY KEY, NAME VARCHAR)");
            for (int i = 0; i < 1000; i++)
            {
                bool useFirst = random.Next(2) == 0;
                DbCommand s = useFirst ? s1 : s2;
                switch (random.Next(5))
                {
                    case 0:
                        Execute(s, "INSERT INTO TEST VALUES(" + i + ", 'Hello')");
                        break;
                    case 1:
                        try
                        {
                            Execute(s, "UPDATE TEST SET NAME=" + i
                                + " WHERE ID=" + random.Next(i));
                        }
                        catch (H2SharpException e)
                        {
                            AssertEquals(ErrorCode.ConcurrentUpdate1, e.H2ErrorCode);
                        }

                        break;
                    case 2:
                        Execute(s, "DELETE FROM TEST WHERE ID=" + random.Next(i));
                        break;
                    case 3:
                        CommitAll(useFirst);
                        break;
                    case 4:
                        RollbackAll(useFirst);
                        break;
                }

                Query(s1, "SELECT * FROM TEST ORDER BY ID");
                Query(s2, "SELECT * FROM TEST ORDER BY ID");
            }

            Rollback2();
            Execute(s1, "DROP TABLE TEST");
            Commit1();
            Commit2();

            Execute(s1, "CREATE TABLE TEST(ID INT, NAME VARCHAR)");
            Execute(s1, "INSERT INTO TEST VALUES(1, 'Hello')");
            AssertResult("0", s2, "SELECT COUNT(*) FROM TEST WHERE NAME!='X'");
            AssertResult("1", s1, "SELECT COUNT(*) FROM TEST WHERE NAME!='X'");
            Commit1();
            AssertResult("1", s2, "SELECT COUNT(*) FROM TEST WHERE NAME!='X'");
            AssertResult("1", s2, "SELECT COUNT(*) FROM TEST WHERE NAME!='X'");
            Execute(s1, "DROP TABLE TEST");
            Commit1();
            Commit2();

            Execute(s1, "CREATE TABLE TEST(ID INT PRIMARY KEY, NAME VARCHAR)");
            Execute(s1, "INSERT INTO TEST VALUES(1, 'Hello')");
            AssertResult("0", s2, "SELECT COUNT(*) FROM TEST WHERE ID<100");
            AssertResult("1", s1, "SELECT COUNT(*) FROM TEST WHERE ID<100");
            Commit1();
            AssertResult("1", s2, "SELECT COUNT(*) FROM TEST WHERE ID<100");
            AssertResult("1", s2, "SELECT COUNT(*) FROM TEST WHERE ID<100");
            Execute(s1, "DROP TABLE TEST");
            Commit1();
            Commit2();

            Execute(s1, "CREATE TABLE TEST(ID INT, NAME VARCHAR, PRIMARY KEY(ID, NAME))");
            Execute(s1, "INSERT INTO TEST VALUES(1, 'Hello')");
            Commit1();
            AssertResult("Hello", s2, "SELECT NAME FROM TEST WHERE ID=1");
            Execute(s1, "UPDATE TEST SET NAME = 'Hallo' WHERE ID=1");
            AssertResult("Hello", s2, "SELECT NAME FROM TEST WHERE ID=1");
            AssertResult("Hallo", s1, "SELECT NAME FROM TEST WHERE ID=1");
            Execute(s1, "DROP TABLE TEST");
            Commit1();
            Commit2();

            Execute(s1, "create table test(id int primary key, name varchar(255))");
            Execute(s1, "insert into test values(1, 'Hello'), (2, 'World')");
            Commit1();
            AssertThrows(ErrorCode.DuplicateKey1, s1,
                "update test set id=2 where id=1");
            s1.CommandText = "select * from test order by id";
            using (DbDataReader rs = s1.ExecuteReader())
            {
                AssertTrue(rs.Read());
                AssertEquals(1, rs.GetInt32(0));
                AssertEquals("Hello", rs.GetString(1));
                AssertTrue(rs.Read());
                AssertEquals(2, rs.GetInt32(0));
                AssertEquals("World", rs.GetString(1));
                AssertFalse(rs.Read());
            }

            s2.CommandText = "select * from test order by id";
            using (DbDataReader rs = s2.ExecuteReader())
            {
                AssertTrue(rs.Read());
                AssertEquals(1, rs.GetInt32(0));
                AssertEquals("Hello", rs.GetString(1));
                AssertTrue(rs.Read());
                AssertEquals(2, rs.GetInt32(0));
                AssertEquals("World", rs.GetString(1));
                AssertFalse(rs.Read());
            }

            Execute(s1, "drop table test");
            Commit1();
            Commit2();
        }
        finally
        {
            t1.Dispose();
            t2.Dispose();
            c1.Close();
            c2.Close();
        }
    }

    private void Begin1()
    {
        t1 = c1.BeginTransaction();
        s1.Transaction = t1;
    }

    private void Begin2()
    {
        t2 = c2.BeginTransaction();
        s2.Transaction = t2;
    }

    private void Commit1()
    {
        t1.Commit();
        t1.Dispose();
        Begin1();
    }

    private void Commit2()
    {
        t2.Commit();
        t2.Dispose();
        Begin2();
    }

    private void Rollback1()
    {
        t1.Rollback();
        t1.Dispose();
        Begin1();
    }

    private void Rollback2()
    {
        t2.Rollback();
        t2.Dispose();
        Begin2();
    }

    private void CommitAll(bool first)
    {
        if (first)
        {
            Commit1();
        }
        else
        {
            Commit2();
        }
    }

    private void RollbackAll(bool first)
    {
        if (first)
        {
            Rollback1();
        }
        else
        {
            Rollback2();
        }
    }

    private static int ExecuteUpdate(DbCommand command, string sql)
    {
        command.CommandText = sql;
        return command.ExecuteNonQuery();
    }

    private static DbCommand WithTransaction(DbConnection conn, DbTransaction transaction,
        string sql)
    {
        DbCommand command = conn.CreateCommand();
        command.Transaction = transaction;
        command.CommandText = sql;
        return command;
    }

    private static void Query(DbCommand command, string sql)
    {
        command.CommandText = sql;
        using DbDataReader rs = command.ExecuteReader();
        while (rs.Read())
        {
            // just loop
        }
    }
}
