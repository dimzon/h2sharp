// docs/commands.html — maintenance statements, one test per checklist row.
using System;
using System.Data;
using Dapper;
using H2SharpSql.Specs.Infrastructure;
using Xunit;

namespace H2SharpSql.Specs.Commands;

public sealed class MaintenanceCommandTests
{
    /// <summary>docs/commands.html:2214 — REFRESH MATERIALIZED VIEW [schemaName.]viewName</summary>
    [Fact]
    public void RefreshMaterializedView_SeesTheChangedRows() // CMD-2214
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT)");
        _ = connection.Execute("INSERT INTO TEST(ID) VALUES (1)");
        _ = connection.Execute("CREATE MATERIALIZED VIEW TEST_VIEW AS SELECT ID FROM TEST WHERE ID < 100");
        _ = connection.Execute("INSERT INTO TEST(ID) VALUES (2)");

        _ = connection.Execute("REFRESH MATERIALIZED VIEW TEST_VIEW");

        Assert.Equal(2, connection.QuerySingle<int>("SELECT COUNT(*) FROM TEST_VIEW"));
    }

    /// <summary>docs/commands.html:2233 — TRUNCATE TABLE [schemaName.]tableName [ [ CONTINUE | RESTART ] IDENTITY ]</summary>
    [Fact]
    public void TruncateTable_RestartIdentity_EmptiesTheTable() // CMD-2233
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID BIGINT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR(50))");
        _ = connection.Execute("INSERT INTO TEST(NAME) VALUES ('Ada')");
        _ = connection.Execute("INSERT INTO TEST(NAME) VALUES ('Alan')");

        _ = connection.Execute("TRUNCATE TABLE TEST RESTART IDENTITY");
        _ = connection.Execute("INSERT INTO TEST(NAME) VALUES ('Grace')");

        Assert.Equal(1, connection.QuerySingle<long>("SELECT ID FROM TEST"));
    }

    /// <summary>docs/commands.html:2273 — CHECKPOINT</summary>
    [Fact]
    public void Checkpoint_IsAccepted() // CMD-2273
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT)");

        int affected = connection.Execute("CHECKPOINT");

        Assert.Equal(0, affected);
    }

    /// <summary>docs/commands.html:2292 — CHECKPOINT SYNC</summary>
    [Fact]
    public void CheckpointSync_IsAccepted() // CMD-2292
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT)");

        int affected = connection.Execute("CHECKPOINT SYNC");

        Assert.Equal(0, affected);
    }

    /// <summary>docs/commands.html:3427 — SHUTDOWN [ IMMEDIATELY | COMPACT | DEFRAG ]</summary>
    [Fact]
    public void Shutdown_Compact_ClosesTheDatabase() // CMD-3427
    {
        using IDbConnection connection = TestDatabase.Open();

        _ = connection.Execute("SHUTDOWN COMPACT");

        _ = Assert.ThrowsAny<Exception>(() => connection.Execute("SELECT 1"));
    }
}
