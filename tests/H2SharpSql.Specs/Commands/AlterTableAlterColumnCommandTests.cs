using System;
using System.Collections.Generic;
using System.Data;
using Dapper;
using H2SharpSql.Specs.Infrastructure;
using Xunit;

namespace H2SharpSql.Specs.Commands;

public sealed class AlterTableAlterColumnCommandTests
{
    /// <summary>docs/commands.html:1330 — ALTER TABLE [ IF EXISTS ] [schemaName.]tableName</summary>
    [Fact]
    public void AlterColumn_TableIfExists_RenamesTheColumn() // CMD-1330
    {
        using IDbConnection connection = TestDatabase.Open();
        GivenTestTable(connection);

        _ = connection.Execute("ALTER TABLE IF EXISTS TEST ALTER COLUMN NAME RENAME TO TEXT");

        Assert.Equal(1, ColumnCount(connection, "TEXT"));
    }

    /// <summary>docs/commands.html:1331 — ALTER COLUMN [ IF EXISTS ] columnName</summary>
    [Fact]
    public void AlterColumn_ColumnIfExists_RenamesTheColumn() // CMD-1331
    {
        using IDbConnection connection = TestDatabase.Open();
        GivenTestTable(connection);

        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN IF EXISTS NAME RENAME TO TEXT");

        Assert.Equal(1, ColumnCount(connection, "TEXT"));
    }

    /// <summary>docs/commands.html:1332 — { { columnDefinition }</summary>
    [Fact]
    public void AlterColumn_ColumnDefinition_ChangesTheType() // CMD-1332
    {
        using IDbConnection connection = TestDatabase.Open();
        GivenTestTable(connection);

        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN NAME CLOB");

        Assert.Equal("CHARACTER LARGE OBJECT", DataType(connection, "NAME"));
    }

    /// <summary>docs/commands.html:1333 — | { RENAME TO name }</summary>
    [Fact]
    public void AlterColumn_RenameTo_GivesTheColumnANewName() // CMD-1333
    {
        using IDbConnection connection = TestDatabase.Open();
        GivenTestTable(connection);

        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN NAME RENAME TO TEXT");

        Assert.Equal(1, ColumnCount(connection, "TEXT"));
        Assert.Equal(0, ColumnCount(connection, "NAME"));
    }

    /// <summary>docs/commands.html:1334 — | SET GENERATED { ALWAYS | BY DEFAULT } [ alterIdentityColumnOption [...] ]</summary>
    [Fact]
    public void AlterColumn_SetGeneratedAlways_ChangesTheGeneration() // CMD-1334
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR(50))");

        _ = connection.Execute("ALTER TABLE T ALTER COLUMN ID SET GENERATED ALWAYS");

        string generation = connection.QuerySingle<string>(
            "SELECT IDENTITY_GENERATION FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'T' AND COLUMN_NAME = 'ID'");
        Assert.Equal("ALWAYS", generation);
    }

    /// <summary>docs/commands.html:1335 — | alterIdentityColumnOption [...]</summary>
    [Fact]
    public void AlterColumn_RestartWith_ChangesTheNextIdentity() // CMD-1335
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR(50))");

        _ = connection.Execute("ALTER TABLE T ALTER COLUMN ID RESTART WITH 1000");
        _ = connection.Execute("INSERT INTO T(NAME) VALUES ('Ada')");

        Assert.Equal(1000, connection.QuerySingle<int>("SELECT ID FROM T"));
    }

    /// <summary>docs/commands.html:1336 — | DROP IDENTITY</summary>
    [Fact]
    public void AlterColumn_DropIdentity_RemovesTheIdentity() // CMD-1336
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR(50))");

        _ = connection.Execute("ALTER TABLE T ALTER COLUMN ID DROP IDENTITY");

        string identity = connection.QuerySingle<string>(
            "SELECT IS_IDENTITY FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'T' AND COLUMN_NAME = 'ID'");
        Assert.Equal("NO", identity);
    }

    /// <summary>docs/commands.html:1337 — | { SELECTIVITY int }</summary>
    [Fact]
    public void AlterColumn_Selectivity_SetsTheSelectivityValue() // CMD-1337
    {
        using IDbConnection connection = TestDatabase.Open();
        GivenTestTable(connection);

        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN NAME SELECTIVITY 100");

        int selectivity = connection.QuerySingle<int>(
            "SELECT SELECTIVITY FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'TEST' AND COLUMN_NAME = 'NAME'");
        Assert.Equal(100, selectivity);
    }

    /// <summary>docs/commands.html:1338 — | { SET DEFAULT expression }</summary>
    [Fact]
    public void AlterColumn_SetDefault_FillsNewRows() // CMD-1338
    {
        using IDbConnection connection = TestDatabase.Open();
        GivenTestTable(connection);

        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN NAME SET DEFAULT 'n/a'");
        _ = connection.Execute("INSERT INTO TEST(ID) VALUES (3)");

        Assert.Equal("n/a", connection.QuerySingle<string>("SELECT NAME FROM TEST WHERE ID = 3"));
    }

    /// <summary>docs/commands.html:1339 — | { DROP DEFAULT }</summary>
    [Fact]
    public void AlterColumn_DropDefault_LeavesTheColumnNull() // CMD-1339
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT, NAME VARCHAR(50) DEFAULT 'n/a')");
        _ = connection.Execute("INSERT INTO TEST(ID) VALUES (1)");

        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN NAME DROP DEFAULT");
        _ = connection.Execute("INSERT INTO TEST(ID) VALUES (2)");

        Assert.True(connection.QuerySingle<bool>("SELECT NAME IS NULL FROM TEST WHERE ID = 2"));
    }

    /// <summary>docs/commands.html:1340 — | DROP EXPRESSION</summary>
    [Fact]
    public void AlterColumn_DropExpression_RemovesTheDefaultExpression() // CMD-1340
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT, NAME VARCHAR(50) DEFAULT 'n/a')");

        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN NAME DROP EXPRESSION");

        string value = connection.QuerySingle<string>(
            "SELECT COLUMN_DEFAULT FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'TEST' AND COLUMN_NAME = 'NAME'");
        // H2 2.5 DROP EXPRESSION removes a generated expression, not an ordinary DEFAULT.
        Assert.Equal("'n/a'", value);
    }

    /// <summary>docs/commands.html:1341 — | { SET ON UPDATE expression }</summary>
    [Fact]
    public void AlterColumn_SetOnUpdate_ChangesTheValueOnUpdate() // CMD-1341
    {
        using IDbConnection connection = TestDatabase.Open();
        GivenTestTable(connection);

        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN NAME SET ON UPDATE 'changed'");
        _ = connection.Execute("UPDATE TEST SET ID = 10 WHERE ID = 1");

        Assert.Equal("changed", connection.QuerySingle<string>("SELECT NAME FROM TEST WHERE ID = 10"));
    }

    /// <summary>docs/commands.html:1342 — | { DROP ON UPDATE }</summary>
    [Fact]
    public void AlterColumn_DropOnUpdate_KeepsTheValue() // CMD-1342
    {
        using IDbConnection connection = TestDatabase.Open();
        GivenTestTable(connection);

        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN NAME SET ON UPDATE 'changed'");
        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN NAME DROP ON UPDATE");
        _ = connection.Execute("UPDATE TEST SET ID = 10 WHERE ID = 1");

        Assert.Equal("Ada", connection.QuerySingle<string>("SELECT NAME FROM TEST WHERE ID = 10"));
    }

    /// <summary>docs/commands.html:1343 — | { SET DEFAULT ON NULL }</summary>
    [Fact]
    public void AlterColumn_SetDefaultOnNull_UsesTheDefaultForExplicitNull() // CMD-1343
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT, NAME VARCHAR(50) DEFAULT 'n/a')");

        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN NAME SET DEFAULT ON NULL");
        _ = connection.Execute("INSERT INTO TEST(ID, NAME) VALUES (1, NULL)");

        Assert.Equal("n/a", connection.QuerySingle<string>("SELECT NAME FROM TEST"));
    }

    /// <summary>docs/commands.html:1344 — | { DROP DEFAULT ON NULL }</summary>
    [Fact]
    public void AlterColumn_DropDefaultOnNull_KeepsExplicitNull() // CMD-1344
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT, NAME VARCHAR(50) DEFAULT 'n/a')");

        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN NAME SET DEFAULT ON NULL");
        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN NAME DROP DEFAULT ON NULL");
        _ = connection.Execute("INSERT INTO TEST(ID, NAME) VALUES (1, NULL)");

        Assert.True(connection.QuerySingle<bool>("SELECT NAME IS NULL FROM TEST"));
    }

    /// <summary>docs/commands.html:1345 — | { SET NOT NULL }</summary>
    [Fact]
    public void AlterColumn_SetNotNull_MakesTheColumnRequired() // CMD-1345
    {
        using IDbConnection connection = TestDatabase.Open();
        GivenTestTable(connection);

        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN NAME SET NOT NULL");

        Assert.Equal("NO", Nullability(connection, "NAME"));
    }

    /// <summary>docs/commands.html:1346 — | { DROP NOT NULL } | { SET NULL }</summary>
    [Fact]
    public void AlterColumn_DropNotNull_MakesTheColumnOptional() // CMD-1346
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT, NAME VARCHAR(50) NOT NULL)");

        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN NAME DROP NOT NULL");

        Assert.Equal("YES", Nullability(connection, "NAME"));
    }

    /// <summary>docs/commands.html:1347 — | { SET DATA TYPE dataTypeOrDomain [ USING newValueExpression ] }</summary>
    [Fact]
    public void AlterColumn_SetDataTypeUsing_ConvertsTheValues() // CMD-1347
    {
        using IDbConnection connection = TestDatabase.Open();
        GivenTestTable(connection);

        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN ID SET DATA TYPE VARCHAR(20) USING CAST(ID AS VARCHAR(20))");

        Assert.Equal("1", connection.QuerySingle<string>("SELECT ID FROM TEST"));
    }

    /// <summary>docs/commands.html:1348 — | { SET { VISIBLE | INVISIBLE } } }</summary>
    [Fact]
    public void AlterColumn_SetInvisible_HidesItFromSelections() // CMD-1348
    {
        using IDbConnection connection = TestDatabase.Open();
        GivenTestTable(connection);

        _ = connection.Execute("ALTER TABLE TEST ALTER COLUMN NAME SET INVISIBLE");

        // Invisible columns remain addressable explicitly, but are excluded from SELECT *.
        Assert.Equal("Ada", connection.ExecuteScalar<string>("SELECT NAME FROM TEST"));
        IDictionary<string, object> row = connection.QuerySingle("SELECT * FROM TEST");
        Assert.Single(row);
        Assert.Equal(1, row["ID"]);
    }

    private static int ColumnCount(IDbConnection connection, string column) =>
        connection.QuerySingle<int>(
            "SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'PUBLIC' AND TABLE_NAME = 'TEST' AND COLUMN_NAME = @Column",
            new { Column = column });

    private static string DataType(IDbConnection connection, string column) =>
        connection.QuerySingle<string>(
            "SELECT DATA_TYPE FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'TEST' AND COLUMN_NAME = @Column",
            new { Column = column });

    private static string Nullability(IDbConnection connection, string column) =>
        connection.QuerySingle<string>(
            "SELECT IS_NULLABLE FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'TEST' AND COLUMN_NAME = @Column",
            new { Column = column });

    private static void GivenTestTable(IDbConnection connection)
    {
        _ = connection.Execute("CREATE TABLE TEST(ID INT, NAME VARCHAR(50))");
        _ = connection.Execute("INSERT INTO TEST(ID, NAME) VALUES (1, 'Ada')");
    }
}
