    /// <summary>docs/grammar.html:2215 — dataTypeOrDomain [ VISIBLE | INVISIBLE ]</summary>
    [Fact]
    public void ColumnDefinition_InvisibleColumn_IsHiddenFromWildcard() // GRM-2215
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT INVISIBLE, NAME VARCHAR(50))");
        _ = connection.Execute("INSERT INTO TEST(NAME) VALUES ('Ada')");

        IDictionary<string, object> row = (IDictionary<string, object>)connection
            .Query("SELECT * FROM TEST").First();

        Assert.True(row.ContainsKey("NAME"));
        Assert.False(row.ContainsKey("ID"));
    }

