    /// <summary>docs/grammar.html:3124 — [ referentialTriggeredAction ]</summary>
    [Fact]
    public void ReferencesSpecification_DeleteCascade_RemovesTheChild() // GRM-3124
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE P(ID INT PRIMARY KEY)");
        _ = connection.Execute("CREATE TABLE C(PID INT, FOREIGN KEY (PID) REFERENCES P(ID) ON DELETE CASCADE)");
        _ = connection.Execute("INSERT INTO P(ID) VALUES (1)");
        _ = connection.Execute("INSERT INTO C(PID) VALUES (1)");

        _ = connection.Execute("DELETE FROM P WHERE ID = 1");

        Assert.Equal(0, connection.QuerySingle<int>("SELECT COUNT(*) FROM C"));
    }

    /// <summary>docs/grammar.html:3143 — ON UPDATE referentialAction [ ON DELETE referentialAction ]</summary>
    [Fact]
    public void ReferentialTriggeredAction_UpdateFirst_CascadesTheUpdate() // GRM-3143
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE P(ID INT PRIMARY KEY)");
        _ = connection.Execute("CREATE TABLE C(PID INT, FOREIGN KEY (PID) REFERENCES P(ID) ON UPDATE CASCADE ON DELETE CASCADE)");
