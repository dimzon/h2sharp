// docs/grammar.html — MERGE when clauses, one test per checklist row.
using System.Data;
using Dapper;
using H2SharpSql.Specs.Infrastructure;
using Xunit;

namespace H2SharpSql.Specs.Grammar;

public sealed class MergeClauseTests
{
    /// <summary>docs/grammar.html:2951 — mergeWhenMatchedClause|mergeWhenNotMatchedClause</summary>
    [Fact]
    public void MergeWhenClause_MatchedAndNotMatched_AreDispatched() // GRM-2951
    {
        using IDbConnection connection = TestDatabase.Open();
        GivenMergeTables(connection);

        _ = connection.Execute(
            "MERGE INTO T USING S ON T.ID = S.ID " +
            "WHEN MATCHED THEN UPDATE SET T.NAME = S.NAME " +
            "WHEN NOT MATCHED THEN INSERT (ID, NAME) VALUES (S.ID, S.NAME)");

        Assert.Equal("Ada!", connection.QuerySingle<string>("SELECT NAME FROM T WHERE ID = 1"));
        Assert.Equal("Grace", connection.QuerySingle<string>("SELECT NAME FROM T WHERE ID = 3"));
    }

    /// <summary>docs/grammar.html:2969 — WHEN MATCHED [ AND expression ] THEN</summary>
    [Fact]
    public void MergeWhenMatchedClause_ExtraCondition_SkipsTheRow() // GRM-2969
    {
        using IDbConnection connection = TestDatabase.Open();
        GivenMergeTables(connection);

        _ = connection.Execute(
            "MERGE INTO T USING S ON T.ID = S.ID " +
            "WHEN MATCHED AND S.V = 2 THEN UPDATE SET T.NAME = S.NAME");

        Assert.Equal("Ada", connection.QuerySingle<string>("SELECT NAME FROM T WHERE ID = 1"));
    }

    /// <summary>docs/grammar.html:2970 — UPDATE SET setClauseList | DELETE</summary>
    [Fact]
    public void MergeWhenMatchedClause_Delete_RemovesTheRow() // GRM-2970
    {
        using IDbConnection connection = TestDatabase.Open();
        GivenMergeTables(connection);

        _ = connection.Execute("MERGE INTO T USING S ON T.ID = S.ID WHEN MATCHED THEN DELETE");

        Assert.Equal(0, connection.QuerySingle<int>("SELECT COUNT(*) FROM T WHERE ID = 1"));
    }

    /// <summary>docs/grammar.html:2989 — WHEN NOT MATCHED [ AND expression ] THEN INSERT</summary>
    [Fact]
    public void MergeWhenNotMatchedClause_Insert_AddsTheRow() // GRM-2989
    {
        using IDbConnection connection = TestDatabase.Open();
        GivenMergeTables(connection);

        _ = connection.Execute(
            "MERGE INTO T USING S ON T.ID = S.ID " +
            "WHEN NOT MATCHED AND S.V > 2 THEN INSERT (ID, NAME) VALUES (S.ID, S.NAME)");

        Assert.Equal(1, connection.QuerySingle<int>("SELECT COUNT(*) FROM T WHERE ID = 3"));
    }

    /// <summary>docs/grammar.html:2990 — [ ( columnName [,...] ) ]</summary>
    [Fact]
    public void MergeWhenNotMatchedClause_ColumnList_IsUsedForInsert() // GRM-2990
    {
        using IDbConnection connection = TestDatabase.Open();
        GivenMergeTables(connection);

        _ = connection.Execute(
            "MERGE INTO T USING S ON T.ID = S.ID " +
            "WHEN NOT MATCHED THEN INSERT (NAME, ID) VALUES (S.NAME, S.ID)");

        Assert.Equal("Grace", connection.QuerySingle<string>("SELECT NAME FROM T WHERE ID = 3"));
    }

    /// <summary>docs/grammar.html:2991 — [ overrideClause ]</summary>
    [Fact]
    public void MergeWhenNotMatchedClause_OverrideClause_IsAccepted() // GRM-2991
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE T(ID BIGINT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR(50))");
        _ = connection.Execute("CREATE TABLE S(ID BIGINT, NAME VARCHAR(50), V INT)");
        _ = connection.Execute("INSERT INTO S(ID, NAME, V) VALUES (10, 'Grace', 3)");

        _ = connection.Execute(
            "MERGE INTO T USING S ON T.ID = S.ID " +
            "WHEN NOT MATCHED THEN INSERT (ID, NAME) OVERRIDING SYSTEM VALUE VALUES (S.ID, S.NAME)");

        Assert.Equal(10, connection.QuerySingle<long>("SELECT ID FROM T"));
    }

    /// <summary>docs/grammar.html:2992 — VALUES ({DEFAULT|expression} [,...])</summary>
    [Fact]
    public void MergeWhenNotMatchedClause_DefaultValue_IsUsed() // GRM-2992
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE T(ID INT, NAME VARCHAR(50) DEFAULT 'x')");
        _ = connection.Execute("CREATE TABLE S(ID INT, NAME VARCHAR(50), V INT)");
        _ = connection.Execute("INSERT INTO S(ID, NAME, V) VALUES (3, 'Grace', 3)");

        _ = connection.Execute(
            "MERGE INTO T USING S ON T.ID = S.ID " +
            "WHEN NOT MATCHED THEN INSERT (ID, NAME) VALUES (S.ID, DEFAULT)");

        Assert.Equal("x", connection.QuerySingle<string>("SELECT NAME FROM T WHERE ID = 3"));
    }

    private static void GivenMergeTables(IDbConnection connection)
    {
        _ = connection.Execute("CREATE TABLE T(ID INT PRIMARY KEY, NAME VARCHAR(50))");
        _ = connection.Execute("CREATE TABLE S(ID INT, NAME VARCHAR(50), V INT)");
        _ = connection.Execute("INSERT INTO T(ID, NAME) VALUES (1, 'Ada')");
        _ = connection.Execute("INSERT INTO S(ID, NAME, V) VALUES (1, 'Ada!', 1)");
        _ = connection.Execute("INSERT INTO S(ID, NAME, V) VALUES (3, 'Grace', 3)");
    }
}
