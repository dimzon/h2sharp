using System.Data;
using Dapper;
using H2SharpSql.Specs.Infrastructure;
using Xunit;

namespace H2SharpSql.Specs.Grammar;

public sealed class StatementGrammarTests
{
    /// <summary>docs/grammar.html:2887 — VALUES { DEFAULT|expression | [ROW] ({DEFAULT|expression} [,...]) }, [,...]</summary>
    [Fact]
    public void InsertValues_DefaultRowAndMultiRow_AreAccepted() // GRM-2887
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT DEFAULT 9, NAME VARCHAR(50))");

        _ = connection.Execute("INSERT INTO TEST VALUES (1, 'Ada'), (2, 'Alan')");
        _ = connection.Execute("INSERT INTO TEST VALUES ROW(3, 'Grace')");
        _ = connection.Execute("INSERT INTO TEST VALUES (DEFAULT, 'Bob')");

        Assert.Equal(4, connection.QuerySingle<int>("SELECT COUNT(*) FROM TEST"));
        Assert.Equal(9, connection.QuerySingle<int>("SELECT ID FROM TEST WHERE NAME = 'Bob'"));
    }

    /// <summary>docs/grammar.html:3049 — OVERRIDING { USER | SYSTEM } VALUE</summary>
    [Fact]
    public void OverrideClause_UserAndSystemValues_AreHonoured() // GRM-3049
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID BIGINT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR(50))");

        _ = connection.Execute("INSERT INTO TEST(ID, NAME) OVERRIDING USER VALUE VALUES (10, 'Ada')");
        _ = connection.Execute("INSERT INTO TEST(ID, NAME) OVERRIDING SYSTEM VALUE VALUES (10, 'Alan')");

        Assert.Equal(1, connection.QuerySingle<long>("SELECT ID FROM TEST WHERE NAME = 'Ada'"));
        Assert.Equal(10, connection.QuerySingle<long>("SELECT ID FROM TEST WHERE NAME = 'Alan'"));
    }

    /// <summary>docs/grammar.html:3369 — { { updateTarget = { DEFAULT | expression } }</summary>
    [Fact]
    public void SetClauseList_DefaultKeyword_RestoresTheDefault() // GRM-3369
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT, NAME VARCHAR(50) DEFAULT 'x')");
        _ = connection.Execute("INSERT INTO TEST(ID, NAME) VALUES (1, 'Ada')");

        _ = connection.Execute("UPDATE TEST SET NAME = DEFAULT WHERE ID = 1");

        Assert.Equal("x", connection.QuerySingle<string>("SELECT NAME FROM TEST WHERE ID = 1"));
    }

    /// <summary>docs/grammar.html:3370 — | { ( updateTarget [,...] ) = { rowValueExpression | (query) } } } [,...]</summary>
    [Fact]
    public void SetClauseList_MultiColumnAssignment_UpdatesBothColumns() // GRM-3370
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT, NAME VARCHAR(50))");
        _ = connection.Execute("INSERT INTO TEST(ID, NAME) VALUES (1, 'Ada')");

        _ = connection.Execute("UPDATE TEST SET (NAME, ID) = ('new', 7) WHERE ID = 1");

        Assert.Equal("new", connection.QuerySingle<string>("SELECT NAME FROM TEST WHERE ID = 7"));
    }

    /// <summary>docs/grammar.html:2687 — { OLD | NEW | FINAL } TABLE</summary>
    [Fact]
    public void DataChangeDeltaTable_OldNewFinal_AreAccepted() // GRM-2687
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT)");

        Assert.Equal(1, connection.QuerySingle<int>(
            "SELECT COUNT(*) FROM FINAL TABLE (INSERT INTO TEST(ID) VALUES (5))"));
        Assert.Equal(1, connection.QuerySingle<int>(
            "SELECT COUNT(*) FROM OLD TABLE (UPDATE TEST SET ID = 6 WHERE ID = 5)"));
        Assert.Equal(1, connection.QuerySingle<int>(
            "SELECT COUNT(*) FROM NEW TABLE (UPDATE TEST SET ID = 7 WHERE ID = 6)"));
    }

    /// <summary>docs/grammar.html:2688 — ( { insert | update | delete | { mergeInto } | mergeUsing } )</summary>
    [Fact]
    public void DataChangeDeltaTable_DeleteAndMerge_AreAccepted() // GRM-2688
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT)");
        _ = connection.Execute("INSERT INTO TEST(ID) VALUES (1)");

        Assert.Equal(1, connection.QuerySingle<int>(
            "SELECT COUNT(*) FROM OLD TABLE (DELETE FROM TEST WHERE ID = 1)"));
        Assert.Equal(1, connection.QuerySingle<int>(
            "SELECT COUNT(*) FROM FINAL TABLE (MERGE INTO TEST(ID) KEY(ID) VALUES (2))"));
    }

    /// <summary>docs/grammar.html:2667 — charsetString [, fieldSepString [, fieldDelimString [, escString [, nullString]]]]</summary>
    [Fact]
    [Trait("Category", "BlockedByPort")]
    public void CsvOptions_PositionalForm_IsAccepted() // GRM-2667
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT)");
        _ = connection.Execute("INSERT INTO TEST(ID) VALUES (1)");
        _ = connection.Execute("INSERT INTO TEST(ID) VALUES (2)");

        int written = connection.ExecuteScalar<int>(
            "CALL CSVWRITE('test2.csv', 'SELECT * FROM TEST', 'UTF-8,|')");

        Assert.Equal(2, written);
    }

    /// <summary>docs/grammar.html:2668 — | optionString</summary>
    [Fact]
    [Trait("Category", "BlockedByPort")]
    public void CsvOptions_OptionStringForm_IsAccepted() // GRM-2668
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT)");
        _ = connection.Execute("INSERT INTO TEST(ID) VALUES (1)");
        _ = connection.Execute("INSERT INTO TEST(ID) VALUES (2)");

        int written = connection.ExecuteScalar<int>(
            "CALL CSVWRITE('test3.csv', 'SELECT * FROM TEST', 'charset=UTF-8 fieldSeparator=|')");

        Assert.Equal(2, written);
    }

    /// <summary>docs/grammar.html:3181 — [ COMPRESSION { DEFLATE | LZF | ZIP | GZIP } ]</summary>
    [Fact]
    public void ScriptCompression_Zip_IsAccepted() // GRM-3181
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT)");

        int affected = connection.Execute("SCRIPT TO 'test.txt' COMPRESSION ZIP");

        Assert.Equal(0, affected);
    }

    /// <summary>docs/grammar.html:3182 — [ CIPHER cipher PASSWORD string ]</summary>
    [Fact]
    [Trait("Category", "BlockedByPort")]
    public void ScriptEncryption_Aes_IsAccepted() // GRM-3182
    {
        using IDbConnection connection = TestDatabase.Open();
        _ = connection.Execute("CREATE TABLE TEST(ID INT)");

        int affected = connection.Execute("SCRIPT TO 'test.txt' CIPHER AES PASSWORD 'secret'");

        Assert.Equal(0, affected);
    }
}
