 * A comparison of a stored value with a value of another date and time type, checked
 * against the reference running the same text.
 *
 * The two types are a TIME and a TIMESTAMP WITH TIME ZONE, and a comparison between them has
 * to know the zone of the reader: the reader is the statement that runs now. The reference
 * gets it from the database, which is the provider of the row factories and asks the session
 * of the thread; the port did the same and answered the comparison with a refusal.
 */
using System;
using System.Collections.Generic;
using System.Globalization;
using H2Sharp;
using H2Sharp.Command;
using H2Sharp.Engine;
using H2Sharp.Result;
using H2Sharp.Tests.Oracle;
using H2Sharp.Values;
using Xunit;

namespace H2Sharp.Tests;

[Collection(OracleCollection.Name)]
public sealed class IndexedDateTimeComparisonOracleTests
{
    /// <summary>
    /// A comparison of a column of one date and time type with a value of another, over an
    /// index, is the same on both sides.
    /// </summary>
    [JavaOracleFact]
    public void AnIndexedComparisonOfTwoDateAndTimeTypesIsTheSameAsTheReference()
    {
        string[] statements =
        [
            // The zone of the comparison is the session's, which starts as the machine zone
            // on both sides; pin it so the oracle does not depend on where it runs (the
            // reference JVM runs with -Duser.timezone=UTC).
            "SET TIME ZONE 'UTC'",
            "CREATE TABLE T(TS TIMESTAMP)",
            "CREATE INDEX I ON T(TS)",
            "INSERT INTO T VALUES (TIMESTAMP '2020-01-02 03:04:05')",
            "SELECT COUNT(*) FROM T WHERE TS = TIMESTAMP WITH TIME ZONE '2020-01-02 03:04:05+00'",
            "SELECT COUNT(*) FROM T WHERE TS = CURRENT_TIMESTAMP",
            "SELECT COUNT(*) FROM T WHERE TS IN (CURRENT_TIMESTAMP)",
        ];
        List<string> port = RunPort(statements);
        List<string> java = RunJava(statements);
        Assert.True(
            java.Count == port.Count && java.SequenceEqual(port),
            "java:\n  " + string.Join("\n  ", java) + "\nport:\n  " + string.Join("\n  ", port));
    }

    /// <summary>
    /// Runs the statements here and writes what the question answered: the value, or the code
    /// of the error.
    /// </summary>
    /// <param name="statements">the statements</param>
    /// <returns>the lines</returns>
    private static List<string> RunPort(IReadOnlyList<string> statements)
    {
        SessionLocal session = new(
            new Database(new ConnectionInfo("jdbc:h2:mem:indexed_datetime_oracle")), "sa")
        {
            CastDataProvider = new TestCastDataProvider(),
            CompareMode = CompareMode.GetInstance(null, 0),
        };
        List<string> lines = [];
        foreach (string sql in statements)
        {
            try
            {
                CommandContainer container =
                    Assert.IsType<CommandContainer>(session.PrepareCommand(sql));
                if (sql.StartsWith("SELECT", StringComparison.Ordinal))
                {
                    ResultInterface result = container.Query(-1);
                    int visible = result.GetVisibleColumnCount();
                    while (result.Next())
                    {
                        Value?[] row = result.CurrentRow();
                        List<string> cells = [];
                        for (int i = 0; i < visible; i++)
                        {
                            Value? value = row[i];
                            cells.Add(value is null or ValueNull ? "-" : value.GetString() ?? "-");
                        }

                        lines.Add("=" + string.Join(":", cells));
                    }
                }
                else
                {
                    _ = container.ExecuteUpdate(false);
                }
            }
            catch (Exception e)
            {
                lines.Add(e is H2SharpException h2
                    ? "=" + h2.H2ErrorCode.ToString(CultureInfo.InvariantCulture)
                    : "=" + e.GetType().Name);
            }
        }

        return lines;
    }

    /// <summary>
    /// Runs the statements on the reference and writes what the question answered.
    /// </summary>
    /// <param name="statements">the statements</param>
    /// <returns>the lines</returns>
    private static List<string> RunJava(IReadOnlyList<string> statements)
        => OracleRunner.Run(
            statements,
            """
            java.sql.Connection conn = java.sql.DriverManager.getConnection("jdbc:h2:mem:indexed_datetime_oracle");
            java.sql.Statement stat = conn.createStatement();
            for (int i = 0; i < inputs.length; i++) {
              try {
                boolean isQuery = stat.execute(inputs[i]);
                if (isQuery) {
                  java.sql.ResultSet rs = stat.getResultSet();
                  int columns = rs.getMetaData().getColumnCount();
                  while (rs.next()) {
                    StringBuilder line = new StringBuilder("=");
                    for (int c = 1; c <= columns; c++) {
                      if (c > 1) {
                        line.append(':');
                      }
                      String s = rs.getString(c);
                      line.append(rs.wasNull() ? "-" : s);
                    }
                    System.out.println(line);
                  }
                }
              } catch (java.sql.SQLException e) {
                System.out.println("=" + e.getErrorCode());
              }
            }
            conn.close();
            """,
            extraJavaArgs: ["-Duser.language=en", "-Duser.timezone=UTC"]);
}
