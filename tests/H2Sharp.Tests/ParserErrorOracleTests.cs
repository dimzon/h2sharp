using Xunit;

namespace H2Sharp.Tests;

[Collection(OracleCollection.Name)]
public sealed class ParserErrorOracleTests : ParserCoverageOracleBase
{
    [JavaOracleFact]
    public void QuerySyntaxErrorsMatchTheReference()
    {
        AssertSameAsReference("parser_error_queries",
            "SELECT 1 2",
            "SELECT 1 AS",
            "SELECT ,",
            "SELECT * FROM (VALUES 1) V(A, A)",
            "SELECT TIME WITH TIME ZONE",
            "SELECT TIMESTAMP WITHOUT TIME ZONE",
            "SELECT PUBLIC..T",
            "CREATE VIEW V AS SELECT 1 2",
            "SELECT * FROM (VALUES (1, 2)) V(A, B) WHERE (A, B) IN (1)");
    }

    [JavaOracleFact]
    public void DdlErrorsMatchTheReference()
    {
        AssertSameAsReference("parser_error_ddl",
            "CREATE TABLE T(A INT)",
            "ALTER TABLE NO_T ALTER COLUMN A DROP IDENTITY",
            "ALTER TABLE T ALTER COLUMN NO_A DROP IDENTITY",
            "CREATE SEQUENCE S2 AS BOOLEAN",
            "CREATE SEQUENCE S3 INCREMENT BY 0",
            "CREATE INDEX I1 ON T()",
            "CREATE INDEX I2 ON T(A, A)",
            "CREATE TABLE D(A INT DEFAULT 1 DEFAULT ON NULL)",
            "CREATE TABLE G(A INT GENERATED BY DEFAULT AS 1)",
            "CREATE TABLE R(A INT REFERENCES T(B) ON DELETE SET)",
            "CREATE TABLE U(A UNKNOWN_TYPE)",
            "SELECT CAST(1 AS)",
            "SELECT 'x'::UNKNOWN");
    }
}
