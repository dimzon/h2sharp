 * The session's last identity: the modes that take the inserted row's identity
 * (takeInsertedIdentity) and the mode that takes a generated sequence value
 * (takeGeneratedSequenceValue), as the reference's SessionLocal does. The compatibility-mode
 * SQL functions that read it (LAST_INSERT_ID and friends) are a separate, unported feature.
 */
using System;
using H2Sharp;
using H2Sharp.Command;
using H2Sharp.Engine;
using H2Sharp.Tests.Oracle;
using H2Sharp.Values;
using Xunit;

namespace H2Sharp.Tests;

public sealed class SessionLastIdentityTests
{
    [Fact]
    public void TheModesTakeTheIdentityWhereTheReferenceDoes()
    {
        foreach (string name in new[] { "LEGACY", "DB2", "Derby", "MSSQLServer", "MariaDB", "MySQL" })
        {
            Assert.True(Mode.GetInstance(name)!.TakeInsertedIdentity, name);
        }

        foreach (string name in new[] { "REGULAR", "STRICT", "HSQLDB", "Oracle", "PostgreSQL" })
        {
            Assert.False(Mode.GetInstance(name)!.TakeInsertedIdentity, name);
        }

        Assert.True(Mode.GetInstance("PostgreSQL")!.TakeGeneratedSequenceValue);
        Assert.False(Mode.GetInstance("MySQL")!.TakeGeneratedSequenceValue);
    }

    [Fact]
    public void TheInsertTakesTheIdentityInMySqlMode()
    {
        SessionLocal session = NewSession("last_identity_insert", Mode.GetInstance("MySQL"));
        try
        {
            session.PrepareCommand(
                "CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY, V INT)")
                .ExecuteUpdate(false);
            Assert.Same(ValueNull.Instance, session.GetLastIdentity());

            session.PrepareCommand("INSERT INTO T(V) VALUES (5)").ExecuteUpdate(false);
            Assert.Equal(1, session.GetLastIdentity().GetInt());
        }
        finally
        {
            session.Close();
        }
    }

    [Fact]
    public void TheInsertDoesNotTakeTheIdentityInRegularMode()
    {
        SessionLocal session = NewSession("last_identity_regular", mode: null);
        try
        {
            session.PrepareCommand(
                "CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY, V INT)")
                .ExecuteUpdate(false);
            session.PrepareCommand("INSERT INTO T(V) VALUES (5)").ExecuteUpdate(false);
            Assert.Same(ValueNull.Instance, session.GetLastIdentity());
        }
        finally
        {
            session.Close();
        }
    }

    [Fact]
    public void TheSequenceValueTakesTheIdentityInPostgreSqlMode()
    {
        SessionLocal session = NewSession("last_identity_sequence", Mode.GetInstance("PostgreSQL"));
        try
        {
            session.PrepareCommand("CREATE SEQUENCE S START WITH 7").ExecuteUpdate(false);
            CommandContainer query = Assert.IsType<CommandContainer>(
                session.PrepareCommand("SELECT NEXT VALUE FOR S"));
            _ = query.Query(-1);
            Assert.Equal(7, session.GetLastIdentity().GetInt());
        }
        finally
        {
            session.Close();
        }
    }

    [Fact]
    public void TheSequenceValueDoesNotTakeTheIdentityInRegularMode()
    {
        SessionLocal session = NewSession("last_identity_sequence_regular", mode: null);
        try
        {
            session.PrepareCommand("CREATE SEQUENCE S START WITH 7").ExecuteUpdate(false);
            CommandContainer query = Assert.IsType<CommandContainer>(
                session.PrepareCommand("SELECT NEXT VALUE FOR S"));
            _ = query.Query(-1);
            Assert.Same(ValueNull.Instance, session.GetLastIdentity());
        }
        finally
        {
            session.Close();
        }
    }

    private static SessionLocal NewSession(string name, Mode? mode)
        => new(
            new Database(ConnectionInfo.Memory(name + "_" + Guid.NewGuid().ToString("N"), mode)), "sa")
        {
            CastDataProvider = new TestCastDataProvider(),
            CompareMode = CompareMode.GetInstance(null, 0),
        };
}
