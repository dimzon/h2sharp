using System;
using System.Collections.Generic;
using System.Globalization;
using H2Sharp;
using H2Sharp.Command;
using H2Sharp.Engine;
using H2Sharp.Result;
using H2Sharp.Tests.Oracle;
using H2Sharp.Values;
using Xunit;

namespace H2Sharp.Tests;

[Collection(OracleCollection.Name)]
public sealed class InsertScriptOracleTests
{
    [JavaOracleFact]
    public void InsertScriptAnswersTheReference()
    {
        string[] statements =
        [
            "CREATE TABLE TEST(A INT, B INT);",
            "INSERT INTO TEST VALUES ROW (1, 2), (3, 4), ROW (5, 6);",
            "INSERT INTO TEST(a) VALUES 7;",
            "INSERT INTO TEST(a) VALUES 8, 9;",
            "TABLE TEST;",
            "DROP TABLE TEST;",
            "CREATE TABLE TEST(ID INT);",
            "INSERT INTO TEST(_ROWID_, ID) VALUES (2, 3);",
            "SELECT _ROWID_, ID FROM TEST;",
            "DROP TABLE TEST;",
            "CREATE TABLE TEST(A INT, B INT DEFAULT 5);",
            "INSERT INTO TEST VALUES (1, DEFAULT);",
            "INSERT INTO TEST SET A = 2, B = DEFAULT;",
            "TABLE TEST;",
            "DROP TABLE TEST;",
            "CREATE TABLE TEST(A INT, B INT GENERATED ALWAYS AS (A + 1));",
            "INSERT INTO TEST VALUES (1, 1);",
            "INSERT INTO TEST(B) VALUES 1;",
            "INSERT INTO TEST VALUES (1, DEFAULT);",
            "INSERT INTO TEST DEFAULT VALUES;",
            "TABLE TEST;",
            "DROP TABLE TEST;",
            "CREATE TABLE TEST(ID NUMERIC(20) GENERATED BY DEFAULT AS IDENTITY, V INT);",
            "INSERT INTO TEST VALUES (12345678901234567890, 1);",
            "TABLE TEST;",
            "DROP TABLE TEST;",
            "CREATE TABLE TEST(ID BIGINT GENERATED BY DEFAULT AS IDENTITY, V INT);",
            "INSERT INTO TEST VALUES (10, 20);",
            "INSERT INTO TEST OVERRIDING USER VALUE VALUES (20, 30);",
            "INSERT INTO TEST OVERRIDING SYSTEM VALUE VALUES (30, 40);",
            "TABLE TEST;",
            "DROP TABLE TEST;",
            "CREATE TABLE TEST(ID BIGINT GENERATED ALWAYS AS IDENTITY, V INT);",
            "INSERT INTO TEST VALUES (10, 20);",
            "INSERT INTO TEST OVERRIDING USER VALUE VALUES (20, 30);",
            "INSERT INTO TEST OVERRIDING SYSTEM VALUE VALUES (30, 40);",
            "TABLE TEST;",
            "DROP TABLE TEST;"
        ];
        RunBoth(statements);
    }

    private static void RunBoth(IReadOnlyList<string> statements)
    {
        List<string> port = RunPort(statements);
        List<string> java = RunJava(statements);
        port.RemoveAll(static line => line.StartsWith("=CREATE USER", StringComparison.Ordinal));
        java.RemoveAll(static line => line.StartsWith("=CREATE USER", StringComparison.Ordinal));
        Assert.True(
            java.Count == port.Count && java.SequenceEqual(port),
            "java:\n  " + string.Join("\n  ", java) + "\nport:\n  " + string.Join("\n  ", port));
    }

    private static List<string> RunPort(IReadOnlyList<string> statements)
    {
        SessionLocal session = new(
            new Database(ConnectionInfo.Memory("insert_script_oracle")), "sa")
        {
            CastDataProvider = new TestCastDataProvider(),
            CompareMode = CompareMode.GetInstance(null, 0),
        };
        List<string> lines = [];
        foreach (string sql in statements)
        {
            try
            {
                CommandContainer container =
                    Assert.IsType<CommandContainer>(session.PrepareCommand(sql));
                if (sql.StartsWith("SELECT", StringComparison.OrdinalIgnoreCase)
                    || sql.StartsWith("TABLE", StringComparison.OrdinalIgnoreCase)
                    || sql.StartsWith("WITH", StringComparison.OrdinalIgnoreCase)
                    || sql.StartsWith("VALUES", StringComparison.OrdinalIgnoreCase))
                {
                    ResultInterface result = container.Query(-1);
                    int visible = result.GetVisibleColumnCount();
                    while (result.Next())
                    {
                        Value?[] row = result.CurrentRow();
                        List<string> cells = [];
                        for (int i = 0; i < visible; i++)
                        {
                            Value? value = row[i];
                            cells.Add(value is null or ValueNull ? "-" : value.GetString() ?? "-");
                        }

                        string rowText = string.Join(":", cells);
                        string[] parts = rowText.Split('\n');
                        for (int p = 0; p < parts.Length; p++)
                        {
                            lines.Add(p == 0 ? "=" + parts[p].TrimEnd('\r') : parts[p].TrimEnd('\r'));
                        }
                    }
                }
                else
                {
                    lines.Add("=" + container.ExecuteUpdate(false).GetUpdateCount());
                }
            }
            catch (Exception e)
            {
                lines.Add(e is H2SharpException h2
                    ? "=" + h2.H2ErrorCode.ToString(CultureInfo.InvariantCulture)
                    : "=" + e.GetType().Name + ":" + e.Message);
            }
        }

        session.Close();
        return lines;
    }

    private static List<string> RunJava(IReadOnlyList<string> statements)
        => OracleRunner.Run(
            statements,
            """
            java.sql.Connection conn = java.sql.DriverManager.getConnection("jdbc:h2:mem:insert_script_oracle", "sa", "");
            java.sql.Statement stat = conn.createStatement();
            for (int i = 0; i < inputs.length; i++) {
              try {
                boolean isQuery = stat.execute(inputs[i]);
                if (isQuery) {
                  java.sql.ResultSet rs = stat.getResultSet();
                  int columns = rs.getMetaData().getColumnCount();
                  while (rs.next()) {
                    StringBuilder line = new StringBuilder("=");
                    for (int c = 1; c <= columns; c++) {
                      if (c > 1) {
                        line.append(':');
                      }
                      String s = rs.getString(c);
                      line.append(rs.wasNull() ? "-" : s);
                    }
                    System.out.println(line);
                  }
                } else {
                  System.out.println("=" + stat.getUpdateCount());
                }
              } catch (java.sql.SQLException e) {
                System.out.println("=" + e.getErrorCode());
              }
            }
            conn.close();
            """,
            extraJavaArgs: ["-Duser.language=en"]);
}

