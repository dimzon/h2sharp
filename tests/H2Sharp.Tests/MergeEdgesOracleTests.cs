 * MERGE edges from the coverage data (uncovered.py): a NULL or ill-typed value in the key,
 * the column-count refusals for both source kinds, the missing primary key refusal, a
 * key-only table (the update degenerates to an insert), a duplicate key from the source
 * itself, and the default-values form where the table is used as a sequence. Checked
 * against the reference running the same text.
 */
using System;
using System.Collections.Generic;
using System.Globalization;
using H2Sharp;
using H2Sharp.Command;
using H2Sharp.Engine;
using H2Sharp.Result;
using H2Sharp.Tests.Oracle;
using H2Sharp.Values;
using Xunit;

namespace H2Sharp.Tests;

[Collection(OracleCollection.Name)]
public sealed class MergeEdgesOracleTests
{
    [JavaOracleFact]
    public void MergeRefusalsAndDegenerateFormsAnswerTheReference()
    {
        string[] statements =
        [
            "CREATE TABLE T(ID INT PRIMARY KEY, NAME VARCHAR(10))",
            // A NULL and a non-numeric value in the key column.
            "MERGE INTO T(ID, NAME) KEY(ID) VALUES (NULL, 'x')",
            "MERGE INTO T(ID, NAME) KEY(ID) VALUES ('a', 'x')",
            // Column counts: a VALUES row and a query row against the column list.
            "MERGE INTO T(ID, NAME) VALUES (1)",
            "MERGE INTO T(ID, NAME) SELECT ID FROM (VALUES (1)) V(ID)",
            "MERGE INTO T(ID, NAME) VALUES (1, 'a')",
            "SELECT ID, NAME FROM T ORDER BY ID",
            // A table without a primary key and without an explicit KEY.
            "CREATE TABLE NPK(A INT, B INT)",
            "MERGE INTO NPK VALUES (1, 2)",
            "MERGE INTO NPK KEY(A) VALUES (1, 2)",
            "DROP TABLE NPK",
            // A table whose only column is the key: the update part is empty.
            "CREATE TABLE ONLYKEY(ID INT PRIMARY KEY)",
            "MERGE INTO ONLYKEY KEY(ID) VALUES (1)",
            "MERGE INTO ONLYKEY KEY(ID) VALUES (1)",
            "SELECT ID FROM ONLYKEY ORDER BY ID",
            "DROP TABLE ONLYKEY",
            // The source repeats a key: the second row collides with the first.
            "MERGE INTO T VALUES (2, 'b'), (2, 'c')",
            "SELECT ID, NAME FROM T ORDER BY ID",
            "DROP TABLE T",
            // The default-values form: the table is used as a sequence.
            "CREATE TABLE SEQ(A INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, B INT DEFAULT 7)",
            "MERGE INTO SEQ KEY(A) VALUES ()",
            "SELECT A, B FROM SEQ ORDER BY A",
            "DROP TABLE SEQ",
            // Consecutive source rows that miss the target: the deferred miss of the
            // previous row is flushed when the next one arrives.
            "CREATE TABLE DST2(ID INT PRIMARY KEY, V INT)",
            "INSERT INTO DST2 VALUES (1, 1)",
            "MERGE INTO DST2 D USING (SELECT X AS ID, X * 10 AS V FROM SYSTEM_RANGE(2, 4)) S "
                + "ON (D.ID = S.ID) WHEN NOT MATCHED THEN INSERT (ID, V) VALUES (S.ID, S.V)",
            "SELECT ID, V FROM DST2 ORDER BY ID",
            "DROP TABLE DST2",
        ];
        RunBoth(statements);
    }

    /// <summary>
    /// Runs the statements on both sides and asserts the same answers.
    /// </summary>
    /// <param name="statements">the statements</param>
    private static void RunBoth(IReadOnlyList<string> statements)
    {
        List<string> port = RunPort(statements);
        List<string> java = RunJava(statements);
        Assert.True(
            java.Count == port.Count && java.SequenceEqual(port),
            "java:\n  " + string.Join("\n  ", java) + "\nport:\n  " + string.Join("\n  ", port));
    }

    /// <summary>
    /// Runs the statements here and writes what the question answered.
    /// </summary>
    /// <param name="statements">the statements</param>
    /// <returns>the lines</returns>
    private static List<string> RunPort(IReadOnlyList<string> statements)
    {
        SessionLocal session = new(
            new Database(ConnectionInfo.Memory("merge_edges_oracle")), "sa")
        {
            CompareMode = CompareMode.GetInstance(null, 0),
        };
        session.CastDataProvider = new SessionCastDataProvider(session, DefaultCastDataProvider.Instance);
        List<string> lines = [];
        foreach (string sql in statements)
        {
            try
            {
                CommandContainer container =
                    Assert.IsType<CommandContainer>(session.PrepareCommand(sql));
                if (sql.StartsWith("SELECT", StringComparison.Ordinal))
                {
                    ResultInterface result = container.Query(-1);
                    int visible = result.GetVisibleColumnCount();
                    while (result.Next())
                    {
                        Value?[] row = result.CurrentRow();
                        List<string> cells = [];
                        for (int i = 0; i < visible; i++)
                        {
                            Value? value = row[i];
                            cells.Add(value is null or ValueNull ? "-" : value.GetString() ?? "-");
                        }

                        lines.Add("=" + string.Join(":", cells));
                    }
                }
                else
                {
                    lines.Add("=" + container.ExecuteUpdate(false).GetUpdateCount());
                }
            }
            catch (Exception e)
            {
                lines.Add(e is H2SharpException h2
                    ? "=" + h2.H2ErrorCode.ToString(CultureInfo.InvariantCulture)
                    : "=" + e.GetType().Name + ":" + e.Message);
            }
        }

        session.Close();
        return lines;
    }

    /// <summary>
    /// Runs the statements on the reference and writes what the question answered.
    /// </summary>
    /// <param name="statements">the statements</param>
    /// <returns>the lines</returns>
    private static List<string> RunJava(IReadOnlyList<string> statements)
        => OracleRunner.Run(
            statements,
            """
            java.sql.Connection conn = java.sql.DriverManager.getConnection("jdbc:h2:mem:merge_edges_oracle", "sa", "");
            java.sql.Statement stat = conn.createStatement();
            for (int i = 0; i < inputs.length; i++) {
              try {
                boolean isQuery = stat.execute(inputs[i]);
                if (isQuery) {
                  java.sql.ResultSet rs = stat.getResultSet();
                  int columns = rs.getMetaData().getColumnCount();
                  while (rs.next()) {
                    StringBuilder line = new StringBuilder("=");
                    for (int c = 1; c <= columns; c++) {
                      if (c > 1) {
                        line.append(':');
                      }
                      String s = rs.getString(c);
                      line.append(rs.wasNull() ? "-" : s);
                    }
                    System.out.println(line);
                  }
                } else {
                  System.out.println("=" + stat.getUpdateCount());
                }
              } catch (java.sql.SQLException e) {
                System.out.println("=" + e.getErrorCode());
              }
            }
            conn.close();
            """,
            extraJavaArgs: ["-Duser.language=en"]);
}
