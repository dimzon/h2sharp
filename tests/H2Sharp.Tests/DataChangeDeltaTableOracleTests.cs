 * The rows a statement changed, checked against the reference running the same text.
 *
 * H2 2.5 has no RETURNING: the row an insert wrote is read back through FINAL TABLE, which
 * is a table whose rows are the rows the statement changed. That is the form the providers
 * write when they want the generated key.
 */
using System;
using System.Collections.Generic;
using System.Globalization;
using H2Sharp;
using H2Sharp.Command;
using H2Sharp.Engine;
using H2Sharp.Expressions;
using H2Sharp.Result;
using H2Sharp.Tests.Oracle;
using H2Sharp.Values;
using Xunit;

namespace H2Sharp.Tests;

[Collection(OracleCollection.Name)]
public sealed class DataChangeDeltaTableOracleTests
{
    /// <summary>
    /// The rows an insert changed, the same on both sides.
    /// </summary>
    [JavaOracleFact]
    public void TheFinalTableIsTheSameAsTheReference()
    {
        string[] statements =
        [
            "CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR(50))",
            "SELECT ID FROM FINAL TABLE (INSERT INTO T(NAME) VALUES('a'))",
            "SELECT ID, NAME FROM FINAL TABLE (INSERT INTO T(NAME) VALUES('b'))",
            "SELECT ID, NAME FROM T ORDER BY ID",
        ];
        List<string> port = RunPort(statements);
        List<string> java = RunJava(statements);
        AssertSame(java, port);
    }

    /// <summary>
    /// The other versions of a changed row, the same on both sides.
    /// </summary>
    [JavaOracleFact]
    public void TheOtherVersionsAreTheSameAsTheReference()
    {
        string[] statements =
        [
            "CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR(50))",
            "SELECT ID FROM NEW TABLE (INSERT INTO T(NAME) VALUES('a'))",
            "SELECT ID FROM FINAL TABLE (INSERT INTO T(NAME) VALUES('b'))",
            "SELECT ID, NAME FROM OLD TABLE (UPDATE T SET NAME = 'c' WHERE ID = 2)",
            "SELECT ID, NAME FROM T ORDER BY ID",
        ];
        List<string> port = RunPort(statements);
        List<string> java = RunJava(statements);
        AssertSame(java, port);
    }

    /// <summary>
    /// A name that is not one of the three, the same on both sides.
    /// </summary>
    [JavaOracleFact]
    public void TheWrongNameIsTheSameAsTheReference()
    {
        string[] statements =
        [
            "CREATE TABLE T(ID INT, NAME VARCHAR(50))",
            "SELECT ID FROM MIDDLE TABLE (INSERT INTO T(NAME) VALUES('a'))",
            "SELECT ID FROM FINAL TABLE (INSERT INTO T(NAME) VALUES('b'))",
        ];
        List<string> port = RunPort(statements);
        List<string> java = RunJava(statements);
        AssertSame(java, port);
    }

    /// <summary>
    /// Several rows at once and a deleted row, the same on both sides.
    /// </summary>
    [JavaOracleFact]
    public void TheSeveralRowsAreTheSameAsTheReference()
    {
        string[] statements =
        [
            "CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR(50))",
            "SELECT ID, NAME FROM FINAL TABLE (INSERT INTO T(NAME) VALUES('a'), ('b'))",
            "SELECT ID, NAME FROM OLD TABLE (DELETE FROM T WHERE ID = 2)",
            "SELECT ID, NAME FROM T ORDER BY ID",
        ];
        List<string> port = RunPort(statements);
        List<string> java = RunJava(statements);
        AssertSame(java, port);
    }

    /// <summary>
    /// Compares the answers of the two sides.
    /// </summary>
    /// <param name="java">the answers of the reference</param>
    /// <param name="port">the answers of the port</param>
    private static void AssertSame(List<string> java, List<string> port)
    {
        Assert.True(
            java.Count == port.Count && java.SequenceEqual(port),
            "java:\n  " + string.Join("\n  ", java) + "\nport:\n  " + string.Join("\n  ", port));
    }

    /// <summary>
    /// Runs the statements here and writes what the question answered.
    /// </summary>
    /// <param name="statements">the statements</param>
    /// <returns>the lines</returns>
    private static List<string> RunPort(IReadOnlyList<string> statements)
    {
        SessionLocal session = new(
            new Database(new ConnectionInfo("jdbc:h2:mem:delta_oracle")), "sa")
        {
            CastDataProvider = new TestCastDataProvider(),
            CompareMode = CompareMode.GetInstance(null, 0),
        };

        List<string> lines = [];
        foreach (string sql in statements)
        {
            try
            {
                CommandContainer container =
                    Assert.IsType<CommandContainer>(session.PrepareCommand(sql));
                if (sql.StartsWith("SELECT", StringComparison.Ordinal))
                {
                    ResultInterface result = container.Query(-1);
                    int visible = result.GetVisibleColumnCount();
                    while (result.Next())
                    {
                        Value?[] row = result.CurrentRow();
                        List<string> cells = [];
                        for (int i = 0; i < visible; i++)
                        {
                            Value? value = row[i];
                            cells.Add(value is null or ValueNull ? "-" : value.GetString() ?? "-");
                        }

                        lines.Add("=" + string.Join(":", cells));
                    }
                }
                else
                {
                    _ = container.ExecuteUpdate(false);
                }
            }
            catch (Exception e)
            {
                lines.Add(e is H2SharpException h2
                    ? "=" + h2.H2ErrorCode.ToString(CultureInfo.InvariantCulture)
                    : "=" + e.GetType().Name + ":" + e.Message);
            }
        }

        return lines;
    }

    /// <summary>
    /// Runs the statements on the reference and writes what the question answered.
    /// </summary>
    /// <param name="statements">the statements</param>
    /// <returns>the lines</returns>
    private static List<string> RunJava(IReadOnlyList<string> statements)
        => OracleRunner.Run(
            statements,
            """
            java.sql.Connection conn = java.sql.DriverManager.getConnection("jdbc:h2:mem:delta_oracle");
            java.sql.Statement stat = conn.createStatement();
            for (int i = 0; i < inputs.length; i++) {
              try {
                boolean isQuery = stat.execute(inputs[i]);
                if (isQuery) {
                  java.sql.ResultSet rs = stat.getResultSet();
                  int columns = rs.getMetaData().getColumnCount();
                  while (rs.next()) {
                    StringBuilder line = new StringBuilder("=");
                    for (int c = 1; c <= columns; c++) {
                      if (c > 1) {
                        line.append(':');
                      }
                      String s = rs.getString(c);
                      line.append(rs.wasNull() ? "-" : s);
                    }
                    System.out.println(line);
                  }
                }
              } catch (java.sql.SQLException e) {
                System.out.println("=" + e.getErrorCode());
              }
            }
            conn.close();
            """,
            extraJavaArgs: ["-Duser.language=en"]);
}
