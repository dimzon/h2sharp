using Xunit;

namespace H2Sharp.Tests;

[Collection(OracleCollection.Name)]
public sealed class ParserSurfaceOracleTests : ParserCoverageOracleBase
{
    [JavaOracleFact]
    public void ShowFormsInTheirCompatibilityModes()
    {
        AssertSameAsReference("ps_show",
            "CREATE SCHEMA S1",
            "SET SCHEMA_SEARCH_PATH TO S1, PUBLIC",
            "SHOW SEARCH_PATH",
            "CREATE TABLE T(A INT PRIMARY KEY, B VARCHAR(10))",
            "SHOW TABLES",
            "SHOW TABLES FROM PUBLIC",
            "SELECT SCHEMA_NAME FROM INFORMATION_SCHEMA.SCHEMATA ORDER BY SCHEMA_NAME",
            "SHOW COLUMNS FROM T",
            "SET OLD_INFORMATION_SCHEMA TRUE",
            "SHOW COLUMNS FROM T",
            "SET OLD_INFORMATION_SCHEMA FALSE",
            "SHOW COLUMNS FROM T FROM PUBLIC",
            "DROP TABLE T",
            "DROP SCHEMA S1");
    }

    [JavaOracleFact]
    public void InsertForms()
    {
        AssertSameAsReference("ps_insert",
            "CREATE TABLE T(A INT PRIMARY KEY, B VARCHAR(10) DEFAULT 'x')",
            "INSERT INTO T(A) VALUES (1)",
            "INSERT INTO T VALUES (2, DEFAULT)",
            "INSERT INTO T DEFAULT VALUES",
            "INSERT INTO T(A, A) VALUES (3, 4)",
            "INSERT INTO NOPE VALUES (1)",
            "SELECT A, B FROM T ORDER BY A",
            "DROP TABLE T");
    }

    [JavaOracleFact]
    public void InsertSetFormInTheMySqlMode()
    {
        AssertSameAsReferenceInMode("ps_insert_set", "MySQL",
            "CREATE TABLE T(A INT, B VARCHAR(10))",
            "INSERT INTO T SET A = 1, B = 'y'",
            "INSERT INTO T SET A = 2",
            "INSERT INTO T(A) SET A = 3",
            "SELECT A, B FROM T ORDER BY A",
            "DROP TABLE T");
    }

    [JavaOracleFact]
    public void LikeSpellingsOnDml()
    {
        AssertSameAsReference("ps_like",
            "CREATE TABLE T(ID INT, NAME VARCHAR(20))",
            "CREATE INDEX IN ON T(NAME)",
            "INSERT INTO T VALUES (1, 'abc'), (2, 'abd'), (3, 'x%y'), (4, NULL), (5, 'a_c')",
            "DELETE FROM T WHERE NAME LIKE 'ab%'",
            "DELETE FROM T WHERE NAME LIKE 'abc'",
            "DELETE FROM T WHERE NAME LIKE 'a_c'",
            "DELETE FROM T WHERE NOT NAME LIKE 'a%'",
            "DELETE FROM T WHERE NAME LIKE 'x!%y' ESCAPE '!'",
            "DELETE FROM T WHERE NAME LIKE 'a!_c' ESCAPE '!'",
            "UPDATE T SET ID = ID + 10 WHERE NAME LIKE 'a%'",
            "SELECT ID, NAME FROM T ORDER BY ID",
            "DROP TABLE T");
    }

    [JavaOracleFact]
    public void DropTableForms()
    {
        AssertSameAsReference("ps_drop",
            "CREATE TABLE A(ID INT PRIMARY KEY)",
            "CREATE TABLE B(ID INT, AID INT REFERENCES A(ID))",
            "DROP TABLE A",
            "DROP TABLE A CASCADE",
            "DROP TABLE B RESTRICT",
            "DROP TABLE B, A CASCADE CONSTRAINTS",
            "DROP TABLE IF EXISTS NOPE",
            "DROP TABLE NOPE IF EXISTS",
            "DROP TABLE NOPE IGNORE",
            "DROP TABLE NOPE");
    }

    [JavaOracleFact]
    public void AlterColumnIdentityForms()
    {
        AssertSameAsReference("ps_alter_identity",
            "CREATE TABLE T(A INT GENERATED BY DEFAULT AS IDENTITY)",
            "INSERT INTO T DEFAULT VALUES",
            "ALTER TABLE T ALTER COLUMN A DROP IDENTITY",
            "INSERT INTO T VALUES (7)",
            "ALTER TABLE T ALTER COLUMN A SET GENERATED ALWAYS",
            "ALTER TABLE T ALTER COLUMN A RESTART WITH 100",
            "INSERT INTO T DEFAULT VALUES",
            "ALTER TABLE T ALTER COLUMN A SET GENERATED BY DEFAULT",
            "INSERT INTO T DEFAULT VALUES",
            "SELECT A FROM T ORDER BY A",
            "ALTER TABLE NOPE ALTER COLUMN A DROP IDENTITY",
            "ALTER TABLE IF EXISTS NOPE ALTER COLUMN A DROP IDENTITY",
            "ALTER TABLE T ALTER COLUMN NOPE DROP IDENTITY",
            "DROP TABLE T");
    }

    [JavaOracleFact]
    public void DataChangeDeltaTables()
    {
        AssertSameAsReference("ps_delta",
            "CREATE TABLE T(A INT PRIMARY KEY, B INT)",
            "INSERT INTO T VALUES (1, 10), (2, 20), (3, 30)",
            "SELECT * FROM OLD TABLE (UPDATE T SET B = B + 1 WHERE A = 1)",
            "SELECT * FROM FINAL TABLE (UPDATE T SET B = B + 1 WHERE A = 2)",
            "SELECT * FROM OLD TABLE (DELETE FROM T WHERE A = 3)",
            "SELECT * FROM FINAL TABLE (INSERT INTO T VALUES (4, 40))",
            "SELECT A, B FROM T ORDER BY A",
            "DROP TABLE T");
    }
}
