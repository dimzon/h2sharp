    public static TheoryData<string, string> Combos()
    {
        TheoryData<string, string> data = new();
        string[] modes = ["REGULAR", "ORACLE", "MSSQLSERVER", "MYSQL", "MARIADB", "POSTGRESQL",
            "DB2", "DERBY", "LEGACY", "HSQLDB"];
        foreach (string script in Skips.Keys)
        {
            foreach (string mode in modes)
            {
                data.Add(script, mode);
            }
        }

        return data;
    }

    [Theory]
    [MemberData(nameof(Combos))]
    public void EveryStatementEitherAnswersOrFailsWithADatabaseException(string script, string mode)
    {
        _ = ScriptRunner.RunAdaptedInMode(script, mode, Skips[script]);
    }
