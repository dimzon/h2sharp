 * Sprint 203: the parser edges of a query — LIMIT/OFFSET literals, the FOR UPDATE family,
 * `* EXCEPT`, the _ROWID_ pseudo-column, domain VALUE, the DATATYPE spellings, TRUNCATE
 * CONTINUE IDENTITY, synonym comments, and qualified UPDATE targets. Every batch runs on
 * both the port and the reference jar and must answer the same.
 */
using Xunit;

namespace H2Sharp.Tests;

[Collection(OracleCollection.Name)]
public sealed class ParserQueryEdgeTests : ParserCoverageOracleBase
{
    [JavaOracleFact]
    public void LimitAndOffsetLiterals()
    {
        AssertSameAsReference("parser_edge_limit",
            "CREATE TABLE T(ID INT)",
            "INSERT INTO T VALUES (1), (2), (3)",
            "SELECT ID FROM T ORDER BY ID LIMIT 1",
            "SELECT ID FROM T ORDER BY ID OFFSET 2",
            "SELECT ID FROM T ORDER BY ID LIMIT 1 OFFSET 1",
            "SELECT ID FROM T ORDER BY ID LIMIT -1",
            "SELECT ID FROM T ORDER BY ID LIMIT 3000000000",
            "SELECT ID FROM T ORDER BY ID FETCH FIRST 1 ROWS ONLY",
            "DROP TABLE T");
    }

    [JavaOracleFact]
    public void ForUpdateFamily()
    {
        AssertSameAsReference("parser_edge_forupdate",
            "CREATE TABLE T(ID INT PRIMARY KEY, V INT)",
            "INSERT INTO T VALUES (1, 10), (2, 20)",
            "SELECT * FROM T ORDER BY ID FOR UPDATE",
            "SELECT * FROM T ORDER BY ID FOR UPDATE NOWAIT",
            "SELECT * FROM T ORDER BY ID FOR UPDATE WAIT 1.5",
            "SELECT * FROM T ORDER BY ID FOR UPDATE WAIT -1",
            "SELECT * FROM T ORDER BY ID FOR UPDATE WAIT 3000000",
            "SELECT * FROM T ORDER BY ID FOR UPDATE SKIP LOCKED",
            "SELECT * FROM T ORDER BY ID FOR UPDATE OF ID",
            "SELECT * FROM T ORDER BY ID FOR READ ONLY",
            "SELECT * FROM T ORDER BY ID FOR FETCH ONLY",
            "DROP TABLE T");
    }

    [JavaOracleFact]
    public void StarExceptRowIdAndSyntaxErrors()
    {
        AssertSameAsReference("parser_edge_star",
            "CREATE TABLE T(A INT, B INT)",
            "INSERT INTO T VALUES (1, 2)",
            "SELECT * EXCEPT (A) FROM T",
            "SELECT *, * EXCEPT (A) FROM T",
            "SELECT T._ROWID_ FROM T",
            "SELECT FROM T",
            "SELECT 1 IS",
            "DROP TABLE T");
    }

    [JavaOracleFact]
    public void DomainValueAndDatatypeSpellings()
    {
        AssertSameAsReference("parser_edge_domain",
            "CREATE DOMAIN D INT CHECK (VALUE > 0)",
            "CREATE DOMAIN D2 INT CONSTRAINT POS CHECK (VALUE > 0)",
            "CREATE DATATYPE DT INT",
            "CREATE TABLE T(X D, Y D2)",
            "INSERT INTO T VALUES (1, 2)",
            "INSERT INTO T VALUES (-1, 2)",
            "SELECT CAST(5 AS D)",
            "DROP TABLE T",
            "DROP DATATYPE DT",
            "DROP DOMAIN D, D2");
    }

    [JavaOracleFact]
    public void TruncateIdentityAndSynonymComment()
    {
        AssertSameAsReference("parser_edge_truncate",
            "CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY, V INT)",
            "INSERT INTO T(V) VALUES (1)",
            "TRUNCATE TABLE T CONTINUE IDENTITY",
            "INSERT INTO T(V) VALUES (2)",
            "SELECT ID, V FROM T",
            "TRUNCATE TABLE T RESTART IDENTITY",
            "INSERT INTO T(V) VALUES (3)",
            "SELECT ID, V FROM T",
            "CREATE SYNONYM S FOR T",
            "CREATE OR REPLACE SYNONYM S2 FOR T COMMENT 'synonym'",
            "SELECT COUNT(DISTINCT SYNONYM_NAME) FROM INFORMATION_SCHEMA.SYNONYMS "
                + "WHERE SYNONYM_NAME IN ('S', 'S2')",
            "SELECT V FROM S2",
            "DROP SYNONYM S, S2",
            "DROP TABLE T");
    }

    /// <summary>
    /// A bare TRUNCATE restarts the identity in the modes whose flag says so (SQL Server),
    /// and continues it in the regular mode.
    /// </summary>
    [JavaOracleFact]
    public void TruncateRestartsIdentityOnlyInTheModesThatSaySo()
    {
        AssertSameAsReferenceInMode("parser_edge_truncate_mssql", "MSSQLServer",
            "CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY, V INT)",
            "INSERT INTO T(V) VALUES (1)",
            "TRUNCATE TABLE T",
            "INSERT INTO T(V) VALUES (2)",
            "SELECT ID, V FROM T",
            "DROP TABLE T");
    }

    [JavaOracleFact]
    public void QualifiedAndArrayUpdateTargets()
    {
        AssertSameAsReference("parser_edge_update",
            "CREATE TABLE T(A INT ARRAY, B INT)",
            "INSERT INTO T VALUES (ARRAY[1, 2], 3)",
            "UPDATE T SET T.B = 4",
            "UPDATE T SET A[1] = 7",
            "UPDATE T SET T.A[2] = 8",
            "SELECT A[1], A[2], B FROM T",
            "UPDATE T SET OTHER.T.B = 1",
            "UPDATE T SET OTHER.PUBLIC.T.B = 1",
            "UPDATE T SET X.B = 1",
            "DROP TABLE T");
    }

    /// <summary>
    /// UPDATE TOP takes its expression in parentheses; DELETE reads a bare term. The
    /// reference refuses the bare UPDATE form.
    /// </summary>
    [JavaOracleFact]
    public void UpdateTopNeedsParentheses()
    {
        AssertSameAsReferenceInMode("parser_edge_top", "MSSQLServer",
            "CREATE TABLE T(ID INT)",
            "INSERT INTO T VALUES (1), (2), (3)",
            "UPDATE TOP (1) T SET ID = 5",
            "SELECT ID FROM T ORDER BY ID",
            "UPDATE TOP 1 T SET ID = 6",
            "DELETE TOP 1 FROM T",
            "DROP TABLE T");
    }

    /// <summary>
    /// The empty schema part of a column name: `T..A` is refused without the flag, and
    /// `DB..T.A` names the current schema in PostgreSQL mode.
    /// </summary>
    [JavaOracleFact]
    public void CommentOnColumnEmptySchema()
    {
        AssertSameAsReference("parser_edge_comment",
            "CREATE TABLE T(A INT)",
            "COMMENT ON COLUMN T..A IS 'x'");

        AssertSameAsReferenceInMode("parser_edge_comment_pg", "PostgreSQL",
            "CREATE TABLE T(A INT)",
            "COMMENT ON COLUMN parser_edge_comment_pg..T.A IS 'x'",
            "SELECT REMARKS FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'T'",
            "DROP TABLE T");
    }
}
