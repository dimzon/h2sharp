using H2Sharp.Command;
using H2Sharp.Engine;
using H2Sharp.Message;
using H2Sharp.Result;
using H2Sharp.Util;
using Xunit;

namespace H2Sharp.Tests;

public sealed class ParserFormsCoverageTests
{
    private static Statement Model(string sql)
        => Command.Parser.Parse(sql, new TestCastDataProvider(), new BitSet());

    private static (Database Database, SessionLocal Session) Open()
    {
        Database database = new(ConnectionInfo.Memory("parser_forms_" + Guid.NewGuid().ToString("N")));
        SessionLocal session = new(database, "sa");
        return (database, session);
    }

    private static void Exec(SessionLocal session, string sql)
        => session.PrepareCommand(sql).ExecuteUpdate(false);

    [Fact]
    public void LiveAlterColumnFormsAnswer()
    {
        (Database database, SessionLocal session) = Open();
        Exec(session, "CREATE TABLE T(ID INT, NAME VARCHAR)");

        Exec(session, "ALTER TABLE T ALTER COLUMN NAME SET NOT NULL");
        Exec(session, "ALTER TABLE T ALTER COLUMN NAME SET NULL");
        Exec(session, "ALTER TABLE T ALTER COLUMN NAME SET DEFAULT 'x'");
        Exec(session, "ALTER TABLE T ALTER COLUMN NAME DROP DEFAULT");
        Exec(session, "ALTER TABLE T ALTER COLUMN NAME SET DATA TYPE VARCHAR(100)");
        Exec(session, "ALTER TABLE T ALTER COLUMN NAME SET VISIBLE");
        Exec(session, "ALTER TABLE T ALTER COLUMN NAME SET INVISIBLE");
        Exec(session, "ALTER TABLE T ALTER COLUMN NAME RENAME TO NAME2");

        database.Close();
    }

    [Fact]
    public void StatementModelAlterColumnFormsAnswer()
    {
        Assert.IsType<AlterTableStatement>(Model("ALTER TABLE T ALTER COLUMN ID DROP IDENTITY"));
        _ = Model("ALTER TABLE T ALTER COLUMN ID SET GENERATED ALWAYS");
        _ = Model("ALTER TABLE T ALTER COLUMN ID SET GENERATED BY DEFAULT");
        _ = Model("ALTER TABLE T ALTER COLUMN ID SET INCREMENT BY 2");
        _ = Model("ALTER TABLE T ALTER COLUMN ID RESTART WITH 7");
        _ = Model("ALTER TABLE T ALTER COLUMN ID SET CYCLE");

        // The statement model keeps only the identity forms; the other column changes are
        // not part of it and refuse as syntax errors.
        Assert.Throws<H2SharpException>(() => Model("ALTER TABLE T ALTER COLUMN ID SET DATA TYPE INT"));
    }

    [Fact]
    public void LiveCreateTableOptionsAnswer()
    {
        (Database database, SessionLocal session) = Open();
        Exec(session, "CREATE TEMPORARY TABLE T1(ID INT) ON COMMIT DROP");
        Exec(session, "CREATE TEMPORARY TABLE T2(ID INT) ON COMMIT DELETE ROWS");
        Exec(session, "CREATE TABLE T4(ID INT CONSTRAINT PK PRIMARY KEY HASH)");

        _ = Model("CREATE TABLE T5(ID INT CONSTRAINT PK PRIMARY KEY HASH)");

        database.Close();
    }

    [Fact]
    public void LiveJsonLiteralsAnswer()
    {
        (Database database, SessionLocal session) = Open();
        using ResultInterface text = session.PrepareCommand("SELECT JSON '{\"a\":1}'").ExecuteQuery(10, 0, false);
        Assert.True(text.Next());
        using ResultInterface bytes = session.PrepareCommand("SELECT JSON X'7B2261223A317D'").ExecuteQuery(10, 0, false);
        Assert.True(bytes.Next());

        database.Close();
    }

    [Fact]
    public void QueryLimitAndForUpdateAnswer()
    {
        (Database database, SessionLocal session) = Open();
        Exec(session, "CREATE TABLE T(ID INT)");
        Exec(session, "INSERT INTO T VALUES(1)");
        using (ResultInterface limit = session.PrepareCommand("SELECT * FROM T LIMIT 5").ExecuteQuery(10, 0, false))
        {
            Assert.True(limit.Next());
        }

        using (ResultInterface big = session.PrepareCommand("SELECT * FROM T LIMIT 2147483648").ExecuteQuery(10, 0, false))
        {
            Assert.True(big.Next());
        }

        using (ResultInterface forUpdate = session.PrepareCommand("SELECT * FROM T FOR UPDATE OF ID").ExecuteQuery(10, 0, false))
        {
            Assert.True(forUpdate.Next());
        }

        database.Close();
    }

    [Fact]
    public void SchemaSearchPathAnswer()
    {
        (Database database, SessionLocal session) = Open();
        Exec(session, "CREATE SCHEMA S1");
        Exec(session, "CREATE TABLE S1.T(ID INT)");
        Exec(session, "INSERT INTO S1.T VALUES(1)");
        Exec(session, "SET SCHEMA_SEARCH_PATH S1");
        using ResultInterface result = session.PrepareCommand("SELECT * FROM T").ExecuteQuery(10, 0, false);
        Assert.True(result.Next());

        database.Close();
    }

    [Fact]
    public void MySqlDuplicateKeyValuesAnswer()
    {
        // D-029: the mode comes from the connection, not from SET MODE.
        Database database = new(ConnectionInfo.Memory(
            "parser_forms_mysql_" + Guid.NewGuid().ToString("N"), Mode.GetInstance("MySQL")));
        SessionLocal session = new(database, "sa");
        Exec(session, "CREATE TABLE T(ID INT PRIMARY KEY)");
        Exec(session, "INSERT INTO T VALUES(1)");
        Exec(session, "INSERT INTO T VALUES(1) ON DUPLICATE KEY UPDATE ID = VALUES(ID)");

        database.Close();
    }

    [Fact]
    public void QualifiedColumnNamesAnswer()
    {
        (Database database, SessionLocal session) = Open();
        Exec(session, "CREATE TABLE T(ID INT)");
        Exec(session, "INSERT INTO T VALUES(1)");
        using ResultInterface result = session.PrepareCommand("SELECT T.ID FROM T").ExecuteQuery(10, 0, false);
        Assert.True(result.Next());
        Assert.Equal(1, result.CurrentRow()[0]!.GetInt());

        database.Close();
    }
}
