 * What an identity column and a generated column answer, checked against the reference
 * running the same text.
 *
 * The numbers an identity hands out are the point: the first row gets 1, the second 2, and
 * a start value moves the first one. A generated column is computed from the other columns
 * of the same row, so the value of the row is what has to agree.
 */
using System;
using System.Collections.Generic;
using System.Globalization;
using H2Sharp;
using H2Sharp.Command;
using H2Sharp.Engine;
using H2Sharp.Expressions;
using H2Sharp.Result;
using H2Sharp.Tests.Oracle;
using H2Sharp.Values;
using Xunit;

namespace H2Sharp.Tests;

[Collection(OracleCollection.Name)]
public sealed class IdentityOracleTests
{
    /// <summary>
    /// The statements both sides run, and the question asked after them.
    /// </summary>
    private static readonly string[] Statements =
    [
        "CREATE TABLE T(ID BIGINT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR(50))",
        "INSERT INTO T(NAME) VALUES('a')",
        "INSERT INTO T(NAME) VALUES('b')",
        "INSERT INTO T(ID, NAME) VALUES(10, 'c')",
        "INSERT INTO T(NAME) VALUES('d')",
        "SELECT ID, NAME FROM T ORDER BY ID",
    ];

    /// <summary>
    /// The values of the identity columns, the same on both sides.
    /// </summary>
    [JavaOracleFact]
    public void TheIdentityValuesAreTheSameAsTheReference()
    {
        List<string> port = RunPort(Statements);
        List<string> java = RunJava(Statements);
        AssertSame(java, port);
    }

    /// <summary>
    /// The start value of the identity, the same on both sides.
    /// </summary>
    [JavaOracleFact]
    public void TheStartValueIsTheSameAsTheReference()
    {
        List<string> port = RunPort(
        [
            "CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY (START WITH 100), NAME VARCHAR(50))",
            "INSERT INTO T(NAME) VALUES('a')",
            "INSERT INTO T(NAME) VALUES('b')",
            "SELECT ID, NAME FROM T ORDER BY ID",
        ]);
        List<string> java = RunJava(
        [
            "CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY (START WITH 100), NAME VARCHAR(50))",
            "INSERT INTO T(NAME) VALUES('a')",
            "INSERT INTO T(NAME) VALUES('b')",
            "SELECT ID, NAME FROM T ORDER BY ID",
        ]);
        AssertSame(java, port);
    }

    /// <summary>
    /// The value of a generated column, the same on both sides.
    /// </summary>
    [JavaOracleFact]
    public void TheGeneratedValueIsTheSameAsTheReference()
    {
        List<string> port = RunPort(
        [
            "CREATE TABLE T(A INT, B INT, C INT GENERATED ALWAYS AS (A + B))",
            "INSERT INTO T(A, B) VALUES(2, 3)",
            "INSERT INTO T(A, B) VALUES(10, 20)",
            "SELECT A, B, C FROM T ORDER BY A",
        ]);
        List<string> java = RunJava(
        [
            "CREATE TABLE T(A INT, B INT, C INT GENERATED ALWAYS AS (A + B))",
            "INSERT INTO T(A, B) VALUES(2, 3)",
            "INSERT INTO T(A, B) VALUES(10, 20)",
            "SELECT A, B, C FROM T ORDER BY A",
        ]);
        AssertSame(java, port);
    }

    /// <summary>
    /// The identity column of the catalogue, the same on both sides.
    /// </summary>
    [JavaOracleFact]
    public void TheCatalogueSaysTheSameAboutTheIdentity()
    {
        List<string> port = RunPort(
        [
            "CREATE TABLE T(ID BIGINT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR(50))",
            "SELECT IS_IDENTITY, IDENTITY_GENERATION, IDENTITY_START, IDENTITY_INCREMENT "
                + "FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'T' AND COLUMN_NAME = 'ID'",
        ]);
        List<string> java = RunJava(
        [
            "CREATE TABLE T(ID BIGINT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR(50))",
            "SELECT IS_IDENTITY, IDENTITY_GENERATION, IDENTITY_START, IDENTITY_INCREMENT "
                + "FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'T' AND COLUMN_NAME = 'ID'",
        ]);
        AssertSame(java, port);
    }

    /// <summary>
    /// An identity column that is always generated refuses a value, on both sides.
    /// </summary>
    [JavaOracleFact]
    public void AnAlwaysGeneratedIdentityRefusesAValue()
    {
        List<string> port = RunPort(
        [
            "CREATE TABLE T(ID BIGINT GENERATED ALWAYS AS IDENTITY, NAME VARCHAR(50))",
            "INSERT INTO T(ID, NAME) VALUES(7, 'a')",
        ]);
        List<string> java = RunJava(
        [
            "CREATE TABLE T(ID BIGINT GENERATED ALWAYS AS IDENTITY, NAME VARCHAR(50))",
            "INSERT INTO T(ID, NAME) VALUES(7, 'a')",
        ]);
        AssertSame(java, port);
    }

    /// <summary>
    /// Compares the answers of the two sides.
    /// </summary>
    /// <param name="java">the answers of the reference</param>
    /// <param name="port">the answers of the port</param>
    private static void AssertSame(List<string> java, List<string> port)
    {
        Assert.Equal(java.Count, port.Count);
        for (int i = 0; i < java.Count; i++)
        {
            Assert.True(
                java[i] == port[i],
                $"line {i}\n  java:   {java[i]}\n  csharp: {port[i]}");
        }
    }

    /// <summary>
    /// Runs the statements here and writes what the question answered.
    /// </summary>
    /// <param name="statements">the statements</param>
    /// <returns>the lines</returns>
    private static List<string> RunPort(IReadOnlyList<string> statements)
    {
        SessionLocal session = new(
            new Database(new ConnectionInfo("jdbc:h2:mem:identity_oracle")), "sa")
        {
            CastDataProvider = new TestCastDataProvider(),
            CompareMode = CompareMode.GetInstance(null, 0),
        };

        List<string> lines = [];
        foreach (string sql in statements)
        {
            CommandContainer container =
                Assert.IsType<CommandContainer>(session.PrepareCommand(sql));
            try
            {
                if (sql.StartsWith("SELECT", StringComparison.Ordinal))
                {
                    ResultInterface result = container.Query(-1);
                    int visible = result.GetVisibleColumnCount();
                    while (result.Next())
                    {
                        Value?[] row = result.CurrentRow();
                        List<string> cells = [];
                        for (int i = 0; i < visible; i++)
                        {
                            Value? value = row[i];
                            cells.Add(value is null or ValueNull ? "-" : value.GetString() ?? "-");
                        }

                        lines.Add("=" + string.Join(":", cells));
                    }
                }
                else
                {
                    _ = container.ExecuteUpdate(false);
                }
            }
            catch (H2SharpException e)
            {
                lines.Add("=" + e.H2ErrorCode.ToString(CultureInfo.InvariantCulture));
            }
        }

        return lines;
    }

    /// <summary>
    /// Runs the statements on the reference and writes what the question answered.
    /// </summary>
    /// <param name="statements">the statements</param>
    /// <returns>the lines</returns>
    private static List<string> RunJava(IReadOnlyList<string> statements)
        => OracleRunner.Run(
            statements,
            """
            java.sql.Connection conn = java.sql.DriverManager.getConnection("jdbc:h2:mem:identity_oracle");
            java.sql.Statement stat = conn.createStatement();
            for (int i = 0; i < inputs.length; i++) {
              try {
                boolean isQuery = stat.execute(inputs[i]);
                if (isQuery) {
                  java.sql.ResultSet rs = stat.getResultSet();
                  int columns = rs.getMetaData().getColumnCount();
                  while (rs.next()) {
                    StringBuilder line = new StringBuilder("=");
                    for (int c = 1; c <= columns; c++) {
                      if (c > 1) {
                        line.append(':');
                      }
                      String s = rs.getString(c);
                      line.append(rs.wasNull() ? "-" : s);
                    }
                    System.out.println(line);
                  }
                }
              } catch (java.sql.SQLException e) {
                System.out.println("=" + e.getErrorCode());
              }
            }
            conn.close();
            """,
            extraJavaArgs: ["-Duser.language=en"]);
}
