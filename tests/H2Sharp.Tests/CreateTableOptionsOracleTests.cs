using Xunit;

namespace H2Sharp.Tests;

[Collection(OracleCollection.Name)]
public sealed class CreateTableOptionsOracleTests : ParserCoverageOracleBase
{
    [JavaOracleFact]
    public void GeneratedColumnsAndDefaults()
    {
        AssertSameAsReference("cto_gen",
            "CREATE TABLE T(A INT, B INT, C INT AS (A + B), D INT GENERATED ALWAYS AS (A * B))",
            "INSERT INTO T(A, B) VALUES (2, 3)",
            "SELECT C, D FROM T",
            "CREATE TABLE D1(A INT DEFAULT ON NULL 5)",
            "INSERT INTO D1 VALUES (NULL), (1)",
            "SELECT A FROM D1 ORDER BY A",
            "CREATE TABLE D2(A INT DEFAULT 7 DEFAULT ON NULL)",
            "INSERT INTO D2 VALUES (NULL), (2)",
            "SELECT A FROM D2 ORDER BY A",
            "CREATE TABLE U(A INT, B INT DEFAULT 0 ON UPDATE (A + 1))",
            "INSERT INTO U(A) VALUES (1)",
            "UPDATE U SET A = 10",
            "SELECT A, B FROM U",
            "DROP TABLE U",
            "DROP TABLE D2",
            "DROP TABLE D1",
            "DROP TABLE T");
    }

    [JavaOracleFact]
    public void IdentitySpellings()
    {
        AssertSameAsReference("cto_identity",
            "CREATE TABLE I1(A INT GENERATED BY DEFAULT AS IDENTITY)",
            "INSERT INTO I1 DEFAULT VALUES",
            "INSERT INTO I1 DEFAULT VALUES",
            "SELECT A FROM I1 ORDER BY A",
            "CREATE TABLE I2(A INT GENERATED ALWAYS AS IDENTITY (START WITH 5))",
            "INSERT INTO I2 DEFAULT VALUES",
            "INSERT INTO I2 DEFAULT VALUES",
            "SELECT A FROM I2 ORDER BY A",
            "CREATE TABLE I3(A INT GENERATED BY DEFAULT AS 5)",
            "DROP TABLE I2",
            "DROP TABLE I1");
    }

    [JavaOracleFact]
    public void NamedAndUnnamedKeys()
    {
        AssertSameAsReference("cto_keys",
            "CREATE TABLE P(A INT, B INT, CONSTRAINT PK PRIMARY KEY(A, B))",
            "CREATE TABLE C(A INT, B INT, CONSTRAINT FK FOREIGN KEY(A, B) REFERENCES P(A, B))",
            "CREATE TABLE H(A INT PRIMARY KEY HASH, B INT NULL)",
            "INSERT INTO H VALUES (1, 2)",
            "SELECT A, B FROM H",
            "DROP TABLE H",
            "DROP TABLE C",
            "DROP TABLE P");
    }

    [JavaOracleFact]
    public void TemporaryTableOptions()
    {
        AssertSameAsReference("cto_temp",
            "CREATE LOCAL TEMPORARY TABLE T1(A INT) ON COMMIT DROP",
            "CREATE GLOBAL TEMPORARY TABLE T2(A INT) ON COMMIT DELETE ROWS",
            "CREATE LOCAL TEMPORARY TABLE T3(A INT) NOT PERSISTENT",
            "CREATE LOCAL TEMPORARY TABLE T4(A INT) NOT LOGGED TRANSACTIONAL",
            "CREATE MEMORY TABLE M1(A INT) NOT PERSISTENT",
            "CREATE MEMORY TABLE M2(A INT) NOT PERSISTENT",
            "CREATE CACHED TABLE C1(A INT) NOT PERSISTENT",
            "CREATE TABLE C2(A INT) NOT PERSISTENT",
            "CREATE MEMORY TABLE M3(A INT) NOT PERSISTENT TRANSACTIONAL",
            "CREATE CACHED TABLE C3(A INT) TRANSACTIONAL",
            "INSERT INTO T2 VALUES (1)",
            "COMMIT",
            "SELECT COUNT(*) FROM T2",
            "SELECT TABLE_NAME, STORAGE_TYPE, COMMIT_ACTION FROM INFORMATION_SCHEMA.TABLES "
            + "WHERE TABLE_NAME IN ('T1', 'T2', 'T3', 'T4', 'M1', 'M2') ORDER BY TABLE_NAME",
            "DROP TABLE M2",
            "DROP TABLE M1",
            "DROP TABLE T4",
            "DROP TABLE T3",
            "DROP TABLE T2",
            "DROP TABLE T1");
    }
}
