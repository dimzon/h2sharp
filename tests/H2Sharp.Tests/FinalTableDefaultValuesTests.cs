 * Issue #66: FINAL TABLE over INSERT ... DEFAULT VALUES must generate identity/defaults. */
using System;
using System.Collections.Generic;
using System.Data.Common;
using System.Globalization;
using System.Linq;
using H2Sharp.Data;
using H2Sharp.Tests.Oracle;
using Xunit;

namespace H2Sharp.Tests;

[Collection(OracleCollection.Name)]
public sealed class FinalTableDefaultValuesTests
{
    [JavaOracleFact]
    public void FinalTableInsertDefaultValuesReturnsGeneratedIdentityAndDefaults()
    {
        Check([
            "CREATE TABLE \"Direct\" (\"Id\" integer GENERATED BY DEFAULT AS IDENTITY, \"Flag\" boolean NOT NULL DEFAULT TRUE, \"Number\" integer NOT NULL DEFAULT 0, CONSTRAINT \"PK_Direct\" PRIMARY KEY (\"Id\"))",
            "CREATE TABLE \"Final\" (\"Id\" integer GENERATED BY DEFAULT AS IDENTITY, \"Flag\" boolean NOT NULL DEFAULT TRUE, \"Number\" integer NOT NULL DEFAULT 0, CONSTRAINT \"PK_Final\" PRIMARY KEY (\"Id\"))",
            "INSERT INTO \"Direct\" DEFAULT VALUES",
            "SELECT \"Id\", \"Flag\", \"Number\" FROM \"Direct\"",
            "SELECT \"Id\", \"Flag\", \"Number\" FROM FINAL TABLE (INSERT INTO \"Final\" DEFAULT VALUES)",
            "SELECT \"Id\", \"Flag\", \"Number\" FROM FINAL TABLE (INSERT INTO \"Final\" (\"Number\") VALUES (9))",
            "SELECT \"Id\", \"Flag\", \"Number\" FROM \"Final\" ORDER BY \"Id\"",
            "INSERT INTO \"Final\" (\"Flag\") DEFAULT VALUES",
            "INSERT INTO \"Final\" DEFAULT VALUES",
            "SELECT \"Id\", \"Flag\", \"Number\" FROM \"Final\" ORDER BY \"Id\"",
        ], allowErrors: true);
    }

    [JavaOracleFact]
    public void OtherDataChangeDeltaFormsAreUnchanged()
    {
        Check([
            "CREATE TABLE T(ID INT PRIMARY KEY, V INT DEFAULT 5)",
            "INSERT INTO T VALUES(1,10),(2,20)",
            "SELECT ID,V FROM FINAL TABLE (UPDATE T SET V=V+1 WHERE ID=1) ORDER BY ID",
            "SELECT ID,V FROM OLD TABLE (DELETE FROM T WHERE ID=2)",
            "SELECT ID,V FROM T ORDER BY ID",
        ]);
    }

    private static void Check(string[] statements, bool allowErrors = false)
    {
        List<string> port = [];
        using H2Connection connection = new("Data Source=final_defaults_" + Guid.NewGuid().ToString("N") + ";Storage=Memory");
        connection.Open();
        for (int i = 0; i < statements.Length; i++)
        {
            using DbCommand command = connection.CreateCommand();
            command.CommandText = statements[i];
            try
            {
                if (statements[i].StartsWith("SELECT", StringComparison.Ordinal))
                {
                    using DbDataReader reader = command.ExecuteReader();
                    port.Add($"={i}:C:{reader.FieldCount}");
                    while (reader.Read())
                    {
                        List<string> cells = [];
                        for (int c = 0; c < reader.FieldCount; c++)
                            cells.Add(reader.IsDBNull(c) ? "NULL"
                                : reader.GetValue(c) is bool flag ? (flag ? "TRUE" : "FALSE")
                                : Convert.ToString(reader.GetValue(c), CultureInfo.InvariantCulture)!);
                        port.Add($"={i}:R:" + string.Join('|', cells));
                    }
                }
                else port.Add($"={i}:U:{command.ExecuteNonQuery()}");
            }
            catch (H2SharpException e) { port.Add($"={i}:E:{e.H2ErrorCode}"); }
        }
        List<string> java = OracleRunner.Run(statements, """
            try(java.sql.Connection c=java.sql.DriverManager.getConnection("jdbc:h2:mem:final_defaults")) {
              java.sql.Statement s=c.createStatement();
              for(int i=0;i<inputs.length;i++) {
                try {
                  if(!s.execute(inputs[i])) { System.out.println("="+i+":U:"+s.getUpdateCount()); continue; }
                  java.sql.ResultSet r=s.getResultSet(); int count=r.getMetaData().getColumnCount();
                  System.out.println("="+i+":C:"+count);
                  while(r.next()) {
                    StringBuilder b=new StringBuilder("="+i+":R:");
                    for(int col=1;col<=count;col++) { if(col>1)b.append('|'); String v=r.getString(col); b.append(v==null?"NULL":v); }
                    System.out.println(b);
                  }
                } catch(java.sql.SQLException e) { System.out.println("="+i+":E:"+e.getErrorCode()); }
              }
            }
            """, extraJavaArgs: ["-Duser.language=en"]);
        Assert.True(java.SequenceEqual(port), "java:\n" + string.Join("\n", java) + "\nport:\n" + string.Join("\n", port));
        if (!allowErrors) Assert.DoesNotContain(port, line => line.Contains(":E:", StringComparison.Ordinal));
    }
}
