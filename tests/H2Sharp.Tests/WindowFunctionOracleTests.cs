using H2Sharp.Tests.Oracle;
using Xunit;

namespace H2Sharp.Tests;

[Collection(OracleCollection.Name)]
public sealed class WindowFunctionOracleTests
{
    [JavaOracleFact]
    public void Issue42RowNumbersAndRanksMatchJdbc()
    {
        FreshIssuesOracleTests.Compare([
            "CREATE TABLE T(ID INT PRIMARY KEY, G INT, N INT)",
            "INSERT INTO T VALUES (1, 1, 10), (2, 1, 10), (3, 1, NULL), (4, 1, 20), (5, 2, 40), (6, 2, NULL)",
            "SELECT ID, ROW_NUMBER() OVER (ORDER BY ID) FROM T ORDER BY ID",
            "SELECT ID, ROW_NUMBER() OVER (PARTITION BY G ORDER BY N NULLS LAST, ID) FROM T ORDER BY ID",
            "SELECT ID, RANK() OVER (PARTITION BY G ORDER BY N NULLS LAST), DENSE_RANK() OVER (PARTITION BY G ORDER BY N NULLS LAST) FROM T ORDER BY ID",
            "SELECT ID, PERCENT_RANK() OVER (PARTITION BY G ORDER BY N NULLS LAST), CUME_DIST() OVER (PARTITION BY G ORDER BY N NULLS LAST) FROM T ORDER BY ID",
            "SELECT ID, NTILE(3) OVER (ORDER BY ID), NTILE(20) OVER (ORDER BY ID) FROM T ORDER BY ID",
            "SELECT ROW_NUMBER() OVER (), RANK() OVER (ORDER BY 1), DENSE_RANK() OVER (ORDER BY 1), PERCENT_RANK() OVER (), CUME_DIST() OVER ()",
            "SELECT ID, ROW_NUMBER() OVER W FROM T WINDOW W AS (PARTITION BY G ORDER BY ID DESC) ORDER BY ID",
            "SELECT RANK() OVER ()", "SELECT ROW_NUMBER(1) OVER ()",
            "SELECT ROW_NUMBER() OVER (ORDER BY ID ROWS UNBOUNDED PRECEDING) FROM T",
            "SELECT NTILE(0) OVER (ORDER BY ID) FROM T",
            "SELECT ROW_NUMBER() OVER (ORDER BY ID) FROM T WHERE FALSE",
            "SELECT DISTINCT G, DENSE_RANK() OVER (ORDER BY G) FROM T ORDER BY G",
        ]);
    }

    [JavaOracleFact]
    public void LeadLagFrameValuesAndNullOptionsMatchJdbc()
    {
        FreshIssuesOracleTests.Compare([
            "CREATE TABLE T(ID INT PRIMARY KEY, G INT, N INT)",
            "INSERT INTO T VALUES (1, 1, 10), (2, 1, NULL), (3, 1, 30), (4, 1, NULL), (5, 2, 50)",
            "SELECT ID, LEAD(N) OVER (PARTITION BY G ORDER BY ID), LAG(N) OVER (PARTITION BY G ORDER BY ID) FROM T ORDER BY ID",
            "SELECT ID, LEAD(N, 1, -1) IGNORE NULLS OVER (PARTITION BY G ORDER BY ID), LAG(N, 1, -1) IGNORE NULLS OVER (PARTITION BY G ORDER BY ID) FROM T ORDER BY ID",
            "SELECT ID, LEAD(N, 0, -1) OVER (ORDER BY ID), LAG(N, 2, -2) RESPECT NULLS OVER (ORDER BY ID) FROM T ORDER BY ID",
            "SELECT ID, FIRST_VALUE(N) OVER (PARTITION BY G ORDER BY ID), LAST_VALUE(N) OVER (PARTITION BY G ORDER BY ID) FROM T ORDER BY ID",
            "SELECT ID, FIRST_VALUE(N) IGNORE NULLS OVER (ORDER BY ID ROWS BETWEEN 1 PRECEDING AND CURRENT ROW) FROM T ORDER BY ID",
            "SELECT ID, LAST_VALUE(N) IGNORE NULLS OVER (ORDER BY ID ROWS BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING) FROM T ORDER BY ID",
            "SELECT ID, NTH_VALUE(N, 2) OVER (ORDER BY ID ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) FROM T ORDER BY ID",
            "SELECT ID, NTH_VALUE(N, 2) FROM LAST IGNORE NULLS OVER (ORDER BY ID ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) FROM T ORDER BY ID",
            "SELECT ID, FIRST_VALUE(N) OVER (ORDER BY ID ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING EXCLUDE CURRENT ROW) FROM T ORDER BY ID",
            "SELECT NTH_VALUE(N, 0) OVER (ORDER BY ID) FROM T", "SELECT LAG(N, -1) OVER (ORDER BY ID) FROM T",
        ]);
    }

    [JavaOracleFact]
    public void RatioAndGroupedWindowFunctionsMatchJdbc()
    {
        FreshIssuesOracleTests.Compare([
            "CREATE TABLE T(ID INT PRIMARY KEY, G INT, N INT)",
            "INSERT INTO T VALUES (1, 1, 10), (2, 1, 30), (3, 1, NULL), (4, 2, 0), (5, 2, 0)",
            "SELECT ID, RATIO_TO_REPORT(N) OVER (PARTITION BY G) FROM T ORDER BY ID",
            "SELECT RATIO_TO_REPORT(N) OVER (ORDER BY ID) FROM T",
            "SELECT G, SUM(N), ROW_NUMBER() OVER (ORDER BY G) FROM T GROUP BY G ORDER BY G",
            "SELECT G, ROW_NUMBER() OVER (ORDER BY SUM(N) DESC) FROM T GROUP BY G ORDER BY G",
        ]);
    }
}
