using Xunit;

namespace H2Sharp.Tests;

[Collection(OracleCollection.Name)]
public sealed class ParserCoverageDdlOracleTests : ParserCoverageOracleBase
{
    [JavaOracleFact]
    public void TablesIndexesSequencesViews()
    {
        AssertSameAsReference("parser_ddl1",
            "CREATE TABLE A(ID INT PRIMARY KEY, V VARCHAR(20) UNIQUE, C INT CHECK (C > 0))",
            "CREATE TABLE IF NOT EXISTS A(ID INT)",
            "INSERT INTO A VALUES(1,'x',5)",
            "SELECT ID, V, C FROM A",
            "CREATE INDEX IDX_A ON A(V)",
            "CREATE INDEX IF NOT EXISTS IDX_A ON A(V)",
            "SELECT INDEX_NAME FROM INFORMATION_SCHEMA.INDEXES WHERE TABLE_NAME='A' ORDER BY INDEX_NAME",
            "CREATE SEQUENCE SEQ START WITH 1 INCREMENT BY 1 NO CACHE",
            "SELECT NEXT VALUE FOR SEQ",
            "SELECT NEXT VALUE FOR SEQ",
            "SELECT NEXT VALUE FOR SEQ",
            "ALTER TABLE A ADD COLUMN X INT DEFAULT 3",
            "INSERT INTO A(ID,V,C,X) VALUES(2,'y',7,9)",
            "SELECT ID, X FROM A ORDER BY ID",
            "ALTER TABLE A ALTER COLUMN X SET NOT NULL",
            "ALTER TABLE A DROP COLUMN X",
            "SELECT ID FROM A ORDER BY ID",
            "CREATE VIEW V1 AS SELECT ID, C FROM A WHERE C > 0",
            "SELECT * FROM V1 ORDER BY ID",
            "CREATE OR REPLACE VIEW V1 AS SELECT ID FROM A",
            "SELECT * FROM V1 ORDER BY ID",
            "DROP INDEX IDX_A",
            "ALTER SEQUENCE SEQ RESTART WITH 20",
            "SELECT NEXT VALUE FOR SEQ",
            "DROP SEQUENCE SEQ",
            "DROP VIEW V1",
            "DROP TABLE A");
    }

    [JavaOracleFact]
    public void ConstraintsAndRename()
    {
        AssertSameAsReference("parser_ddl2",
            "CREATE TABLE A(ID INT PRIMARY KEY)",
            "INSERT INTO A VALUES(1)",
            "CREATE TABLE B(ID INT, AID INT)",
            "ALTER TABLE B ADD CONSTRAINT PK_B PRIMARY KEY(ID)",
            "ALTER TABLE B ADD CONSTRAINT FK_B FOREIGN KEY(AID) REFERENCES A(ID)",
            "INSERT INTO B VALUES(1,1)",
            "SELECT COUNT(*) FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS WHERE TABLE_NAME='B'",
            "ALTER TABLE B DROP CONSTRAINT FK_B",
            "ALTER TABLE B DROP CONSTRAINT PK_B",
            "ALTER TABLE B RENAME TO B2",
            "ALTER TABLE B2 RENAME COLUMN ID TO ID2",
            "SELECT ID2, AID FROM B2",
            "DROP TABLE B2",
            "DROP TABLE A");
    }

    [JavaOracleFact]
    public void IdentityGeneratedAndCreateAs()
    {
        AssertSameAsReference("parser_ddl3",
            "CREATE TABLE G(ID BIGINT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR(20))",
            "INSERT INTO G(NAME) VALUES('a')",
            "INSERT INTO G(NAME) VALUES('b')",
            "SELECT ID, NAME FROM G ORDER BY ID",
            "CREATE TABLE H(ID INT GENERATED ALWAYS AS IDENTITY START WITH 100, NAME VARCHAR(10))",
            "INSERT INTO H(NAME) VALUES('z')",
            "SELECT ID, NAME FROM H",
            "CREATE TABLE K AS SELECT 1 AS X, 'ok' AS Y",
            "SELECT X, Y FROM K",
            "CREATE TABLE L(ID INT, FULL_NAME VARCHAR(30) GENERATED ALWAYS AS (NAME || '!'))",
            "INSERT INTO L(ID, NAME) VALUES(1,'hi')",
            "SELECT ID, FULL_NAME FROM L");
    }
}
