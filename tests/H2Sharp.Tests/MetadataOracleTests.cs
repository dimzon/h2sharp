        conn.close();
        """;

    [JavaOracleFact]
    public void MetadataMatchesTheReference()
    {
        SessionLocal session = NewSession();
        DatabaseMeta meta = session.GetDatabaseMeta();

        List<string> actual = [];
        Add(actual, "tables", Describe(meta.GetTables(null, "PUBLIC", null, null)));
        Add(actual, "columns", Describe(meta.GetColumns(null, "PUBLIC", null, null)));
        Add(actual, "schemas", Describe(meta.GetSchemas()));
        Add(actual, "catalogs", Describe(meta.GetCatalogs()));
        Add(actual, "tableTypes", Describe(meta.GetTableTypes()));
        Add(actual, "indexes", Describe(meta.GetIndexInfo(null, "PUBLIC", "C", unique: false, approximate: false)));
        Add(actual, "primaryKeys", Describe(meta.GetPrimaryKeys(null, "PUBLIC", "P")));
        Add(actual, "importedKeys", Describe(meta.GetImportedKeys(null, "PUBLIC", "C")));
        Add(actual, "exportedKeys", Describe(meta.GetExportedKeys(null, "PUBLIC", "P")));
        Add(actual, "crossReference", Describe(
            meta.GetCrossReference(null, "PUBLIC", "P", null, "PUBLIC", "C")));
        Add(actual, "procedures", Describe(meta.GetProcedures(null, "PUBLIC", null)));
        Add(actual, "procedureColumns", Describe(meta.GetProcedureColumns(null, "PUBLIC", null, null)));
        Add(actual, "typeInfo", Describe(meta.GetTypeInfo()));
        actual.Add("=keywords");
        actual.Add("=sqlKeywords:" + Hex(meta.GetSQLKeywords()));
        actual.Add("=searchStringEscape:" + Hex(meta.GetSearchStringEscape()));
        Add(actual, "bestRow", Describe(meta.GetBestRowIdentifier(null, "PUBLIC", "P", 2, nullable: true)));
        Add(actual, "pseudoColumns", Describe(meta.GetPseudoColumns(null, "PUBLIC", null, null)));

        List<string> java = OracleRunner.RunWithMembers([], JavaBody, JavaMembers);
        CompareLines(java, actual);
        session.Close();
    }

    private static SessionLocal NewSession()
    {
        SessionLocal session = new(new Database(ConnectionInfo.Memory(DatabaseName)), "sa");
        Execute(session, "CREATE TABLE P(ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NAME VARCHAR(20) DEFAULT 'x', N INT GENERATED ALWAYS AS (ID + 1), AMT NUMERIC(10, 2), PLAIN NUMERIC, F FLOAT(10), R REAL, D DOUBLE)");
        Execute(session, "CREATE TABLE C(ID INT PRIMARY KEY, PID INT, CONSTRAINT FK_C_P FOREIGN KEY(PID) REFERENCES P(ID) ON DELETE CASCADE)");
        Execute(session, "CREATE INDEX IDX_C_PID ON C(PID)");
        Execute(session, "CREATE VIEW V AS SELECT ID FROM P");
        Execute(session, "COMMENT ON TABLE P IS 'parent'");
        Execute(session, "COMMENT ON COLUMN P.NAME IS 'name'");
        return session;
    }

    private static void Execute(SessionLocal session, string sql)
    {
        CommandContainer container = Assert.IsType<CommandContainer>(session.PrepareCommand(sql));
        _ = container.ExecuteUpdate(false);
    }

    private static void Add(List<string> lines, string name, List<string> rows)
    {
        lines.Add("=" + name);
        lines.AddRange(rows);
    }

    private static List<string> Describe(ResultInterface result, params int[] skip)
    {
        List<string> lines = [];
        StringBuilder header = new("=");
        bool first = true;
        for (int i = 0; i < result.GetVisibleColumnCount(); i++)
        {
            if (Array.IndexOf(skip, i) >= 0)
            {
                continue;
            }

            if (!first)
            {
                _ = header.Append('|');
            }

            first = false;
            _ = header.Append(result.GetColumnName(i));
        }

        lines.Add(header.ToString());
        while (result.Next())
        {
            Value?[] row = result.CurrentRow();
            StringBuilder line = new("=");
            first = true;
            for (int i = 0; i < row.Length; i++)
            {
                if (Array.IndexOf(skip, i) >= 0)
                {
                    continue;
                }

                if (!first)
                {
                    _ = line.Append('|');
                }

                first = false;
                Value? value = row[i];
                _ = line.Append(value is null || ReferenceEquals(value, ValueNull.Instance)
                    ? "<null>"
                    : Hex(value.GetString()));
            }

            lines.Add(line.ToString());
        }

        return lines;
    }

    private static string Hex(string? value)
    {
        if (value is null)
        {
            return "<null>";
        }

        StringBuilder builder = new(value.Length * 4);
        foreach (char c in value)
        {
            _ = builder.Append(((int)c).ToString("x4", System.Globalization.CultureInfo.InvariantCulture));
        }

        return builder.ToString();
    }

    private static void CompareLines(List<string> java, List<string> actual)
    {
        Assert.Equal(java.Count, actual.Count);
        for (int i = 0; i < java.Count; i++)
        {
            if (java[i] != actual[i])
            {
                int from = Math.Max(0, i - 3);
                StringBuilder message = new();
                for (int j = from; j <= i; j++)
                {
                    _ = message.Append(j).Append(" java: ").Append(java[j]).AppendLine();
                    _ = message.Append(j).Append(" port: ").Append(actual[j]).AppendLine();
                }

                Assert.Fail(message.ToString());
            }
        }
    }
}
