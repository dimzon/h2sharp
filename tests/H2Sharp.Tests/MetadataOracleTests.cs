{
    private const string DatabaseName = "META_ORACLE";

    private const string JavaSetup = """
        java.sql.Connection conn = java.sql.DriverManager.getConnection("jdbc:h2:mem:META_ORACLE");
        java.sql.Statement stat = conn.createStatement();
        stat.execute("CREATE TABLE P(ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NAME VARCHAR(20) DEFAULT 'x', N INT GENERATED ALWAYS AS (ID + 1), AMT NUMERIC(10, 2), PLAIN NUMERIC, F FLOAT(10), R REAL, D DOUBLE)");
        stat.execute("CREATE TABLE C(ID INT PRIMARY KEY, PID INT, CONSTRAINT FK_C_P FOREIGN KEY(PID) REFERENCES P(ID) ON DELETE CASCADE)");
        stat.execute("CREATE INDEX IDX_C_PID ON C(PID)");
        stat.execute("CREATE VIEW V AS SELECT ID FROM P");
        stat.execute("COMMENT ON TABLE P IS 'parent'");
        stat.execute("COMMENT ON COLUMN P.NAME IS 'name'");
        java.sql.DatabaseMetaData md = conn.getMetaData();
        """;

    private const string JavaMembers = """
        static boolean skipped(int[] skip, int column) {
            for (int value : skip) {
                if (value == column) {
                    return true;
                }
            }
            return false;
        }

        static void print(java.sql.ResultSet rs, int... skip) throws java.sql.SQLException {
            java.sql.ResultSetMetaData m = rs.getMetaData();
            int count = m.getColumnCount();
            StringBuilder header = new StringBuilder("=");
            boolean first = true;
            for (int i = 1; i <= count; i++) {
                if (skipped(skip, i)) {
                    continue;
                }
                if (!first) {
                    header.append('|');
                }
                first = false;
                header.append(m.getColumnLabel(i));
            }
            System.out.println(header);
            while (rs.next()) {
                StringBuilder line = new StringBuilder("=");
                first = true;
                for (int i = 1; i <= count; i++) {
                    if (skipped(skip, i)) {
                        continue;
                    }
                    if (!first) {
                        line.append('|');
                    }
                    first = false;
                    String value = rs.getString(i);
                    line.append(value == null ? "<null>" : hex(value).substring(1));
                }
                System.out.println(line);
            }
        }

        static void section(String name) {
            System.out.println("=" + name);
        }

        static void text(String name, String value) {
            System.out.println("=" + name + ":" + (value == null ? "<null>" : hex(value).substring(1)));
        }
        """;

