 * The engine metadata against the reference, row for row.
 *
 * The reference's default JDBC mode does not query INFORMATION_SCHEMA: JdbcDatabaseMetaData
 * delegates to DatabaseMetaLocal, which walks the catalogue. The port now has the same
 * class, so the oracle compares the port's rows with what the reference's JDBC interface
 * answers for the same schema. DATA_TYPE is skipped where it appears: java.sql.Types and
 * the port's SqlDbType are different vocabularies, and that adaptation is the .NET layer's
 * business, not the metadata algorithm's.
 */
