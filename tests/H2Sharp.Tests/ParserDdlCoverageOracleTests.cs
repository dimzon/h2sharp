using H2Sharp.Tests.Oracle;
using Xunit;

namespace H2Sharp.Tests;

[Collection(OracleCollection.Name)]
public sealed class ParserDdlCoverageOracleTests
{
    [JavaOracleFact]
    public void IdentityFormsMatchJdbc()
    {
        ExplainOracleTests.Check([
            "CREATE TABLE I1(ID INT GENERATED ALWAYS AS IDENTITY, V INT)",
            "INSERT INTO I1(V) VALUES (10), (20)",
            "SELECT ID, V FROM I1 ORDER BY ID",
            "CREATE TABLE I2(ID INT GENERATED BY DEFAULT AS IDENTITY, V INT)",
            "INSERT INTO I2 VALUES (DEFAULT, 1), (5, 2)",
            "SELECT ID, V FROM I2 ORDER BY ID",
            "CREATE TABLE I3(ID INT GENERATED BY DEFAULT AS IDENTITY(START WITH 5 INCREMENT BY 2), V INT)",
            "INSERT INTO I3(V) VALUES (1), (2)",
            "SELECT ID, V FROM I3 ORDER BY ID",
            "CREATE TABLE I4(ID INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, V INT)",
            "INSERT INTO I4(V) VALUES (7)",
            "SELECT ID, V FROM I4",
            "DROP TABLE I1",
            "DROP TABLE I2",
            "DROP TABLE I3",
            "DROP TABLE I4",
        ]);
    }

    [JavaOracleFact]
    public void GeneratedAndDefaultColumnFormsMatchJdbc()
    {
        ExplainOracleTests.Check([
            "CREATE TABLE G1(A INT, B INT GENERATED ALWAYS AS (A + 1))",
            "INSERT INTO G1(A) VALUES (1), (2)",
            "SELECT A, B FROM G1 ORDER BY A",
            "CREATE TABLE G2(A INT DEFAULT 5 ON NULL)",
            "INSERT INTO G2 VALUES (NULL), (7)",
            "SELECT A FROM G2 ORDER BY A",
            "CREATE TABLE G3(A INT NULL, B INT NOT NULL)",
            "INSERT INTO G3 VALUES (NULL, 1)",
            "SELECT A, B FROM G3",
            "CREATE TABLE G4(A TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP)",
            "INSERT INTO G4 DEFAULT VALUES",
            "SELECT COUNT(*) FROM G4 WHERE A IS NOT NULL",
            "DROP TABLE G1",
            "DROP TABLE G2",
            "DROP TABLE G3",
            "DROP TABLE G4",
        ]);
    }

    [JavaOracleFact]
    public void NamedConstraintsMatchJdbc()
    {
        ExplainOracleTests.Check([
            "CREATE TABLE P1(A INT, B INT, CONSTRAINT PK PRIMARY KEY(A))",
            "INSERT INTO P1 VALUES (1, 2)",
            "SELECT A, B FROM P1",
            "SELECT CONSTRAINT_NAME, CONSTRAINT_TYPE FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS "
                + "WHERE TABLE_NAME = 'P1' ORDER BY CONSTRAINT_NAME",
            "CREATE TABLE P2(A INT, B INT, PRIMARY KEY HASH(A))",
            "INSERT INTO P2 VALUES (1, 2)",
            "SELECT A, B FROM P2",
            "CREATE TABLE R1(A INT PRIMARY KEY)",
            "INSERT INTO R1 VALUES (1), (2)",
            "CREATE TABLE R2(A INT, CONSTRAINT FK FOREIGN KEY(A) REFERENCES R1(A) ON DELETE CASCADE)",
            "INSERT INTO R2 VALUES (1), (2)",
            "DELETE FROM R1 WHERE A = 1",
            "SELECT A FROM R2 ORDER BY A",
            "DROP TABLE R2",
            "DROP TABLE R1",
            "DROP TABLE P1",
            "DROP TABLE P2",
        ]);
    }

    [JavaOracleFact]
    public void DataTypeFormsMatchJdbc()
    {
        ExplainOracleTests.Check([
            "CREATE TABLE DT1(A VARCHAR_IGNORECASE(10), B VARCHAR_IGNORECASE, C NUMERIC, D DECIMAL, E DECIMAL(10,2))",
            "CREATE TABLE DT2(A NUMERIC(10))",
            "CREATE TABLE DT3(A NUMERIC(10, 2))",
            "CREATE TABLE DT4(A CHARACTER VARYING(5), B CHAR VARYING(6), C VARCHAR(7))",
            "CREATE TABLE DT5(A INTERVAL DAY, B INTERVAL HOUR TO SECOND, C INTERVAL YEAR TO MONTH)",
            "CREATE TABLE DT6(A NOSUCHTYPE)",
            "CREATE TABLE DT7(A NUMERIC(0))",
            "CREATE TABLE DT8(A NUMERIC(10, 1000))",
            "CREATE DOMAIN DM AS INT",
            "CREATE TABLE DT9(A DM)",
            "CREATE TABLE DT10(A NOSUCHDOMAIN)",
            "CREATE SCHEMA S",
            "CREATE DOMAIN S.D2 AS INT",
            "CREATE TABLE DT11(A S.D2)",
            "DROP TABLE DT1",
            "DROP TABLE DT2",
            "DROP TABLE DT3",
            "DROP TABLE DT4",
            "DROP TABLE DT5",
            "DROP TABLE DT9",
            "DROP TABLE DT11",
            "DROP DOMAIN DM",
            "DROP DOMAIN S.D2",
            "DROP SCHEMA S",
        ]);
    }

    [JavaOracleFact]
    public void AlterTableFormsMatchJdbc()
    {
        ExplainOracleTests.Check([
            "CREATE TABLE AT(A INT, B INT)",
            "ALTER TABLE AT ADD COLUMN C INT AFTER A",
            "ALTER TABLE AT ADD COLUMN D INT FIRST",
            "ALTER TABLE AT ADD COLUMN E INT BEFORE B",
            "ALTER TABLE AT ADD (F INT, G INT)",
            "ALTER TABLE AT ALTER COLUMN A SET DATA TYPE BIGINT",
            "ALTER TABLE AT ALTER COLUMN B SET NOT NULL",
            "ALTER TABLE AT ALTER COLUMN B DROP NOT NULL",
            "ALTER TABLE AT ALTER COLUMN B SET DEFAULT 5",
            "ALTER TABLE AT ALTER COLUMN B DROP DEFAULT",
            "ALTER TABLE AT ALTER COLUMN A SET GENERATED BY DEFAULT AS IDENTITY",
            "ALTER TABLE AT ALTER COLUMN A SET GENERATED ALWAYS",
            "ALTER TABLE AT MODIFY COLUMN B NOT NULL",
            "ALTER TABLE AT MODIFY (B INT)",
            "ALTER TABLE AT MODIFY B BIGINT",
            "ALTER TABLE AT RENAME COLUMN E TO E2",
            "SELECT COLUMN_NAME, DATA_TYPE, IS_NULLABLE FROM INFORMATION_SCHEMA.COLUMNS "
                + "WHERE TABLE_NAME = 'AT' ORDER BY ORDINAL_POSITION",
            "DROP TABLE AT",
        ]);
    }

    [JavaOracleFact]
    public void TemporaryTableOnCommitMatchJdbc()
    {
        ExplainOracleTests.Check([
            "CREATE LOCAL TEMPORARY TABLE TT1(A INT) ON COMMIT DELETE ROWS",
            "INSERT INTO TT1 VALUES (1)",
            "COMMIT",
            "SELECT COUNT(*) FROM TT1",
            "CREATE LOCAL TEMPORARY TABLE TT2(A INT) ON COMMIT DROP",
            "INSERT INTO TT2 VALUES (1)",
            "COMMIT",
            "SELECT COUNT(*) FROM TT2",
        ]);
    }

    [JavaOracleFact]
    public void InsertQuerySourceMatchesJdbc()
    {
        ExplainOracleTests.Check([
            "CREATE TABLE Q(A INT)",
            "INSERT INTO Q (SELECT 1)",
            "INSERT INTO Q (SELECT 2)",
            "SELECT A FROM Q ORDER BY A",
            "DROP TABLE Q",
        ]);
    }

    [JavaOracleFact]
    public void DuplicateKeyQualifiedColumnMatchesJdbc()
    {
        ExplainOracleTests.Check([
            "CREATE TABLE DU(A INT PRIMARY KEY, B INT)",
            "INSERT INTO DU VALUES (1, 1)",
            "INSERT INTO DU VALUES (1, 2) ON DUPLICATE KEY UPDATE DU.B = 2",
            "SELECT A, B FROM DU",
            "INSERT INTO DU VALUES (1, 3) ON DUPLICATE KEY UPDATE OTHER.B = 3",
            "DROP TABLE DU",
        ], urlSuffix: "MODE=MySQL");
    }

    [JavaOracleFact]
    public void MySqlAlterAndIdentityFormsMatchJdbc()
    {
        ExplainOracleTests.Check([
            "CREATE TABLE M1(A INT PRIMARY KEY AUTO_INCREMENT, B INT)",
            "INSERT INTO M1(B) VALUES (1), (2)",
            "SELECT A, B FROM M1 ORDER BY A",
            "ALTER TABLE M1 MODIFY COLUMN B NOT NULL",
            "ALTER TABLE M1 MODIFY (B INT)",
            "ALTER TABLE M1 MODIFY B BIGINT",
            "SELECT COLUMN_NAME, DATA_TYPE FROM INFORMATION_SCHEMA.COLUMNS "
                + "WHERE TABLE_NAME = 'M1' ORDER BY ORDINAL_POSITION",
            "ALTER TABLE M1 ADD COLUMN A2 INT AUTO_INCREMENT",
            "DROP TABLE M1",
        ], urlSuffix: "MODE=MySQL");
    }

    [JavaOracleFact]
    public void InsertSyntaxEdgesMatchJdbc()
    {
        ExplainOracleTests.Check([
            "CREATE TABLE Q2(A INT)",
            "INSERT INTO Q2(A, A) VALUES (1, 2)",
            "CREATE TABLE Q3(A INT GENERATED BY DEFAULT AS (1))",
            "SELECT COUNT(*) FROM Q2",
            "DROP TABLE Q2",
        ]);
    }

    [JavaOracleFact]
    public void SchemaQualifiedDuplicateKeyColumnMatchesJdbc()
    {
        ExplainOracleTests.Check([
            "CREATE SCHEMA S",
            "CREATE TABLE S.DU2(A INT PRIMARY KEY, B INT)",
            "INSERT INTO S.DU2 VALUES (1, 1)",
            "INSERT INTO S.DU2 VALUES (1, 2) ON DUPLICATE KEY UPDATE S.DU2.B = 2",
            "INSERT INTO S.DU2 VALUES (1, 3) ON DUPLICATE KEY UPDATE OTHER.S.DU2.B = 3",
            "SELECT A, B FROM S.DU2",
            "DROP TABLE S.DU2",
            "DROP SCHEMA S",
        ], urlSuffix: "MODE=MySQL");
    }

    [JavaOracleFact]
    public void SchemaMismatchRefusalsMatchJdbc()
    {
        ExplainOracleTests.Check([
            "CREATE SCHEMA S2",
            "CREATE TABLE SM(A INT)",
            "ALTER TABLE SM RENAME CONSTRAINT S2.C TO D",
            "ALTER TABLE SM RENAME TO S2.SM2",
            "ALTER TABLE SM ADD (H INT, H INT)",
            "SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'SM'",
            "DROP TABLE SM",
            "DROP SCHEMA S2",
        ]);
    }

    [JavaOracleFact]
    public void SqlServerIdentityClauseMatchesJdbc()
    {
        ExplainOracleTests.Check([
            "CREATE TABLE MS(A INT IDENTITY, B INT)",
            "INSERT INTO MS(B) VALUES (1), (2)",
            "SELECT A, B FROM MS ORDER BY A",
            "DROP TABLE MS",
        ], urlSuffix: "MODE=MSSQLServer");
    }
}