using Xunit;

namespace H2Sharp.Tests;

[Collection(OracleCollection.Name)]
public sealed class ParserCoverageSeventhOracleTests : ParserCoverageOracleBase
{
    [JavaOracleFact]
    public void AlterDropIdentity()
    {
        AssertSameAsReference("parser_seven1",
            "CREATE TABLE T(ID BIGINT GENERATED BY DEFAULT AS IDENTITY, V VARCHAR(10))",
            "ALTER TABLE T ALTER COLUMN ID DROP IDENTITY",
            "INSERT INTO T(ID, V) VALUES(5, 'x')",
            "SELECT ID, V FROM T",
            "DROP TABLE T");
    }

    [JavaOracleFact]
    public void ThreePartNamesAndCatalogErrors()
    {
        AssertSameAsReference("parser_seven2",
            "CREATE TABLE T(ID INT)",
            "INSERT INTO T VALUES(1)",
            "SELECT * FROM PARSER_SEVEN2.PUBLIC.T",
            "SELECT * FROM NO_SUCH_CAT.PUBLIC.T",
            "SELECT * FROM PARSER_SEVEN2.NO_SCHEMA.T",
            "DROP TABLE T");
    }

    [JavaOracleFact]
    public void WindowClauseAndFetchVariants()
    {
        AssertSameAsReference("parser_seven3",
            "CREATE TABLE P(ID INT, VAL INT)",
            "INSERT INTO P VALUES(1,10),(2,20),(3,30)",
            "SELECT ID, SUM(VAL) OVER w FROM P WINDOW w AS (ORDER BY ID) ORDER BY ID",
            "SELECT ID FROM P ORDER BY ID FETCH NEXT 2 ROWS ONLY",
            "SELECT ID FROM P ORDER BY ID LIMIT 2 + 1",
            "DROP TABLE P");
    }

    [JavaOracleFact]
    public void InlineConstraintsAndDefaults()
    {
        AssertSameAsReference("parser_seven4",
            "CREATE TABLE P(ID INT PRIMARY KEY)",
            "CREATE TABLE C(CID INT PRIMARY KEY, PID INT REFERENCES P(ID) ON DELETE CASCADE,"
            + " CHECK (PID > 0), X INT DEFAULT 1 ON NULL)",
            "INSERT INTO P VALUES(1)",
            "INSERT INTO C(CID, PID, X) VALUES(1, 1, NULL)",
            "SELECT X FROM C",
            "INSERT INTO C(CID, PID) VALUES(2, 1)",
            "SELECT X FROM C WHERE CID=2",
            "DROP TABLE C, P",
            "CREATE TABLE G(A INT, B INT GENERATED ALWAYS AS (A * 2))",
            "INSERT INTO G(A) VALUES(5)",
            "SELECT A, B FROM G",
            "DROP TABLE G");
    }

    [JavaOracleFact]
    public void IndexNullsAndMathFunctions()
    {
        AssertSameAsReference("parser_seven5",
            "CREATE TABLE T(A INT, B INT)",
            "CREATE INDEX IX ON T(A DESC NULLS LAST, B ASC)",
            "SELECT INDEX_NAME FROM INFORMATION_SCHEMA.INDEXES WHERE TABLE_NAME='T'",
            "DROP TABLE T",
            "SELECT SIN(1), COS(1), TAN(1), ASIN(0.5), ACOS(0.5), ATAN(1)",
            "SELECT COT(1), PI(), RADIANS(180)",
            "SELECT CAST(LOG10(1000) AS BIGINT), CAST(EXP(0) AS BIGINT),"
            + " CAST(POWER(3,3) AS BIGINT), CAST(SQRT(9) AS BIGINT)");
    }

    [JavaOracleFact]
    public void InvalidSetValues()
    {
        AssertSameAsReference("parser_seven6",
            "SET LOCK_TIMEOUT -1",
            "SET MAX_MEMORY_ROWS -5",
            "SET WRITE_DELAY -1");
    }
}
