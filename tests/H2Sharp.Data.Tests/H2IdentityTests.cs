 * The identity and the generated columns, seen through ADO.NET.
 *
 * The provider is a thin layer over the engine, so what is asked here is the engine's answer
 * with the provider's spelling: a row that gets its number from the sequence, a column that
 * is computed from the other columns of the same row, and the numbers that come back are
 * the ones the reference gives.
 */
using System;
using System.Data;
using System.Data.Common;
using System.Linq;
using H2Sharp.Data;
using Xunit;

namespace H2Sharp.Data.Tests;

public sealed class H2IdentityTests
{
    [Fact]
    public void TheIdentityNumbersTheRows()
    {
        using H2Connection connection = Open("identity");
        Execute(
            connection,
            "CREATE TABLE T(ID BIGINT GENERATED BY DEFAULT AS IDENTITY, NAME VARCHAR(50))");

        Execute(connection, "INSERT INTO T(NAME) VALUES('a')");
        Execute(connection, "INSERT INTO T(NAME) VALUES('b')");

        // The numbers are 1 and 2: the sequence of the identity column starts at one.
        Assert.Equal(
            [1L, 2L],
            Read<long>(connection, "SELECT ID FROM T ORDER BY ID"));

        // A value may be given as well, when the column is generated by default.
        Execute(connection, "INSERT INTO T(ID, NAME) VALUES(10, 'c')");
        Assert.Equal(
            [1L, 2L, 10L],
            Read<long>(connection, "SELECT ID FROM T ORDER BY ID"));
    }

    [Fact]
    public void TheGeneratedColumnIsComputed()
    {
        using H2Connection connection = Open("generated");
        Execute(connection, "CREATE TABLE T(A INT, B INT, C INT GENERATED ALWAYS AS (A + B))");

        Execute(connection, "INSERT INTO T(A, B) VALUES(2, 3)");
        Execute(connection, "INSERT INTO T(A, B) VALUES(10, 20)");

        // The third column is the sum of the first two, of the row it belongs to.
        Assert.Equal(
            [5, 30],
            Read<int>(connection, "SELECT C FROM T ORDER BY A"));
    }

    [Fact]
    public void TheIdentityRefusesAValueWhenItIsAlwaysGenerated()
    {
        using H2Connection connection = Open("identity_always");
        Execute(connection, "CREATE TABLE T(ID BIGINT GENERATED ALWAYS AS IDENTITY, NAME VARCHAR(50))");

        // The reference refuses this with 90154, and so does the port.
        H2SharpException error = Assert.Throws<H2SharpException>(
            () => Execute(connection, "INSERT INTO T(ID, NAME) VALUES(7, 'a')"));
        Assert.Equal(90154, error.H2ErrorCode);
    }

    /// <summary>
    /// Opens a connection to a database of its own.
    /// </summary>
    /// <param name="name">the name of the database</param>
    /// <returns>the connection</returns>
    private static H2Connection Open(string name)
    {
        H2Connection connection = new($"Data Source=ado_{name};Storage=Memory");
        connection.Open();
        return connection;
    }

    /// <summary>
    /// Runs a statement that answers nothing.
    /// </summary>
    /// <param name="connection">the connection</param>
    /// <param name="sql">the statement</param>
    private static void Execute(H2Connection connection, string sql)
    {
        using DbCommand command = connection.CreateCommand();
        command.CommandText = sql;
        _ = command.ExecuteNonQuery();
    }

    /// <summary>
    /// Reads a column of numbers.
    /// </summary>
    /// <param name="connection">the connection</param>
    /// <param name="sql">the query</param>
    /// <returns>the numbers</returns>
    private static T[] Read<T>(H2Connection connection, string sql)
    {
        using DbCommand command = connection.CreateCommand();
        command.CommandText = sql;
        using DbDataReader reader = command.ExecuteReader();
        System.Collections.Generic.List<T> values = [];
        while (reader.Read())
        {
            values.Add((T)reader.GetValue(0));
        }

        return [.. values];
    }
}
