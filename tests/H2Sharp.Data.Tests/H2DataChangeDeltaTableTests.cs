 * The rows a statement changed, seen through ADO.NET.
 *
 * H2 2.5 has no RETURNING, and a provider that wants the generated key reads it back from
 * the table of the changed rows: FINAL TABLE (INSERT INTO …). The form the providers write
 * has quoted names and a parameter, and this is that form.
 */
using System;
using System.Data;
using System.Data.Common;
using System.Linq;
using H2Sharp.Data;
using Xunit;

namespace H2Sharp.Data.Tests;

public sealed class H2DataChangeDeltaTableTests
{
    [Fact]
    public void TheFinalTableGivesTheGeneratedKey()
    {
        using H2Connection connection = Open("delta");
        Execute(
            connection,
            "CREATE TABLE \"Items\" (\"Id\" integer GENERATED BY DEFAULT AS IDENTITY, \"Name\" varchar(10))");

        // The form the providers write: the key of the row the insert wrote.
        using DbCommand command = connection.CreateCommand();
        command.CommandText = "SELECT \"Id\" FROM FINAL TABLE (INSERT INTO \"Items\" (\"Name\") VALUES (@p0))";
        DbParameter parameter = command.CreateParameter();
        parameter.ParameterName = "@p0";
        parameter.Value = "x";
        command.Parameters.Add(parameter);

        object? id = command.ExecuteScalar();
        Assert.Equal(1, Convert.ToInt32(id, System.Globalization.CultureInfo.InvariantCulture));

        // The row is in the table as well.
        Assert.Equal(
            [1],
            Read<int>(connection, "SELECT \"Id\" FROM \"Items\""));
    }

    [Fact]
    public void TheFinalTableGivesTheRowOfTheDelete()
    {
        using H2Connection connection = Open("delta_delete");
        Execute(
            connection,
            "CREATE TABLE \"Items\" (\"Id\" integer GENERATED BY DEFAULT AS IDENTITY, \"Name\" varchar(10))");
        Execute(connection, "INSERT INTO \"Items\" (\"Name\") VALUES ('a')");
        Execute(connection, "INSERT INTO \"Items\" (\"Name\") VALUES ('b')");

        using DbCommand command = connection.CreateCommand();
        command.CommandText = "SELECT \"Id\", \"Name\" FROM OLD TABLE (DELETE FROM \"Items\" WHERE \"Id\" = 2)";

        using DbDataReader reader = command.ExecuteReader();
        Assert.True(reader.Read());
        Assert.Equal(2, Convert.ToInt32(reader.GetValue(0), System.Globalization.CultureInfo.InvariantCulture));
        Assert.Equal("b", reader.GetString(1));
        Assert.False(reader.Read());
    }

    [Fact]
    public void TheDefaultWithATypedLiteralIsTaken()
    {
        using H2Connection connection = Open("delta_default");

        // The form the providers write: a default value with its type in front of it.
        Execute(
            connection,
            "CREATE TABLE \"Chips\" (\"Id\" integer GENERATED BY DEFAULT AS IDENTITY, "
                + "\"Name\" varchar, \"BestBuyDate\" timestamp NOT NULL DEFAULT TIMESTAMP '2035-09-25T00:00:00')");
        Execute(connection, "INSERT INTO \"Chips\" (\"Name\") VALUES ('a')");

        Assert.Equal(
            [new DateTime(2035, 9, 25, 0, 0, 0, DateTimeKind.Unspecified)],
            Read<DateTime>(connection, "SELECT \"BestBuyDate\" FROM \"Chips\""));
    }

    /// <summary>
    /// Opens a connection to a database of its own.
    /// </summary>
    /// <param name="name">the name of the database</param>
    /// <returns>the connection</returns>
    private static H2Connection Open(string name)
    {
        H2Connection connection = new($"jdbc:h2:mem:ado_{name}");
        connection.Open();
        return connection;
    }

    /// <summary>
    /// Runs a statement that answers nothing.
    /// </summary>
    /// <param name="connection">the connection</param>
    /// <param name="sql">the statement</param>
    private static void Execute(H2Connection connection, string sql)
    {
        using DbCommand command = connection.CreateCommand();
        command.CommandText = sql;
        _ = command.ExecuteNonQuery();
    }

    /// <summary>
    /// Reads a column of numbers.
    /// </summary>
    /// <param name="connection">the connection</param>
    /// <param name="sql">the query</param>
    /// <returns>the numbers</returns>
    private static T[] Read<T>(H2Connection connection, string sql)
    {
        using DbCommand command = connection.CreateCommand();
        command.CommandText = sql;
        using DbDataReader reader = command.ExecuteReader();
        System.Collections.Generic.List<T> values = [];
        while (reader.Read())
        {
            values.Add((T)reader.GetValue(0));
        }

        return [.. values];
    }
}
