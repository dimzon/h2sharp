    }

    /// <summary>
    /// Check if this result set is closed.
    /// </summary>
    /// <returns>true if it is</returns>
    public bool IsClosed()
    {
        return closed;
    }

    /// <inheritdoc/>
    public int GetFetchSize()
    {
        return 0;
    }

    /// <inheritdoc/>
    public void SetFetchSize(int fetchSize)
    {
        // ignore
    }

    /// <summary>
    /// Releases what this result holds, which is its temporary store if it made one.
    /// </summary>
    public void Dispose()
    {
        Close();
        GC.SuppressFinalize(this);
    }

    /// <summary>
    /// The sorted map of the rows that DISTINCT keeps. Ordered by the session, so that two rows
    /// are the same row when SQL says they are.
    /// </summary>
    /// <returns>the map</returns>
    private SortedDictionary<ValueRow, Value?[]> NewDistinctRows()
    {
        SessionLocal current = RequireSession();
        return new SortedDictionary<ValueRow, Value?[]>(new SessionRowComparer(current));
    }

    /// <summary>
    /// The session, which every operation that compares or names a column needs.
    /// </summary>
    /// <returns>the session</returns>
    private SessionLocal RequireSession()
        => session ?? throw new TODOException("LocalResult: this result was created without a session");

    /// <summary>
    /// The temporary store, which exists only after something spilled to it.
    /// </summary>
    /// <returns>the store</returns>
    private ResultExternal RequireExternal()
        => external ?? throw new InvalidOperationException("there is no external result");

    /// <summary>
    /// Orders rows the way the session compares them.
    /// </summary>
    /// <remarks>
    /// The reference hands the session itself to the TreeMap as its comparator, because a row is
    /// a value and the session is what knows how two values compare. It is the same rule here,
    /// wrapped: the comparator cannot be the session itself, so it asks it. Shared with the
    /// group map, which must split rows exactly where DISTINCT merges them.
    /// </remarks>
    internal sealed class SessionRowComparer : IComparer<ValueRow>
    {
        private readonly SessionLocal session;

        internal SessionRowComparer(SessionLocal session)
        {
            this.session = session;
        }

        public int Compare(ValueRow? x, ValueRow? y)
        {
            // No null checks: keys come from ValueRow.Get, which never answers null, and
            // neither map ever stores one. Java forbids null keys by contract; the same
            // rule holds here, without paying for it on every comparison.
            return session.Compare(x!, y!);
        }
    }
}
