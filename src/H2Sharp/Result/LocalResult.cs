 *
 * The result a statement fills on this side. It holds every row of a result set.
 *
 * It is both a result and a target — a statement walks it with Next() and writes into it with
 * AddRow() — and the two halves meet at Done(). That method is where a query stops being filled
 * and starts being an answer: the distinct rows are taken out of the map they were collected in,
 * the rows are sorted if an order was asked for, and only then are OFFSET and LIMIT applied.
 * The order of those three is not a detail, and getting it wrong is silent: applying the limit
 * before the sort truncates the *wrong* rows and every later answer is correct about a wrong
 * set.
 *
 * Two decisions are worth reading before the code.
 *
 * **Rows may live on disk.** When there are more rows than maxMemoryRows the result spills into
 * a temporary store and reads back from it, which is why Reset and Next both ask `external`
 * before they ask the list. That store is not ported yet, so the members that create it refuse;
 * everything else here is real, and a result that fits in memory — which is every result an
 * in-memory database produces in a test — works.
 *
 * **Duplicates go through a sorted map, not a set.** The map is ordered by the session, because
 * two values of different type or scale must be compared the way SQL compares them: 0.0 and 0.00
 * are the same number, and a hash set would have called them two rows. It is also what makes
 * DISTINCT and ORDER BY one piece of work instead of two, and why an IN predicate's value list
 * can be answered by asking whether a value is already in the result.
 */
