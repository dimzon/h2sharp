/// <summary>
/// A local result set contains all row data of a result set. This is the object generated by
/// engine, and it is also used directly by the ResultSet class in the embedded mode. If the
/// result does not fit in memory, it is written to a temporary file.
/// </summary>
public class LocalResult : ResultInterface, ResultTarget
{
    private int maxMemoryRows;

    private readonly SessionLocal? session;

    private int visibleColumnCount;

    private int resultColumnCount;

    private Expression[] expressions;

    private bool forDataChangeDeltaTable;

    private long rowId;

    private long rowCount;

    private List<Value?[]> rows = Utils.NewSmallArrayList<Value?[]>();

    private SortOrder? sort;

    /// <summary>
    /// HashSet cannot be used here, because we need to compare values of different type or scale
    /// properly.
    /// </summary>
    private SortedDictionary<ValueRow, Value?[]>? distinctRows;

    private Value?[]? currentRow;

    private long offset;

    private long limit = -1;

    private bool fetchPercent;

    private SortOrder? withTiesSortOrder;

    private bool limitsWereApplied;

    private ResultExternal? external;

    private bool distinct;

    private int[]? distinctIndexes;

    private bool closed;

    private bool containsLobs;

    private bool? containsNull;

    /// <summary>
    /// Constructs a new local result object for the specified table.
    /// </summary>
    /// <param name="session">the session</param>
    /// <param name="table">the table</param>
    /// <returns>the local result</returns>
    public static LocalResult ForTable(SessionLocal session, Table table)
        => throw new TODOException(
            "LocalResult.forTable: it needs a ColumnResolver, and mapping a column is done through a resolver here; TableFilter is not ported");

    /// <summary>
    /// Construct a local result object.
    /// </summary>
    public LocalResult()
        : this(null)
    {
    }

    private LocalResult(SessionLocal? session)
    {
        this.session = session;
        expressions = [];
    }

    /// <summary>
    /// Construct a local result object.
    /// </summary>
    /// <param name="session">the session</param>
    /// <param name="expressions">the expression array</param>
    /// <param name="visibleColumnCount">the number of visible columns</param>
    /// <param name="resultColumnCount">
    /// the number of columns including visible columns and additional virtual columns for
    /// ORDER BY and DISTINCT ON clauses
    /// </param>
    public LocalResult(
        SessionLocal? session,
        Expression[] expressions,
        int visibleColumnCount,
        int resultColumnCount)
    {
        this.session = session;
        if (session is null)
        {
            maxMemoryRows = int.MaxValue;
        }
        else
        {
            // A persistent, writable database keeps its results bounded; anything else — an
            // in-memory database, a read-only one — keeps all of them, because spilling costs
            // more than it saves when there is nothing to protect.
            Database db = session.GetDatabase();
            if (db.IsPersistent() && !db.IsReadOnly())
            {
                maxMemoryRows = db.GetMaxMemoryRows();
            }
            else
            {
                maxMemoryRows = int.MaxValue;
            }
        }

        this.visibleColumnCount = visibleColumnCount;
        this.resultColumnCount = resultColumnCount;
        rowId = -1;
        this.expressions = expressions;
    }

    /// <inheritdoc/>
    public bool IsLazy() => false;

    /// <summary>
    /// Redefine count of maximum rows holds in memory for the result.
    /// </summary>
    /// <param name="maxValue">Maximum rows count in memory.</param>
    public void SetMaxMemoryRows(int maxValue)
    {
        maxMemoryRows = maxValue;
    }

    /// <summary>
    /// Sets value collection mode for data change delta tables.
    /// </summary>
    public void SetForDataChangeDeltaTable()
    {
        forDataChangeDeltaTable = true;
    }

    /// <summary>
    /// Create a shallow copy of the result set. The data and a temporary table (if there is any)
    /// is not copied.
    /// </summary>
    /// <param name="targetSession">the session of the copy</param>
    /// <returns>the copy if possible, or null if copying is not possible</returns>
    public ResultInterface? CreateShallowCopy(Session targetSession)
    {
        if (external is null && (rows.Count < rowCount))
        {
            return null;
        }

        if (containsLobs)
        {
            return null;
        }

        ResultExternal? e2 = null;
        if (external is not null)
        {
            e2 = external.CreateShallowCopy();
            if (e2 is null)
            {
                return null;
            }
        }

        LocalResult copy = new(targetSession as SessionLocal);
        copy.maxMemoryRows = maxMemoryRows;
        copy.visibleColumnCount = visibleColumnCount;
        copy.resultColumnCount = resultColumnCount;
        copy.expressions = expressions;
        copy.rowId = -1;
        copy.rowCount = rowCount;
        copy.rows = rows;
        copy.sort = sort;
        copy.distinctRows = distinctRows;
        copy.distinct = distinct;
        copy.distinctIndexes = distinctIndexes;
        copy.currentRow = null;
        copy.offset = 0;
        copy.limit = -1;
        copy.external = e2;
        copy.containsNull = containsNull;
        return copy;
    }

    /// <summary>
    /// Sets sort order to be used by this result. When rows are presorted by the query this
    /// method should not be used.
    /// </summary>
    /// <param name="sort">the sort order</param>
    public void SetSortOrder(SortOrder sort)
    {
        this.sort = sort;
    }

    /// <summary>
    /// Remove duplicate rows.
    /// </summary>
    public void SetDistinct()
    {
        System.Diagnostics.Debug.Assert(distinctIndexes is null);
        distinct = true;
        distinctRows = NewDistinctRows();
    }

    /// <summary>
    /// Remove rows with duplicates in columns with specified indexes.
    /// </summary>
    /// <param name="distinctIndexes">distinct indexes</param>
    public void SetDistinct(int[] distinctIndexes)
    {
        System.Diagnostics.Debug.Assert(!distinct);
        this.distinctIndexes = distinctIndexes;
        distinctRows = NewDistinctRows();
    }

    /// <summary>
    /// Configures result to hold value list of the IN predicate.
    /// </summary>
    /// <param name="inPredicateSortTypes">sort order bit masks or an empty array</param>
    public void SetInPredicateValueListResult(int[] inPredicateSortTypes)
    {
        ArgumentNullException.ThrowIfNull(inPredicateSortTypes);
        distinct = true;
        distinctRows = NewDistinctRows();
        if (inPredicateSortTypes.Length != 0)
        {
            SortOrder ofSortTypes = SortOrder.OfSortTypes(RequireSession(), inPredicateSortTypes);
            sort = ofSortTypes;
        }
    }

    /// <summary>
    /// Whether this result is a distinct result.
    /// </summary>
    /// <returns>true if it is</returns>
    private bool IsAnyDistinct()
    {
        return distinct || distinctIndexes is not null;
    }

    /// <summary>
    /// Check if this result set contains the given row.
    /// </summary>
    /// <param name="values">the row</param>
    /// <returns>true if the row exists</returns>
    public bool ContainsDistinct(Value?[] values)
    {
        ArgumentNullException.ThrowIfNull(values);
        System.Diagnostics.Debug.Assert(values.Length == visibleColumnCount);
        if (external is not null)
        {
            return external.Contains(values!);
        }

        if (distinctRows is null)
        {
            SortedDictionary<ValueRow, Value?[]> map = NewDistinctRows();
            foreach (Value?[] row in rows)
            {
                ValueRow array = GetDistinctRow(row);
                map[array] = array.GetList();
            }

            distinctRows = map;
        }

        ValueRow array2 = ValueRow.Get(values);
        return distinctRows.TryGetValue(array2, out _);
    }

    /// <summary>
    /// Check if this result set contains a NULL value. This method may reset this result.
    /// </summary>
    /// <returns>true if there is a NULL value</returns>
    public bool ContainsNull()
    {
        bool? r = containsNull;
        if (r is null)
        {
            bool found = false;
            Reset();
            while (Next())
            {
                Value?[] row = currentRow!;
                for (int i = 0; i < visibleColumnCount; i++)
                {
                    if (row[i]?.ContainsNull() == true)
                    {
                        found = true;
                        goto LoopEnd;
                    }
                }
            }

        LoopEnd:
            Reset();
            containsNull = found;
            return found;
        }

        return r.Value;
    }

    /// <summary>
    /// Remove the row from the result set if it exists.
    /// </summary>
    /// <param name="values">the row</param>
    public void RemoveDistinct(Value?[] values)
    {
        ArgumentNullException.ThrowIfNull(values);
        if (!distinct)
        {
            throw DbException.GetInternalError();
        }

        System.Diagnostics.Debug.Assert(values.Length == visibleColumnCount);
        if (distinctRows is not null)
        {
            _ = distinctRows.Remove(ValueRow.Get(values));
            rowCount = distinctRows.Count;
        }
        else
        {
            rowCount = RequireExternal().RemoveRow(values!);
        }
    }

    /// <inheritdoc/>
    public void Reset()
    {
        rowId = -1;
        currentRow = null;
        external?.Reset();
    }

    /// <summary>
    /// Retrieve the current row.
    /// </summary>
    /// <returns>row</returns>
    public Row CurrentRowForTable()
        => throw new TODOException("LocalResult.currentRowForTable: Database.getRowFactory is not ported");

    /// <inheritdoc/>
    public Value?[] CurrentRow()
    {
        return currentRow!;
    }

    /// <inheritdoc/>
    public bool Next()
    {
        if (!closed && rowId < rowCount)
        {
            rowId++;
            if (rowId < rowCount)
            {
                if (external is not null)
                {
                    currentRow = external.Next();
                }
                else
                {
                    currentRow = rows[(int)rowId];
                }

                return true;
            }

            currentRow = null;
        }

        return false;
    }

    /// <inheritdoc/>
    public long GetRowId()
    {
        return rowId;
    }

    /// <inheritdoc/>
    public bool IsAfterLast()
    {
        return rowId >= rowCount;
    }

    /// <summary>
    /// Gives a lob a lifetime that outlives the statement that read it.
    /// </summary>
    /// <param name="values">the values</param>
    private void CloneLobs(Value?[] values)
    {
        for (int i = 0; i < values.Length; i++)
        {
            if (values[i] is Values.ValueLob v)
            {
                if (forDataChangeDeltaTable)
                {
                    containsLobs = true;
                }
                else
                {
                    Values.ValueLob v2 = v.CopyToResult();
                    if (!ReferenceEquals(v2, v))
                    {
                        containsLobs = true;
                        values[i] = RequireSession().AddTemporaryLob(v2);
                    }
                }
            }
        }
    }

    /// <summary>
    /// Gets the part of a row that decides whether two rows are the same.
    /// </summary>
    /// <param name="values">the row</param>
    /// <returns>the key</returns>
    private ValueRow GetDistinctRow(Value?[] values)
    {
        if (distinctIndexes is not null)
        {
            int cnt = distinctIndexes.Length;
            Value?[] newValues = new Value?[cnt];
            for (int i = 0; i < cnt; i++)
            {
                newValues[i] = values[distinctIndexes[i]];
            }

            values = newValues;
        }
        else if (values.Length > visibleColumnCount)
        {
            Value?[] shortened = new Value?[visibleColumnCount];
            Array.Copy(values, shortened, visibleColumnCount);
            values = shortened;
        }

        return ValueRow.Get(values);
    }

    /// <summary>
    /// Moves the rows into the temporary store.
    /// </summary>
    /// <remarks>
    /// The store itself is not ported: it is an MVStore over a temporary file, and writing a
    /// result to disk needs that file's lifecycle (where it lives, when it is deleted, what
    /// happens when the database dies first). A port that wrote results to a file of its own
    /// choosing would leave files behind on every crash, which is worse than refusing.
    /// </remarks>
    private void CreateExternalResult()
        => throw new TODOException("LocalResult.createExternalResult: MVTempResult is not ported");

    /// <summary>
    /// Add a row for a table.
    /// </summary>
    /// <param name="row">the row to add</param>
    public void AddRowForTable(Row row)
    {
        ArgumentNullException.ThrowIfNull(row);
        int degree = visibleColumnCount;
        Value?[] values = new Value?[degree + 1];
        for (int i = 0; i < degree; i++)
        {
            values[i] = row.GetValue(i);
        }

        values[degree] = ValueBigint.Get(row.GetKey());
        AddRowInternal(values);
    }

    /// <inheritdoc/>
    public void AddRow(params Value?[] values)
    {
        ArgumentNullException.ThrowIfNull(values);
        System.Diagnostics.Debug.Assert(values.Length == resultColumnCount);
        CloneLobs(values);
        AddRowInternal(values);
    }

    /// <summary>
    /// The part of AddRow that decides where a row goes.
    /// </summary>
    /// <remarks>
    /// With DISTINCT the map is both the filter and the storage, and a later row that compares
    /// equal to an earlier one replaces it — that is what ORDER BY with DISTINCT means, and it
    /// only works because the map is ordered rather than hashed.
    /// </remarks>
    /// <param name="values">the row</param>
    private void AddRowInternal(params Value?[] values)
    {
        if (IsAnyDistinct())
        {
            if (distinctRows is not null)
            {
                ValueRow distinctRow = GetDistinctRow(values);
                if (!distinctRows.TryGetValue(distinctRow, out Value?[]? previous)
                    || sort is not null && sort.Compare(previous!, values) > 0)
                {
                    distinctRows[distinctRow] = values;
                }

                rowCount = distinctRows.Count;
                if (rowCount > maxMemoryRows)
                {
                    CreateExternalResult();
                    rowCount = RequireExternal().AddRows(distinctRows.Values);
                    distinctRows = null;
                }
            }
            else
            {
                rowCount = RequireExternal().AddRow(values!);
            }
        }
        else
        {
            rows.Add(values);
            rowCount++;
            if (rows.Count > maxMemoryRows)
            {
                AddRowsToDisk();
            }
        }
    }

    /// <summary>
    /// Writes the rows held in memory to the temporary store.
    /// </summary>
    private void AddRowsToDisk()
    {
        if (external is null)
        {
            CreateExternalResult();
        }

        rowCount = RequireExternal().AddRows(rows);
        rows.Clear();
    }

    /// <inheritdoc/>
    public int GetVisibleColumnCount()
    {
        return visibleColumnCount;
    }

    /// <summary>
    /// This method is called after all rows have been added.
    /// </summary>
    public void Done()
    {
        if (external is not null)
        {
            AddRowsToDisk();
        }
        else
        {
            if (IsAnyDistinct())
            {
                rows = [.. distinctRows!.Values];
            }

            if (sort is not null && limit != 0 && !limitsWereApplied)
            {
                bool withLimit = limit > 0 && withTiesSortOrder is null;
                if (offset > 0 || withLimit)
                {
                    int endExclusive = rows.Count;
                    if (offset < endExclusive)
                    {
                        int fromInclusive = (int)offset;
                        if (withLimit && limit < endExclusive - fromInclusive)
                        {
                            endExclusive = fromInclusive + (int)limit;
                        }

                        sort.Sort(rows, fromInclusive, endExclusive);
                    }
                }
                else
                {
                    sort.Sort(rows);
                }
            }
        }

        ApplyOffsetAndLimit();
        Reset();
    }

    /// <summary>
    /// Drops the rows before the offset and after the limit.
    /// </summary>
    /// <remarks>
    /// The early return is worth reading: when there is nothing to drop, the row count already
    /// says the right thing and copying the list would be pure cost. Everything else trims the
    /// list, and WITH TIES extends it past the limit for as long as the rows keep comparing
    /// equal to the last one kept.
    /// </remarks>
    private void ApplyOffsetAndLimit()
    {
        if (limitsWereApplied)
        {
            return;
        }

        long startOffset = Math.Max(offset, 0);
        long rowLimit = limit;
        if (startOffset == 0 && rowLimit < 0 && !fetchPercent || rowCount == 0)
        {
            return;
        }

        if (fetchPercent)
        {
            if (rowLimit < 0 || rowLimit > 100)
            {
                throw DbException.GetInvalidValueException("FETCH PERCENT", rowLimit);
            }

            // Oracle rounds percent up, do the same for now
            rowLimit = (rowLimit * rowCount + 99) / 100;
        }

        bool clearAll = startOffset >= rowCount || rowLimit == 0;
        if (!clearAll)
        {
            long remaining = rowCount - startOffset;
            rowLimit = rowLimit < 0 ? remaining : Math.Min(remaining, rowLimit);
            if (startOffset == 0 && remaining <= rowLimit)
            {
                return;
            }
        }
        else
        {
            rowLimit = 0;
        }

        distinctRows = null;
        rowCount = rowLimit;
        if (external is null)
        {
            if (clearAll)
            {
                rows.Clear();
                return;
            }

            int to = (int)(startOffset + rowLimit);
            if (withTiesSortOrder is not null)
            {
                Value?[] expected = rows[to - 1];
                while (to < rows.Count && withTiesSortOrder.Compare(expected, rows[to]) == 0)
                {
                    to++;
                    rowCount++;
                }
            }

            if (startOffset != 0 || to != rows.Count)
            {
                // GetRange already hands back a fresh list; wrapping it copies every row twice.
                rows = rows.GetRange((int)startOffset, to - (int)startOffset);
            }
        }
        else
        {
            if (clearAll)
            {
                external.Close();
                external = null;
                return;
            }

            TrimExternal(startOffset, rowLimit);
        }
    }

    /// <summary>
    /// Trims the rows on disk, reading back only the ones that are kept.
    /// </summary>
    /// <param name="startOffset">the offset</param>
    /// <param name="rowLimit">the limit</param>
    private void TrimExternal(long startOffset, long rowLimit)
    {
        ResultExternal temp = RequireExternal();
        external = null;
        temp.Reset();
        while (--startOffset >= 0)
        {
            _ = temp.Next();
        }

        Value?[]? row = null;
        while (--rowLimit >= 0)
        {
            row = temp.Next();
            rows.Add(row!);
            if (rows.Count > maxMemoryRows)
            {
                AddRowsToDisk();
            }
        }

        if (withTiesSortOrder is not null && row is not null)
        {
            Value?[] expected = row;
            while ((row = temp.Next()) is not null && withTiesSortOrder.Compare(expected, row) == 0)
            {
                rows.Add(row);
                rowCount++;
                if (rows.Count > maxMemoryRows)
                {
                    AddRowsToDisk();
                }
            }
        }

        if (external is not null)
        {
            AddRowsToDisk();
        }

        temp.Close();
    }

    /// <inheritdoc/>
    public long GetRowCount()
    {
        return rowCount;
    }

    /// <inheritdoc/>
    public void LimitsWereApplied()
    {
        limitsWereApplied = true;
    }

    /// <inheritdoc/>
    public bool HasNext()
    {
        return !closed && rowId < rowCount - 1;
    }

    /// <summary>
    /// Set the number of rows that this result will return at the maximum.
    /// </summary>
    /// <param name="limit">the limit (-1 means no limit, 0 means no rows)</param>
    public void SetLimit(long limit)
    {
        this.limit = limit;
    }

    /// <summary>
    /// Sets whether limit expression specifies percentage of rows.
    /// </summary>
    /// <param name="fetchPercent">whether the limit is a percentage</param>
    public void SetFetchPercent(bool fetchPercent)
    {
        this.fetchPercent = fetchPercent;
    }

    /// <summary>
    /// Enables inclusion of tied rows to result and sets the sort order for tied rows. The
    /// specified sort order must be the same as sort order if sort order was set. Passed value
    /// will be used if sort order was not set that is possible when rows are presorted.
    /// </summary>
    /// <param name="withTiesSortOrder">the sort order for tied rows</param>
    public void SetWithTies(SortOrder withTiesSortOrder)
    {
        System.Diagnostics.Debug.Assert(sort is null || sort == withTiesSortOrder);
        this.withTiesSortOrder = withTiesSortOrder;
    }

    /// <inheritdoc/>
    public bool NeedToClose()
    {
        return external is not null;
    }

    /// <inheritdoc/>
    public void Close()
    {
        if (external is not null)
        {
            external.Close();
            external = null;
            closed = true;
        }
    }

