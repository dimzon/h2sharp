 * A unique constraint. This object is always backed by a unique index.
 *
 * The pairing of constraint and index is what keeps the two names apart: the constraint carries
 * the name the user wrote — or CONSTRAINT_5 when they wrote none — while the index keeps its own
 * PRIMARY_KEY_ name, and the constraint prints the index after INDEX so a dump recreates the
 * same pair. The owner flag records which side created the other: an index this constraint owns
 * goes when the constraint goes, and one it merely uses is left for whoever owns it.
 *
 * The constraint adds no check of its own. Uniqueness is the index's job, and a second row that
 * the index refuses already fails before any constraint could look at it; a checkRow here would
 * be a second answer to a question the index has answered.
 */
using System.Collections.Generic;
using H2Sharp.Engine;
using H2Sharp.Result;
using H2Sharp.Schemas;
using H2Sharp.Tables;
using H2Sharp.Util;
using Index = H2Sharp.Indexes.Index;

namespace H2Sharp.Constraints;

/// <summary>
/// A unique constraint. This object is always backed by a unique index.
/// </summary>
public class ConstraintUnique : Constraint
{
    private Index? index;

    private bool indexOwner;

    private IndexColumn[]? columns;

    private readonly bool primaryKey;

    private readonly NullsDistinct? nullsDistinct;

    /// <summary>
    /// Creates the constraint.
    /// </summary>
    /// <param name="schema">constraint belongs to</param>
    /// <param name="id">of the constraint</param>
    /// <param name="name">of the constraint</param>
    /// <param name="table">constraint belongs to</param>
    /// <param name="primaryKey">true if primary key constraint</param>
    /// <param name="indexColumns">used by this constraint</param>
    /// <param name="index">the index</param>
    /// <param name="indexOwner">true if the index is generated by the system and belongs to this constraint</param>
    /// <param name="nullsDistinct">NULL handling mode</param>
    public ConstraintUnique(
        Schema schema,
        int id,
        string name,
        Table table,
        bool primaryKey,
        IndexColumn[] indexColumns,
        Index index,
        bool indexOwner,
        NullsDistinct? nullsDistinct)
        : base(schema, id, name, table)
    {
        this.primaryKey = primaryKey;
        columns = indexColumns;
        this.index = index;
        this.indexOwner = indexOwner;
        this.nullsDistinct = nullsDistinct;
    }

    /// <inheritdoc/>
    public override Type GetConstraintType()
    {
        return primaryKey ? Type.PRIMARY_KEY : Type.UNIQUE;
    }

    /// <inheritdoc/>
    public override string GetCreateSql()
    {
        return GetCreateSqlForCopy(table, GetSql(HasSql.DefaultSqlFlags));
    }

    /// <inheritdoc/>
    public override string GetCreateSqlWithoutIndexes()
    {
        return GetCreateSqlForCopy(table, GetSql(HasSql.DefaultSqlFlags), internalIndex: false);
    }

    private string GetCreateSqlForCopy(Table forTable, string quotedName)
    {
        return GetCreateSqlForCopy(forTable, quotedName, internalIndex: true);
    }

    /// <summary>
    /// Constructs the SQL that recreates this constraint on the given table.
    /// </summary>
    /// <remarks>
    /// The INDEX clause is printed only when the index belongs to this constraint and the table
    /// is the same one: a copy onto another table cannot reuse the index, and a dump must not
    /// try. The NULLS DISTINCT words are the unique constraint's, not the primary key's — SQL
    /// has no NULLs rule on a primary key, and printing one would be a syntax error.
    /// </remarks>
    /// <param name="forTable">the table the copy is for</param>
    /// <param name="quotedName">the quoted name of the constraint</param>
    /// <param name="internalIndex">whether to print the index clause</param>
    /// <returns>the SQL statement</returns>
    private string GetCreateSqlForCopy(Table forTable, string quotedName, bool internalIndex)
    {
        System.Text.StringBuilder builder = new("ALTER TABLE ");
        _ = forTable.GetSql(builder, HasSql.DefaultSqlFlags).Append(" ADD CONSTRAINT ");
        _ = builder.Append(quotedName);
        if (comment is not null)
        {
            _ = builder.Append(" COMMENT ");
            _ = StringUtils.QuoteStringSql(builder, comment);
        }

        _ = builder.Append(' ').Append(ConstraintTypeRules.GetSqlName(GetConstraintType()));
        if (!primaryKey)
        {
            _ = NullsDistinctSql.GetSql(builder.Append(' '), nullsDistinct!.Value, HasSql.DefaultSqlFlags).Append(' ');
        }

        _ = IndexColumn.WriteColumns(builder.Append('('), columns!, 0, columns!.Length, HasSql.DefaultSqlFlags).Append(')');
        if (internalIndex && indexOwner && ReferenceEquals(forTable, table))
        {
            _ = builder.Append(" INDEX ");
            _ = index!.GetSql(builder, HasSql.DefaultSqlFlags);
        }

        return builder.ToString();
    }

    /// <summary>
    /// Gets the columns this constraint covers.
    /// </summary>
    /// <returns>the columns</returns>
    public IndexColumn[] GetColumns()
    {
        return columns!;
    }

    /// <inheritdoc/>
    /// <remarks>
    /// The referential constraints that point at this unique one go first: a foreign key cannot
    /// outlive the key it refers to, and the reference expresses that by removing the dependent
    /// constraints before its own index. The meta-table write between them is deferred with the
    /// meta table.
    /// </remarks>
    public override void RemoveChildrenAndResources(SessionLocal session)
    {
        List<Constraint> constraints = [];
        foreach (Constraint c in table.GetConstraints())
        {
            if (ReferenceEquals(c.GetReferencedConstraint(), this))
            {
                constraints.Add(c);
            }
        }

        foreach (Constraint c in constraints)
        {
            database!.RemoveSchemaObject(session, c);
        }

        table.RemoveConstraint(this);
        if (indexOwner)
        {
            table.RemoveIndexOrTransferOwnership(session, index!);
        }

        index = null;
        columns = null;
        table = null!;
        Invalidate();
    }

    /// <inheritdoc/>
    /// <remarks>Unique index check is enough.</remarks>
    public override void CheckRow(SessionLocal session, Table t, Row oldRow, Row newRow)
    {
        _ = session;
        _ = t;
        _ = oldRow;
        _ = newRow;
    }

    /// <inheritdoc/>
    public override bool UsesIndex(Index index)
    {
        return ReferenceEquals(index, this.index);
    }

    /// <inheritdoc/>
    public override void SetIndexOwner(Index index)
    {
        indexOwner = true;
    }

    /// <inheritdoc/>
    public override HashSet<Column> GetReferencedColumns(Table table)
    {
        HashSet<Column> result = [];
        foreach (IndexColumn c in columns!)
        {
            _ = result.Add(c.GetColumn());
        }

        return result;
    }

    /// <inheritdoc/>
    public override bool IsBefore()
    {
        return true;
    }

    /// <inheritdoc/>
    /// <remarks>No need to check: when creating the unique index any problems are found.</remarks>
    public override void CheckExistingData(SessionLocal session)
    {
        _ = session;
    }

    /// <inheritdoc/>
    public override Index? GetIndex()
    {
        return index;
    }

    /// <inheritdoc/>
    public override void Rebuild()
    {
    }

    /// <summary>
    /// Whether the values are distinct when they contain NULL.
    /// </summary>
    /// <returns>whether nulls are distinct</returns>
    public NullsDistinct? GetNullsDistinct()
    {
        return nullsDistinct;
    }
}
